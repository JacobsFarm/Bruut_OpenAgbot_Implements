"""Animation: the Bruut OpenAgbot kills the weeds in a paved path with hot foam.

The robot drives at the dose speed (0.19 m/s: the boiler heats 6.8 l/min, 0.4 l/m2 over 1.5 m). The hood is shown
see-through. The foam bar lays a white layer of hot foam; a weed under the foam turns orange while it heats and black
when it has had the lethal time (2 s above ~60 C). The water and gas used are counted. Rates from hfw_field / hfw_calc.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot (via build_flw),
weeder from build_hfw, the path, the weeds and the foam.

Use in FreeCAD:
    import animate_hfw
    animate_hfw.build()                              # build the document
    animate_hfw.play()                               # play live, animate_hfw.stop()
    animate_hfw.summary()                            # key figures of the run
    animate_hfw.render_all(r"C:\\temp\\hfw_frames")
    import make_gif_hfw; make_gif_hfw.main(r"C:\\temp\\hfw_frames", r"previews\\animation_hot_foam.gif")
"""
import json
import math
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import hfw_params as P
import hfw_parts as G
import hfw_field as F
import build_hfw

DOC_NAME = "Hot_foam_weeder_on_robot_animation"
FPS = 2                         # frames per second of real time; the GIF plays at 12 fps = 6 x speed
COLOR = {"path": (0.62, 0.60, 0.56), "weed": (0.25, 0.55, 0.15), "hot": (0.95, 0.55, 0.10),
         "dead": (0.15, 0.12, 0.10), "foam": (0.97, 0.97, 0.95)}
SEE_THROUGH = ("hood_skin", "blanket", "top_cover", "front_shield")
MOVING = ("Hood", "Upper_arms", "Lower_arms")

_timer = None
_play = {}


def prepare(fps=FPS):
    ws = F.weeds()
    t_end = F.drive_time() + F.HOLD_END
    n = int(math.ceil(t_end * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        f = F.frame_state(t, ws)
        f["spin"] = (f["y"] - F.Y_START) / (P.robot_tire_d / 2.0)
        frames.append(f)
    return frames


def build():
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Hot foam weeder on robot - animation"
    doc.Comment = "Generated by animate_hfw.py. Robot from agbot design, weeder from build_hfw."
    robot = build_hfw.build_robot(doc)
    build_hfw.build_into(doc, robot)
    build_hfw.set_robot_visible(True, doc)
    for n in SEE_THROUGH:
        doc.getObject(n).ViewObject.Transparency = 80
    path = doc.addObject("Part::Feature", "anim_path")
    path.Shape = G.path_strip(*F.PATH_Y)
    path.ViewObject.ShapeColor = COLOR["path"]
    for name, color, transp in (("anim_weeds", "weed", 0), ("anim_hot", "hot", 0), ("anim_dead", "dead", 0),
                                ("anim_foam", "foam", 20)):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
        o.ViewObject.Transparency = transp
    doc.recompute()
    return doc


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def apply_frame(doc, f, weeds=None):
    weeds = weeds or F.weeds()
    doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    alive, hot, dead = [], [], []
    for (x, y, s), st in zip(weeds, f["weeds"]):
        if st["dead"]:
            dead.append(G.weed_dead(x, y, s))
        elif st["foamed"]:
            hot.append(G.weed(x, y, s))
        else:
            alive.append(G.weed(x, y, s))
    doc.getObject("anim_weeds").Shape = _compound(alive)
    doc.getObject("anim_hot").Shape = _compound(hot)
    doc.getObject("anim_dead").Shape = _compound(dead)
    y0, y1 = f["foam"]
    hw = P.W.work_w / 2.0
    doc.getObject("anim_foam").Shape = G.foam(-hw, hw, y0, y1) if y1 - y0 > 5.0 else Part.Shape()


CAM_A = ((-2600.0, -3000.0, 2000.0), (0.0, -900.0, 150.0))     # eye and target relative to the robot centre


def track_camera(f, fov=40.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(40000.0)


def meta(f):
    w = f["weeds"]
    state = "done" if f["t"] >= F.drive_time() else ("foaming" if f["on"] else "start")
    return {"t": round(f["t"], 1), "state": state, "v": round(f["v"], 0), "n": len(w),
            "foamed": sum(1 for s in w if s["foamed"]), "dead": sum(1 for s in w if s["dead"]),
            "m2": round(f["m2"], 2), "water_l": round(f["water_l"], 2), "gas_g": round(f["gas_g"], 1)}


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    weeds = F.weeds()
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i], weeds)
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=3.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    weeds = F.weeds()
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f, weeds)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))
