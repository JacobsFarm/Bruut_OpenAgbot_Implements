"""Model of the biostimulant sprayer on the Bruut OpenAgbot (standard robot).

Tank, plumbing and the 3.75 m folding boom are the spot sprayer's groups (build_ssp, imported); the mount is the spot
sprayer's with longer control-box bolts on the right; new are the weather mast and the aerator.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_bss
    build_bss.build()                              # saves FCStd and STEP (wings out)
    build_bss.set_fold(left=0, right=90)           # fold angle of the wings (0 = working, 90 = up)
    build_bss.check_interference()                 # overlap in the current pose (must be empty)
    build_bss.check_holes()                        # bolts in their holes (must be empty)
    build_bss.check_fit()                          # overlap over the whole fold, and the mast (must be empty)
    build_bss.mass_properties()
    build_bss.render_all()                         # all images in previews/
"""
import os

import FreeCAD as App
import Part

import bss_params as P
import bss_parts as G
import ssp_parts as SG
import build_ssp as BS

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Biostimulant_Sprayer"
SAVE_BASE = os.path.join(FOLDER, "Biostimulant_Sprayer")
ROOT = "Biostimulant_sprayer"

COLOR = dict(BS.COLOR)
COLOR.update({"air": (0.30, 0.65, 0.90), "sensor": (0.96, 0.96, 0.95)})


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BS.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_mount(doc, parent):
    grp = BS.new_part(doc, parent, "Mount", "rear_subframe_hangers_control_box_from_spot_sprayer")
    add_shape(doc, grp, "sub_plate", "sub_plate_10mm_under_rear_beams", SG.sub_plate(), "frame")
    add_shape(doc, grp, "hangers", "boom_hangers_webs_and_clamp_plates_8mm", SG.hangers(), "frame")
    add_shape(doc, grp, "sub_bolts", "sub_plate_bolts_8xM10", SG.sub_bolts(), "zinc")
    add_shape(doc, grp, "boom_bolts", "boom_clamp_bolts_4xM10", SG.boom_bolts(), "zinc")
    add_shape(doc, grp, "box_base", "control_box_base_plate_and_rails", SG.box_base(), "galv")
    add_shape(doc, grp, "box_bolts", "control_box_bolts_4xM10_right_ones_through_mast_foot", G.box_bolts(), "zinc")
    add_shape(doc, grp, "control_box", "control_box_IP66_logger_GNSS_LTE", SG.control_box(), "box")
    return grp


def build_weather(doc, parent):
    grp = BS.new_part(doc, parent, "Weather_mast", "weather_mast_on_rear_beams")
    add_shape(doc, grp, "mast_foot", "mast_foot_plate_6mm", G.mast_foot(), "frame")
    add_shape(doc, grp, "mast_tube", "mast_tube_30x30x2_cap", G.mast_tube(), "frame")
    add_shape(doc, grp, "mast_braces", "mast_braces_D16", G.braces(), "frame")
    add_shape(doc, grp, "weather_sensor", "weather_sensor_wind_T_RH_rain", G.weather_sensor(), "sensor")
    add_shape(doc, grp, "sensor_cable", "sensor_cable", G.sensor_cable(), "plastic")
    return grp


def build_aerator(doc, parent):
    grp = BS.new_part(doc, parent, "Aerator", "aerator_air_pump_diffuser")
    add_shape(doc, grp, "air_pump", "air_pump_12V_30lpm_on_strap", G.air_pump(), "pump")
    add_shape(doc, grp, "air_bulkhead", "air_bulkhead_tank_top", G.air_bulkhead(), "plastic")
    add_shape(doc, grp, "air_hose", "air_hose_10mm", G.air_hose(), "air")
    add_shape(doc, grp, "diffuser", "diffuser_ring_stainless_D300", G.diffuser(), "stainless")
    return grp


def build_into(doc, parent=None, left=0.0, right=0.0):
    pl = BS.pose_placements(left, right)
    root = BS.new_part(doc, parent, ROOT, "biostimulant_sprayer_3750")
    BS.build_tank(doc, root)
    build_mount(doc, root)
    BS.build_plumbing(doc, root)
    BS.build_boom(doc, root, pl)
    build_weather(doc, root)
    build_aerator(doc, root)
    return root


def build(left=0.0, right=0.0, save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Biostimulant sprayer 3750"
    doc.Comment = ("Generated by build_bss.py from bss_params.py (tank, plumbing, boom and mount from spotspray unit/boom). "
                   "Robot coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BS.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, left, right)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible           # the robot keeps its own GNSS antenna


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = BS.global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


def set_fold(left=0.0, right=0.0, doc=None):
    BS.set_fold(left, right, active_doc(doc))


# Pairs joined by design. The spot sprayer's own check skipped nothing: its bolts, pins and hoses have clearance holes,
# so only the new joints are listed here.
JOINTS = {("box_bolts", "mast_foot"), ("box_bolts", "box_base"), ("mast_braces", "mast_tube"),
          ("mast_braces", "mast_foot"), ("mast_tube", "mast_foot"), ("weather_sensor", "mast_tube"),
          ("sensor_cable", "mast_foot"), ("air_bulkhead", "tank_shell"), ("air_hose", "air_bulkhead"),
          ("air_hose", "air_pump"), ("diffuser", "air_bulkhead"), ("diffuser", "tank_shell"),
          ("air_pump", "straps")}


def _joint(a, b):
    return (a, b) in JOINTS or (b, a) in JOINTS


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, BS.global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, BS.global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return BS._overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """The long box bolts must pass the mast foot, the base plate and the beam through holes."""
    doc = active_doc(doc)
    b = BS.global_shape(doc.getObject("box_bolts"))
    out = {}
    for n in ["mast_foot", "box_base"] + [o.Name for o in robot_objects(doc) if o.Name.startswith("lower_beam")]:
        s = BS.global_shape(doc.getObject(n))
        if s.BoundBox.intersect(b.BoundBox):
            v = s.common(b).Volume
            if v > tol:
                out[n] = round(v, 1)
    return out


def check_fit(doc=None, tol=1.0, step=15.0):
    """Wings over the whole fold against the mast, the aerator and the robot (both wings at once)."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Boom")
    names = {o.Name for o in moving} - {o.Name for o in objects_of(doc, "Centre_section")}
    mv_objs = [o for o in moving if o.Name in names]
    fixed = [(o, BS.global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    out = {}
    n = int(P.S.fold_up // step)
    for phi in [i * step for i in range(n + 1)] + [P.S.fold_stop]:
        set_fold(phi, phi, doc)
        mv = [(o, BS.global_shape(o)) for o in mv_objs]
        hits = BS._overlaps([(a, c) for a in mv for c in fixed if not _joint(a[0].Name, c[0].Name)], tol)
        if hits:
            out["phi_%g" % phi] = hits
    set_fold(0.0, 0.0, doc)
    return out


DENSITY = {"diffuser": 8.0e-6, "air_hose": 1.2e-6, "sensor_cable": 1.5e-6, "air_bulkhead": 1.2e-6}
MASS_FIXED = {"weather_sensor": 0.7, "air_pump": 1.4}


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity, tank empty: the spot sprayer's masses for its parts, the new parts here."""
    doc = active_doc(doc)
    from FreeCAD import Vector as V
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        if o.Name in MASS_FIXED:
            mo, co = MASS_FIXED[o.Name], BS.global_shape(o).BoundBox.Center
        elif o.Name in DENSITY:
            s = BS.global_shape(o)
            mo, co = s.Volume * DENSITY[o.Name], s.BoundBox.Center
        else:
            mo, co = BS._mass_cg(o)
        m += mo
        c += co * mo
    c = c * (1.0 / m)
    return {"total_kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = BS.global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BS.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BS.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    """Standard images in previews/, then build and save (FCStd + STEP, robot hidden)."""
    out = []
    doc = build(save=False, show_robot=True, step=False)
    BS.add_floor(doc)
    out.append(save_view("1_work_iso_on_robot.png", (1.0, 1.2, -0.75), target=(0, -250, 600), height=3600))
    out.append(save_view("2_side_on_robot.png", (1.0, 0.0, 0.0), target=(0, 0, 900), height=2300))
    BS.remove(doc, [BS.GROUND])
    set_fold(90.0, 90.0, doc)
    BS.add_floor(doc)
    out.append(save_view("3_folded_rear_weather_mast.png", (-0.6, 1.0, -0.35), target=(0, -300, 1000), height=2600))
    BS.remove(doc, [BS.GROUND])
    set_fold(0.0, 0.0, doc)
    for n in ("tank_shell",):
        doc.getObject(n).ViewObject.Transparency = 70
    out.append(save_view("4_tank_aerator_diffuser.png", (-1.0, 0.8, -0.8), target=(0, -100, 850), height=1300))
    doc.getObject("tank_shell").ViewObject.Transparency = 0
    out.append(save_view("5_weather_mast_detail.png", (-0.8, 1.0, -0.3), target=(260, -500, 1100), height=1100))
    App.closeDocument(doc.Name)
    build()
    return out
