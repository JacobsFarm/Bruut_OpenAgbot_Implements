"""Model of the overseeder with Cambridge roll on the Bruut OpenAgbot.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_osr
    build_osr.build()                          # saves FCStd and STEP (trailer straight behind the robot)
    build_osr.set_articulation(35, 0)
    build_osr.check_interference()             # must be empty
    build_osr.check_poses()                    # over the articulation range, must be empty
    build_osr.clearance()
    build_osr.mass_properties()                # mass, centre of gravity, ball load (hopper empty / full)
    build_osr.render_all()

The roll, the frame, the drawbar and the hitch are built with the functions of build_cbr / cbr_parts (longer frame:
axle_y, cross_y from osr_params), the seeder unit with build_ovd.build_unit.
"""
import os

import FreeCAD as App

import osr_params as P
import osr_parts as G
import cbr_parts as CG
import build_cbr as B
import build_ovd as BO

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Overseeder_Cambridge_Roll"
SAVE_BASE = os.path.join(FOLDER, "Overseeder_Cambridge_Roll")
ROOT = "Overseeder_roll"
TRAILER = "Combo_trailer"
COLOR = BO.COLOR


def build_trailer(doc, parent):
    tr = B.new_part(doc, parent, TRAILER, "roll_trailer_with_seeder_unit")
    fr = B.build_roll_frame(doc, tr, P.axle_y, P.cross_y)
    arms = doc.getObject("arms")
    arms.Shape = arms.Shape.cut(G.hanger_holes())
    B.build_roll(doc, tr, P.axle_y)
    B.build_drawbar(doc, tr, P.cross_y)
    BO.build_unit(doc, tr, P.unit_y)
    plates = doc.getObject("end_plates")
    plates.Shape = plates.Shape.cut(G.hanger_holes())
    hang = B.new_part(doc, fr, "Hangers", "seeder_unit_hangers")
    BO.add(doc, hang, "hanger_blocks", "hanger_spacer_blocks_10mm", G.hanger_blocks(), "frame")
    BO.add(doc, hang, "hanger_bolts", "hanger_bolts_M10", G.hanger_bolts(), "zinc")
    return tr


def build_into(doc, parent=None):
    root = B.new_part(doc, parent, ROOT, "overseeder_with_cambridge_roll")
    B.build_hitch(doc, root)
    build_trailer(doc, root)
    return root


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Overseeder with Cambridge roll"
    doc.Comment = ("Generated by build_osr.py from osr_params.py (+ cbr_params, ovd_params). Robot coordinates: "
                   "x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = B.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        B.set_robot_visible(False, doc, ROOT)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        B.export_step(doc, SAVE_BASE + ".step", ROOT)
    return doc


def active_doc(doc=None):
    return B.active_doc(doc, ROOT)


def set_articulation(yaw=0.0, pitch=0.0, doc=None):
    B.set_articulation(yaw, pitch, active_doc(doc), TRAILER)


def check_interference(doc=None, tol=1.0):
    return B.check_interference(active_doc(doc), tol, ROOT)


def check_poses(doc=None, poses=None, tol=1.0):
    return B.check_poses(active_doc(doc), poses, tol, ROOT, TRAILER)


def clearance(doc=None):
    return B.clearance(active_doc(doc), ROOT, TRAILER)


MASS_FIXED = dict(BO.MASS_FIXED)
MASS_FIXED.update({"bearings": 2 * P.C.bearing_kg})


def mass_properties(doc=None):
    doc = active_doc(doc)
    tr = B.objects_of(doc, TRAILER)
    m, c = B.sum_mass(tr, MASS_FIXED, BO.DENSITY + B.DENSITY)
    seed = BO.hopper_litres() * P.O.seed_density
    mf = m + seed
    cyf = (c.y * m + P.unit_y * seed) / mf
    mu, cu = B.sum_mass(B.objects_of(doc, "Seeder_unit"), MASS_FIXED, BO.DENSITY)
    return {"trailer_kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z)), "unit_kg": round(mu, 1),
            "seed_kg": round(seed, 1), "ball_load_empty_N": round(B.ball_load(m, c.y, P.axle_y)),
            "ball_load_full_N": round(B.ball_load(mf, cyf, P.axle_y)),
            "roll_load_full_kg": round(mf - B.ball_load(mf, cyf, P.axle_y) / 9.81, 1)}


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    B.add_floor(doc, y=(-2900.0, 1000.0))
    out.append(B.save_view("1_iso_on_robot.png", (1.0, 1.2, -0.7), target=(0, -1100, 350), folder=PREVIEW_DIR))
    out.append(B.save_view("2_side.png", (1.0, 0.0, 0.0), target=(0, -1200, 420), height=1700, folder=PREVIEW_DIR))
    B.remove(doc, [B.GROUND])
    set_articulation(40.0, 0.0, doc)
    out.append(B.save_view("3_top_turn_40deg.png", (0.0, 0.0, -1.0), target=(-450, -1300, 0), up=(0.0, 1.0, 0.0),
                           height=3600, folder=PREVIEW_DIR))
    set_articulation(0.0, 0.0, doc)
    B.set_robot_visible(False, doc, ROOT)
    out.append(B.save_view("4_iso_rear.png", (-1.0, 1.0, -0.6), target=(0, -1800, 350), folder=PREVIEW_DIR))
    B.set_visible(doc, ("end_plates", "side_plates", "bearings", "bearing_bolts", "control_box", "gearmotor",
                        "gm_bracket", "gm_coupling", "meter_bearings", "hanger_bolts"), False)
    out.append(B.save_view("5_section_drop_and_roll.png", (1.0, 0.0, 0.0), target=(0, P.unit_y - 50, 330),
                           height=1100, folder=PREVIEW_DIR))
    B.set_robot_visible(True, doc, ROOT)
    App.closeDocument(doc.Name)
    build()
    return out
