def add_obj(doc, name, color, transparency=0, parent=None):
    obj = doc.addObject("Part::Feature", name)
    obj.ViewObject.ShapeColor = color
    obj.ViewObject.Transparency = transparency
    obj.ViewObject.DisplayMode = "Shaded"       # no edge lines (the band is made of many small faces)
    if parent is not None:
        parent.addObject(obj)
    return obj


def build():
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Overseeder with Cambridge roll on robot - animation"
    doc.Comment = "Generated by animate_osr.py. Robot from agbot design, implement from build_osr, process from osr_ground."
    robot = B.build_robot(doc)
    BS.build_into(doc, robot)
    floor = add_obj(doc, "anim_floor", COLOR["grass"])
    floor.Shape = Part.makeBox(50000.0, 50000.0, 40.0, V(-20000.0, -20000.0, -40.0))
    for key in ("band", "bare", "seeded", "pressed", "rolled_bare"):
        add_obj(doc, "anim_" + key, COLOR["rolled" if key == "band" else key])
    trailer = doc.getObject(BS.TRAILER)
    curtain = add_obj(doc, "anim_curtain", COLOR["seed"], parent=trailer)
    curtain.Shape = Part.Shape()
    strip = add_obj(doc, "anim_cam_strip", COLOR["cam"], 70, parent=trailer)
    u0, u1 = P.O.cam_use_v
    strip.Shape = Part.makePlane(P.O.width, u1 - u0, V(-P.O.width / 2.0, P.unit_y + u0, 3.0))
    doc.recompute()
    return doc


def runs(cells, z0, z1):
    """Thin boxes for a set of cells, merged per row (cells next to each other in x)."""
    rows = {}
    for i, j in cells:
        rows.setdefault(j, []).append(i)
    out = []
    c = GR.CELL
    for j, xs in rows.items():
        xs.sort()
        start = prev = xs[0]
        for i in xs[1:] + [None]:
            if i is not None and i == prev + 1:
                prev = i
                continue
            out.append(Part.makeBox((prev - start + 1) * c, c, z1 - z0, V(start * c, j * c, z0)))
            if i is not None:
                start = prev = i
    return Part.makeCompound(out) if out else Part.Shape()


def band_shape(band, n):
    faces = []
    for q in band[:n]:
        pts = [V(p[0], p[1], 0.4) for p in q]
        try:
            faces.append(Part.Face(Part.makePolygon(pts + [pts[0]])))
        except Exception:
            pass
    return Part.makeCompound(faces) if faces else Part.Shape()


def curtain_shape(t):
    rnd = random.Random(int(t * 1000))
    z_top = P.O.roller_z - P.O.roller_d / 2.0
    out = []
    for _ in range(90):
        x = rnd.uniform(-P.O.width / 2.0 + 5.0, P.O.width / 2.0 - 15.0)
        z = rnd.uniform(5.0, z_top - 15.0)
        v = rnd.uniform(-12.0, 12.0)
        out.append(Part.makeBox(9.0, 9.0, 9.0, V(x, P.unit_y + v, z)))
    return Part.makeCompound(out)


def apply_frame(doc, f, band):
    cx, cy = f["centre"]
    doc.getObject("Robot").Placement = App.Placement(V(cx, cy, 0.0), App.Rotation(V(0, 0, 1), math.degrees(f["psi"])))
    for tag, delta in (("FL", f["steer"][0]), ("FR", f["steer"][1])):
        doc.getObject(tag + "_steered").Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), delta))
    for tag in ("RL", "RR", "FL", "FR"):
        rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"][tag]))
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    doc.getObject(BS.TRAILER).Placement = B.articulation(f["articulation"], 0.0)
    doc.getObject("Roll").Placement = B.roll_spin(math.degrees(f["roll_angle"]), P.axle_y)
    doc.getObject("Meter").Placement = BO.meter_spin(math.degrees(f["meter_angle"]), P.unit_y)
    bare = simulation()["bare"]
    seeded, rolled = f["seeded_set"], f["rolled_set"]
    doc.getObject("anim_bare").Shape = runs(bare - seeded - rolled, 0.6, 1.4)
    doc.getObject("anim_seeded").Shape = runs(seeded - rolled, 0.6, 1.6)
    doc.getObject("anim_pressed").Shape = runs(seeded & rolled, 0.6, 1.4)
    doc.getObject("anim_rolled_bare").Shape = runs(rolled - seeded, 0.6, 1.4)
    doc.getObject("anim_band").Shape = band_shape(band, f["band_n"])
    doc.getObject("anim_curtain").Shape = curtain_shape(f["t"]) if f["flow"] else Part.Shape()


def track_camera(f):
    import FreeCADGui as Gui
    from pivy import coin
    cx, cy = f["centre"]
    rx, ry = GR.trailer_point(f["ball"], f["theta"], P.L_roll)
    tgt = ((cx + rx) / 2.0, (cy + ry) / 2.0, 150.0)
    off = GR.local_to_world((0.0, 0.0), f["psi"], CAM_EYE[0], CAM_EYE[1])
    eye = (tgt[0] + off[0], tgt[1] + off[1], tgt[2] + CAM_EYE[2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(CAM_FOV))
    cam.nearDistance.setValue(50.0)
    cam.farDistance.setValue(60000.0)


def phase(f):
    s = f["s"]
    if s <= GR.L1:
        return "pass 1 (north)"
    if s <= GR.L1 + GR.LT:
        return "headland turn"
    return "pass 2 (south)"


def meta(f):
    st = GR.stats(f)
    return {"t": round(f["t"], 2), "v": round(f["v"]), "phase": phase(f), "flow": f["flow"], "motor": f["motor"],
            "command": f["command"], "ahead": f["ahead"], "articulation": round(f["articulation"], 1),
            "steer": [round(f["steer"][0], 1), round(f["steer"][1], 1)], "draft": round(f["draft_N"]),
            "rpm": round(VC.rpm_for(max(f["v"], 50.0) / 1000.0), 1) if f["motor"] else 0.0,
            "seeded_pct": st["seeded_pct"], "rolled_pct": st["rolled_pct"], "seed_g": st["seed_g"],
            "on_green_pct": st["on_green_pct"], "bare_m2": st["bare_m2"],
            "timing": {k: round(v, 2) for k, v in VC.timing(max(f["v"], 50.0) / 1000.0).items()}}


def summary():
    sim = simulation()
    S = sim["states"]
    st = GR.stats(S[-1])
    switches = sum(1 for a, b in zip(S, S[1:]) if b["flow"] and not a["flow"])
    st.update({"duration_s": round(S[-1]["t"], 1), "frames": len(frames()), "switch_ons": switches,
               "patches": len(GR.PATCHES), "max_articulation_deg": round(max(abs(s["articulation"]) for s in S), 1),
               "max_steer_deg": round(max(max(abs(a) for a in s["steer"]) for s in S), 1),
               "draft_N": (round(min(s["draft_N"] for s in S)), round(max(s["draft_N"] for s in S)))})
    return st


def check_fit(doc=None, tol=1.0):
    """Trailer against the hitch and the robot at the articulations of the run (every 10 degrees). Must be empty."""
    doc = doc or App.getDocument(DOC_NAME)
    arts = sorted({round(s["articulation"] / 10.0) * 10.0 for s in simulation()["states"]})
    return B.check_poses(doc, [(a, 0.0) for a in arts], tol, BS.ROOT, BS.TRAILER)


def render_frames(folder, first=0, count=None, fps=FPS, size=(720, 480)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    fr = frames(fps)
    band = simulation()["band"]
    os.makedirs(folder, exist_ok=True)
    if first == 0:
        with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
            json.dump([meta(f) for f in fr], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(fr) if count is None else min(len(fr), first + count)
    for i in range(first, last):
        apply_frame(doc, fr[i], band)
        track_camera(fr[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(fr)


def render_all(folder, fps=FPS, size=(720, 480)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 40, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=2.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    fr = frames(fps)
    band = simulation()["band"]
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(fr):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = fr[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f, band)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))
