"""Animation: the Bruut OpenAgbot pulls the overseeder with Cambridge roll over a lawn with bare (black) patches.

The robot drives one pass north, turns right (half circle, rear axle radius 2.25 m, front wheels steered with
Ackermann) and drives back south. The trailer follows the tow ball (pursuit kinematics), so it cuts inside in the
turn. The camera on the seeder looks 0.4 .. 1.2 m ahead of the drop line (blue strip); where it sees bare soil the
controller starts the metering motor early enough (motor start + fall time) that the seed lands from just before the
patch to just after it. On full grass the motor stops. The roll always rolls: rolled lawn turns lighter, bare soil
turns from black (bare) to golden (seed on the soil) to brown (seed pressed in by the rings).

All figures come from osr_ground (process model), osr_calc / ovd_calc (timing, draft), so the animation and the
report agree.

Use in FreeCAD:
    import animate_osr
    animate_osr.build()                          # build the document
    animate_osr.play()                           # play live, animate_osr.stop()
    animate_osr.summary()                        # key figures of the run
    animate_osr.check_fit()                      # trailer vs robot over the articulation of the run (must be empty)
    animate_osr.render_all(r"C:\\temp\\osr_frames")
    import make_gif_osr; make_gif_osr.main(r"C:\\temp\\osr_frames", r"previews\\animation_spot_seeding.gif")
"""
import json
import math
import os
import random

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import osr_params as P
import osr_ground as GR
import ovd_calc as VC
import build_cbr as B
import build_ovd as BO
import build_osr as BS

DOC_NAME = "Overseeder_roll_on_robot_animation"
FPS = 4                         # frames per second of real time; the GIF plays at 8 fps = 2 x speed
HOLD_END = 2.5
COLOR = {"grass": (0.34, 0.55, 0.22), "rolled": (0.50, 0.68, 0.32), "bare": (0.05, 0.04, 0.035),
         "seeded": (0.86, 0.70, 0.30), "pressed": (0.45, 0.32, 0.17), "rolled_bare": (0.22, 0.17, 0.12),
         "seed": (0.95, 0.80, 0.35), "cam": (0.35, 0.65, 1.0)}

# Camera: behind-left of the robot, high (robot frame: x = right, y = forward); it turns with the robot, follows the
# middle between the robot and the roll
CAM_EYE = (-2300.0, -2900.0, 2700.0)
CAM_FOV = 45.0

_timer = None
_play = {}
_sim = {}


def simulation():
    if "sim" not in _sim:
        _sim["sim"] = GR.simulate()
    return _sim["sim"]


def frames(fps=FPS):
    sim = simulation()
    step = max(1, int(round(1.0 / (fps * GR.DT))))
    out = sim["states"][::step]
    hold = int(HOLD_END * fps)
    out = out + [out[-1]] * hold
    return out


