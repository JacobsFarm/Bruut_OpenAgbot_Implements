"""Animation: the Bruut OpenAgbot rakes moss and thatch out of grassland with the electric belt rake, working from the
outside of the field inwards.

The robot drives at 1.2 m/s, the belt runs at 1.5 m/s. The litter in the tine band is carried to the left (orange
while it is on the move) and thrown against the swath board into one windrow. The windrow of the previous pass lies
inside this pass's width (right): it is picked up and laid in the new windrow too. At the headland the two castor
actuators push the rake up 100 mm (3.3 s), then the belt stops. Litter, belt and lift come from brk_field /
brk_calc, the same figures as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, rake from
build_brk, grass floor, the litter.

Use in FreeCAD:
    import animate_brk
    animate_brk.build()                              # build the document
    animate_brk.play()                               # play live, animate_brk.stop()
    animate_brk.summary()                            # key figures of the run
    animate_brk.render_all(r"C:\\temp\\brk_frames")
    import make_gif_brk; make_gif_brk.main(r"C:\\temp\\brk_frames", r"previews\\animation_raking_windrow.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import brk_params as P
import brk_calc as C
import brk_parts as G
import brk_field as F
import build_brk

DOC_NAME = "Belt_rake_on_robot_animation"
FPS = 10                        # frames per second of real time; the GIF plays at 10 fps = real speed
COLOR = {"grass": (0.47, 0.62, 0.30), "litter": (0.80, 0.70, 0.36), "carried": (0.95, 0.45, 0.08)}

_timer = None
_play = {}


# ---------------------------------------------------------------------
# Frames
# ---------------------------------------------------------------------
def prepare(fps=FPS):
    n = int(math.ceil(F.t_end() * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        y = F.robot_y(t)
        lift = F.lift_at(t)
        if t <= F.drive_time():
            phase = "raking"
        elif lift < P.lift_travel:
            phase = "lifting"
        else:
            phase = "up"
        frames.append({"t": t, "y": y, "lift": lift, "belt": F.belt_phase(t), "phase": phase,
                       "v": F.mode()["v"] * 1000.0 if t < F.drive_time() else 0.0,
                       "spin": (y - F.Y_START) / (P.robot_tire_d / 2.0)})
    return frames


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build():
    if build_brk.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_brk.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    _CACHE.clear()
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Belt rake on robot - animation"
    doc.Comment = "Generated by animate_brk.py. Robot from agbot design, rake from build_brk."
    robot = build_brk.build_robot(doc)
    build_brk.build_into(doc, robot)
    build_brk.set_robot_visible(True, doc)
    floor = doc.addObject("Part::Feature", "anim_floor")
    floor.Shape = Part.makeBox(5000.0, 13000.0, 40.0, V(-2500.0, -4000.0, -40.0))
    floor.ViewObject.ShapeColor = COLOR["grass"]
    for name, color in (("anim_litter", "litter"), ("anim_carried", "carried"), ("anim_windrow", "litter")):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
        o.ViewObject.DisplayMode = "Shaded"            # thin straws: no black edge lines
    doc.recompute()
    return doc


_CACHE = {}


def _straws():
    if not _CACHE:
        _CACHE["base"] = [G.straw(0.0, 0.0, p["l"], p["rot"], z=0.0, w=7.0, t=3.0) for p in F.pieces()]
    return _CACHE["base"]


def _place(i, x, y, z):
    s = _straws()[i].copy()
    s.Placement = App.Placement(V(x, y, z), App.Rotation())
    return s


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def apply_frame(doc, f):
    y = f["y"]
    doc.getObject("Robot").Placement = App.Placement(V(0.0, y, 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    for name, pl in build_brk.pose_placements(f["lift"], f["belt"]).items():
        doc.getObject(name).Placement = pl
    lying, carried, windrow = [], [], []
    for i, (x, yy, z, s) in enumerate(F.at(f["t"])):
        (lying, carried, windrow)[s].append(_place(i, x, yy, z))
    doc.getObject("anim_litter").Shape = _compound(lying)
    doc.getObject("anim_carried").Shape = _compound(carried)
    doc.getObject("anim_windrow").Shape = _compound(windrow)


# ---------------------------------------------------------------------
# Camera and rendering
# ---------------------------------------------------------------------
CAM_A = ((-2100.0, 2900.0, 1650.0), (-250.0, 650.0, 80.0))     # eye and target relative to the robot centre


def track_camera(f, fov=44.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


STATE = {"raking": "raking: litter carried to the left into the windrow", "lifting": "headland: castor actuators "
         "lift the rake", "up": "rake up, belt stopped: ready to turn"}


def meta(f):
    m = F.mode()
    d = C.drive(F.MODE)
    sf = C.side_force(F.MODE)
    st = F.at(f["t"])
    on = f["phase"] != "up"
    moved = sum(1 for s in st if s[3] == 2)
    carried = sum(1 for s in st if s[3] == 1)
    return {"t": round(f["t"], 2), "phase": f["phase"], "state": STATE[f["phase"]], "v": round(f["v"], 0),
            "u": round(m["u"] * 1000.0 if on else 0.0, 0), "lift": round(f["lift"], 0),
            "P_el": round(d["P_el"] if f["phase"] == "raking" else (P.bearing_loss_W / 0.78 if on else 0.0), 0),
            "side_N": round(sf["lat"] if f["phase"] == "raking" else 0.0, 0),
            "moved_kg": round(moved * F.PIECE_KG, 2), "carried_kg": round(carried * F.PIECE_KG, 3),
            "driven_m": round((f["y"] - F.Y_START) / 1000.0, 2)}


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    s["lift_max"] = max(f["lift"] for f in frames)
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i])
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=1.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))


def check_fit(doc=None, tol=1.0):
    """Overlap between the robot and the rake in the animation document over the lift and the belt (the poses of
    build_brk.check_fit cover the lift that occurs here)."""
    doc = doc or App.getDocument(DOC_NAME)
    return build_brk.check_fit(doc, tol=tol)
