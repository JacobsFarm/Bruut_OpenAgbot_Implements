"""Model of the lime spreader on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_lsp
    build_lsp.build()                      # saves FCStd and STEP (hopper full, lime shown)
    build_lsp.check_interference()         # overlap between the parts and with the robot (must be empty)
    build_lsp.check_holes()                # shafts and bolts in their holes (must be empty)
    build_lsp.check_steering()             # overlap with the front wheels steered +-30 (must be empty)
    build_lsp.clearance()                  # smallest distance to the tyres (rear and steered front)
    build_lsp.hopper_volume()              # litres up to the fill level
    build_lsp.mass_properties()
    build_lsp.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import lsp_params as P
import lsp_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Lime_Spreader"
SAVE_BASE = os.path.join(FOLDER, "Lime_Spreader")
ROOT = "Lime_spreader"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "hopper": (0.20, 0.50, 0.30),
    "lid": (0.15, 0.40, 0.25),
    "zinc": (0.82, 0.84, 0.87),
    "steel": (0.75, 0.75, 0.78),
    "rubber": (0.10, 0.10, 0.10),
    "motor": (0.20, 0.22, 0.25),
    "lime": (0.93, 0.93, 0.88),
}


def new_part(doc, parent, name, label):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_into(doc, parent=None, full=True):
    root = new_part(doc, parent, ROOT, "lime_spreader_simple")
    m = new_part(doc, root, "Mount", "mount_rails_on_inner_upper_beams")
    add_shape(doc, m, "rails", "rails_40x40x3", G.rails(), "frame")
    add_shape(doc, m, "spacers", "spacers_25mm", G.spacers(), "frame")
    add_shape(doc, m, "rail_bolts", "rail_bolts_M10", G.rail_bolts(), "zinc")
    add_shape(doc, m, "legs", "legs_40x40x3_saddles", G.legs(), "frame")
    h = new_part(doc, root, "Hopper", "hopper_200l")
    add_shape(doc, h, "hopper", "hopper_steel_2mm_V_trough", G.hopper(), "hopper")
    add_shape(doc, h, "lid", "lid_alu_2mm", G.lid(), "lid", visible=False)
    d = new_part(doc, root, "Metering", "augers_and_drop_tube")
    add_shape(doc, d, "long_auger", "trough_auger_D100_p100", G.long_auger(), "steel")
    add_shape(doc, d, "long_tube", "auger_tube_114x3", G.long_tube(), "frame")
    add_shape(doc, d, "chute", "drop_chute_100x100", G.chute(), "frame")
    add_shape(doc, d, "cross_tube", "cross_tube_114x3_outlet_holes_D20", G.cross_tube(), "frame")
    add_shape(doc, d, "cross_auger", "cross_auger_D100_left_right_hand", G.cross_auger(), "steel")
    add_shape(doc, d, "end_plates", "cross_tube_end_plates_6mm", G.end_plates(), "frame")
    add_shape(doc, d, "skirt", "dust_skirt_rubber_4mm", G.skirt(), "rubber")
    add_shape(doc, d, "gm_long", "gearmotor_24V_worm_trough_auger", G.gearmotor_long(), "motor")
    add_shape(doc, d, "gm_cross", "gearmotor_24V_worm_cross_auger", G.gearmotor_cross(), "motor")
    load = new_part(doc, root, "Load", "lime_load")
    add_shape(doc, load, "lime", "lime_fill", G.lime_fill(), "lime", visible=full)
    return root


def build_robot(doc, steer=0.0):
    """Real robot model from 'agbot design' (read only)."""
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, steer if tag in ("FL", "FR") else 0.0)
    return robot


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Lime spreader simple"
    doc.Comment = ("Generated by build_lsp.py from lsp_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0. Hopper full (lime_fill).")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


