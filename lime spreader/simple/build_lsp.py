def set_camera(direction, target=None, height=None, up=(0.0, 0.0, 1.0)):
    import FreeCADGui as Gui
    from pivy import coin
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Orthographic")
    d = V(*direction)
    d.normalize()
    cam = view.getCameraNode()
    tgt = V(*target) if target is not None else V(0, -200, 500)
    eye = tgt - d * 9000.0
    cam.position.setValue(coin.SbVec3f(eye.x, eye.y, eye.z))
    cam.pointAt(coin.SbVec3f(tgt.x, tgt.y, tgt.z), coin.SbVec3f(*up))
    cam.nearDistance.setValue(10.0)
    cam.farDistance.setValue(30000.0)
    if height is None:
        view.fitAll()
    else:
        cam.height.setValue(height)
    return view


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    """Standard images in previews/, then build and save (FCStd + STEP, robot hidden)."""
    out = []
    doc = build(save=False, show_robot=True, step=False)
    floor = doc.addObject("Part::Feature", "render_floor")
    floor.Shape = G.box_span((-1100, 1100), (-1300, 900), (-40.0, 0.0))
    floor.ViewObject.ShapeColor = (0.55, 0.45, 0.33)
    out.append(save_view("1_iso_rear_right_on_robot.png", (-1.0, 1.2, -0.8), target=(0, -250, 450)))
    out.append(save_view("2_side.png", (-1.0, 0.0, 0.0), target=(0, -250, 500), height=1500))
    out.append(save_view("3_rear.png", (0.0, 1.0, 0.0), target=(0, -250, 500), height=1400))
    doc.removeObject("render_floor")
    out.append(save_view("4_top.png", (0.0, 0.0, -1.0), target=(0, -200, 0), up=(0.0, 1.0, 0.0), height=2300))
    set_robot_visible(False, doc)
    doc.getObject("lime").ViewObject.Visibility = False
    out.append(save_view("5_augers_iso.png", (-1.0, 1.0, -0.9), target=(0, -350, 500), height=1700))
    App.closeDocument(doc.Name)
    build()
    return out
