def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    if g is None:
        return []
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"]


def implement_objects(doc):
    """All implement parts except the lime load."""
    return [o for o in objects_of(doc, ROOT) if o.Name != "lime"]


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in implement_objects(doc):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        try:
            vol = sa.common(sb).Volume
        except Exception as exc:
            hits.append((oa.Label, ob.Label, "error %s" % exc))
            continue
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits


JOINTS = {("rail_bolts", "rails"), ("rail_bolts", "spacers"), ("rail_bolts", "hopper"), ("legs", "rails"),
          ("long_auger", "hopper"), ("long_auger", "long_tube"), ("long_auger", "gm_long"),
          ("cross_auger", "cross_tube"), ("cross_auger", "end_plates"), ("cross_auger", "gm_cross"),
          ("long_tube", "hopper"), ("legs", "cross_tube")}


def _joint(a, b):
    return (a, b) in JOINTS or (b, a) in JOINTS or (a == "rail_bolts" and b.startswith("upper_beam")) or \
        (b == "rail_bolts" and a.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    """Volume overlap (mm3): implement parts among themselves and against the robot (shafts and bolts in their holes
    are skipped, see check_holes)."""
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in implement_objects(doc)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in implement_objects(doc)}
    for o in robot_objects(doc):
        if o.Name.startswith("upper_beam"):
            objs[o.Name] = global_shape(o)
    out = {}
    pairs = [p for p in JOINTS] + [("rail_bolts", n) for n in objs if n.startswith("upper_beam")]
    for a, b in pairs:
        if a in objs and b in objs and objs[a].BoundBox.intersect(objs[b].BoundBox):
            v = objs[a].common(objs[b]).Volume
            if v > tol and (a, b) not in (("legs", "rails"), ("legs", "cross_tube"), ("long_tube", "hopper")):
                out[(a, b)] = round(v, 1)
    return out


def check_steering(doc=None, tol=1.0):
    """Front wheels steered -30 and +30: the implement against the front wheel units. Must be empty."""
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in implement_objects(doc)]
    out = {}
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        front = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name[:2] in ("FL", "FR")]
        hits = _overlaps([(a, b) for a in mine for b in front], tol)
        if hits:
            out[st] = hits
    set_steering(0.0, doc)
    return out


def tyre_envelope(x, y, steer=0.0):
    c = V(x, y, P.robot_axle_z)
    t = Part.makeCylinder(P.robot_tire_d / 2.0, P.robot_tire_w, c - V(P.robot_tire_w / 2.0, 0, 0), V(1, 0, 0))
    t.rotate(V(x, y, 0), V(0, 0, 1), steer)
    return t


def clearance(doc=None):
    """Smallest distance (mm) of the implement to the rear tyres and the front tyres steered +-30 (envelopes)."""
    doc = active_doc(doc)
    tyres = [(tyre_envelope(sx * P.robot_wheel_x, -P.robot_axle_y), "rear") for sx in (-1, 1)]
    for st in (-P.robot_steer_deg, 0.0, P.robot_steer_deg):
        tyres += [(tyre_envelope(sx * P.robot_wheel_x, P.robot_axle_y, st), "front_%g" % st) for sx in (-1, 1)]
    best = (1e9, None, None)
    for o in implement_objects(doc):
        s = global_shape(o)
        for t, tag in tyres:
            d = s.distToShape(t)[0]
            if d < best[0]:
                best = (d, o.Name, tag)
    return round(best[0], 1), best[1], best[2]


def ground_clearance(doc=None):
    doc = active_doc(doc)
    return {o.Name: round(global_shape(o).BoundBox.ZMin, 1) for o in implement_objects(doc)
            if global_shape(o).BoundBox.ZMin < 400.0}


def hopper_volume(doc=None):
    """Litres of lime up to the fill level, and its centre of gravity."""
    s = G.lime_fill()
    c = V(0, 0, 0)
    for sol in s.Solids:
        c += sol.CenterOfMass * sol.Volume
    c = c * (1.0 / s.Volume)
    return {"volume_l": round(s.Volume / 1e6, 1), "cg": (round(c.x), round(c.y), round(c.z))}


MASS_FIXED = {"gm_long": P.gm_kg, "gm_cross": P.gm_kg}
DENSITY = (("skirt", P.rubber), ("lid", P.alu))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity of the empty spreader (robot coordinates)."""
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in implement_objects(doc):
        mo, co = _mass_cg(o)
        m += mo
        c += co * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in implement_objects(doc):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


