def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


GROUND = "render_floor"


def add_floor(doc, y=(-900.0, 2300.0), x=(-1100.0, 1100.0)):
    obj = doc.addObject("Part::Feature", GROUND)
    obj.Shape = G.box_span(x, y, (-40.0, 0.0))
    obj.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    obj.ViewObject.Transparency = 30
    return obj


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    """Standard images in previews/, then build and save (FCStd + STEP, robot hidden)."""
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_floor(doc)
    out.append(save_view("1_iso_front_on_robot.png", (-1.0, -1.2, -0.7), target=(0, 900, 300)))
    out.append(save_view("2_side_work.png", (1.0, 0.0, 0.0), target=(0, 900, 400), height=2000))
    set_pose(P.lift_transport, doc)
    out.append(save_view("3_side_lifted.png", (1.0, 0.0, 0.0), target=(0, 900, 400), height=2000))
    remove(doc, [GROUND])
    set_pose(P.lift_work, doc)
    set_steering(P.robot_steer_deg, doc)
    out.append(save_view("4_top_steered_30deg.png", (0.0, 0.0, -1.0), target=(0, 800, 0), up=(0.0, 1.0, 0.0),
                         height=2800))
    set_steering(0.0, doc)
    set_robot_visible(False, doc)
    out.append(save_view("5_root_and_actuator.png", (-1.0, -0.8, -0.5), target=(150, 750, 650), height=900))
    doc.getObject("housing").ViewObject.Transparency = 75
    out.append(save_view("6_coil_inside.png", (-0.8, -1.0, -0.9), target=(0, 1800, 40), height=1000))
    App.closeDocument(doc.Name)
    build()
    return out
