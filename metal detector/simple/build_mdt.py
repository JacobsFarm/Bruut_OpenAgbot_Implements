"""Model of the metal detector on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_mdt
    build_mdt.build()                 # saves FCStd and STEP (work pose: coil on its skids)
    build_mdt.set_pose(lift=14)       # boom angle about the pivot (deg, + = up)
    build_mdt.check_interference()    # overlap in the current pose (must be empty)
    build_mdt.check_holes()           # pins and bolts in their holes (must be empty)
    build_mdt.check_poses()           # overlap over lift x steering +-30 (must be empty)
    build_mdt.clearance()             # smallest distance of the boom to the front tyres, and of the coil to robot steel
    build_mdt.mass_properties()
    build_mdt.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import mdt_params as P
import mdt_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Metal_Detector"
SAVE_BASE = os.path.join(FOLDER, "Metal_Detector")
ROOT = "Metal_detector"

COLOR = dict(BP.COLOR)
COLOR.update({
    "bracket": (0.85, 0.40, 0.10),
    "gfrp": (0.93, 0.85, 0.45),
    "coil": (0.15, 0.35, 0.75),
    "copper": (0.85, 0.50, 0.20),
    "pe": (0.95, 0.95, 0.92),
    "box": (0.25, 0.25, 0.28),
})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def boom_placement(lift_deg):
    return App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), lift_deg), V(0, P.pivot[0], P.pivot[1]))


def build_into(doc, parent=None, lift=P.lift_work):
    root = new_part(doc, parent, ROOT, "metal_detector_simple")
    mount = new_part(doc, root, "Mount", "mount_root_brackets")
    add_shape(doc, mount, "bracket_left", "root_bracket_left_8mm", G.bracket_left(), "bracket")
    add_shape(doc, mount, "bracket_right", "root_bracket_right_8mm_with_actuator_mast", G.bracket_right(), "bracket")
    add_shape(doc, mount, "bracket_bolts", "bracket_bolts_M10_4x", G.bracket_bolts(), "zinc")
    add_shape(doc, mount, "pivot_pin", "pivot_pin_stainless_D16", G.pivot_pin(), "steel")
    boom = new_part(doc, root, "Boom", "boom_turns_about_pivot", boom_placement(lift))
    add_shape(doc, boom, "boom_tubes", "boom_tubes_GFRP_50x50x4_2x", G.boom_tubes(), "gfrp")
    add_shape(doc, boom, "cross_tubes", "cross_tubes_GFRP_40x40x4_2x", G.cross_tubes(), "gfrp")
    add_shape(doc, boom, "lug", "actuator_lug_GFRP_24mm_slot_40", G.lug(), "gfrp")
    add_shape(doc, boom, "ebox", "PI_electronics_box_IP67", G.ebox(), "box")
    add_shape(doc, boom, "carrier", "coil_carrier_GFRP_10mm_wedges", G.carrier(), "gfrp")
    add_shape(doc, boom, "housing", "coil_housing_ABS_600x400x40", G.housing(), "coil")
    add_shape(doc, boom, "winding", "search_coil_24_turns_litz", G.winding(), "copper")
    add_shape(doc, boom, "skids", "skids_PE_15mm_2x", G.skids(), "pe")
    act = new_part(doc, root, "Actuator", "lift_actuator_24V_500N_stroke_100")
    body, rod, pins, _ = G.actuator(lift)
    add_shape(doc, act, "act_body", "actuator_body", body, "actuator")
    add_shape(doc, act, "act_rod", "actuator_rod", rod, "steel")
    add_shape(doc, act, "act_pins", "actuator_pins_D12", pins, "zinc")
    return root


def set_pose(lift=P.lift_work, doc=None):
    doc = active_doc(doc)
    doc.getObject("Boom").Placement = boom_placement(lift)
    body, rod, pins, _ = G.actuator(lift)
    doc.getObject("act_body").Shape = body
    doc.getObject("act_rod").Shape = rod
    doc.getObject("act_pins").Shape = pins


build_robot = BP.build_robot
set_steering = BP.set_steering
tyre_envelope = BP.tyre_envelope
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True, lift=P.lift_work):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Metal detector simple"
    doc.Comment = ("Generated by build_mdt.py from mdt_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0. Work pose; build_mdt.set_pose() lifts the boom.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, lift)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("bracket_bolts", "bracket_left"), ("bracket_bolts", "bracket_right"), ("pivot_pin", "bracket_left"),
          ("pivot_pin", "bracket_right"), ("pivot_pin", "boom_tubes"), ("act_pins", "bracket_right"),
          ("act_pins", "act_body"), ("act_pins", "act_rod"), ("act_pins", "lug"), ("act_body", "act_rod")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return ("bracket_bolts" in (a, b)) and (a.startswith("lower_beam") or b.startswith("lower_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    out = {}
    for a, b in JOINTS:
        if (a, b) == ("act_body", "act_rod"):
            continue
        if a in objs and b in objs and objs[a].BoundBox.intersect(objs[b].BoundBox):
            v = objs[a].common(objs[b]).Volume
            if v > tol:
                out[str((a, b))] = round(v, 1)
    return out


def check_poses(doc=None, tol=1.0, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Boom and actuator against the mount and the robot over lift x steering. Must be empty."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Boom") + objects_of(doc, "Actuator")
    names = {o.Name for o in moving}
    others = [o for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    act_names = {o.Name for o in objects_of(doc, "Actuator")}
    out = {}
    for st in steer:
        set_steering(st, doc)
        fixed = [(o, global_shape(o)) for o in others]
        for lift in P.LIFT_POSES:
            set_pose(lift, doc)
            mv = [(o, global_shape(o)) for o in moving]
            pairs = [(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)]
            pairs += [(a, b) for a in mv for b in mv if a[0].Name in act_names and b[0].Name not in act_names
                      and not _joint(a[0].Name, b[0].Name)]
            hits = _overlaps(pairs, tol)
            if hits:
                out[str((st, lift))] = hits
    set_steering(0.0, doc)
    set_pose(P.lift_work, doc)
    return out


def clearance(doc=None, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Smallest distance (mm) of the boom to the front tyres over the poses, and of the winding to the nearest robot
    or mount steel in the work pose (the detector needs distance)."""
    doc = active_doc(doc)
    moving = [doc.getObject(n) for n in ("boom_tubes", "cross_tubes", "lug", "act_body")]
    best = (1e9, None, None)
    for st in steer:
        tg = [tyre_envelope(sx * P.robot_wheel_x, st) for sx in (-1, 1)]
        for lift in (P.LIFT_POSES[0], P.LIFT_POSES[-1]):
            set_pose(lift, doc)
            for o in moving:
                s = global_shape(o)
                for t in tg:
                    d = s.distToShape(t)[0]
                    if d < best[0]:
                        best = (d, o.Name, (st, lift))
    set_pose(P.lift_work, doc)
    coil = global_shape(doc.getObject("winding"))
    metal = [o for o in robot_objects(doc) if "tire" not in o.Name and "rim" not in o.Name]
    metal += [doc.getObject(n) for n in ("bracket_left", "bracket_right", "pivot_pin", "bracket_bolts")]
    near = min((coil.distToShape(_bbox(global_shape(o)))[0], o.Name) for o in metal)   # box: fast, conservative
    return {"tyres": (round(best[0], 1), best[1], best[2]), "coil_to_steel": (round(near[0]), near[1])}


def _bbox(s):
    import Part
    b = s.BoundBox
    return Part.makeBox(max(b.XLength, 0.1), max(b.YLength, 0.1), max(b.ZLength, 0.1), V(b.XMin, b.YMin, b.ZMin))


def ground_contact(doc=None):
    doc = active_doc(doc)
    out = {}
    for lift in (P.lift_work, P.lift_transport):
        set_pose(lift, doc)
        out["lift_%g" % lift] = {n: round(global_shape(doc.getObject(n)).BoundBox.ZMin, 1)
                                 for n in ("skids", "housing", "winding", "boom_tubes")}
    set_pose(P.lift_work, doc)
    return out


MASS_FIXED = {"act_body": P.act_kg - 0.3, "act_rod": 0.3, "ebox": 1.2}
DENSITY = (("boom_tubes", P.gfrp), ("cross_tubes", P.gfrp), ("lug", P.gfrp), ("carrier", P.gfrp),
           ("housing", P.abs_), ("winding", 3.0e-6), ("skids", P.pe))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
            break
    return vol * dens, cg


def sum_mass(objs):
    m, c = 0.0, V(0, 0, 0)
    for o in objs:
        mo, co = _mass_cg(o)
        m += mo
        c += co * mo
    return m, (c * (1.0 / m) if m > 0 else c)


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Boom", "Actuator"):
        m, c = sum_mass(objects_of(doc, name))
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


