"""Model of the yield estimator on the Bruut OpenAgbot (standard robot).

Camera bridge from "mole mapper/simple" (mmp_parts); this file adds the cameras, depth cameras and LED bars.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_yld
    build_yld.build()                 # saves FCStd and STEP
    build_yld.check_interference()    # overlap (must be empty)
    build_yld.check_holes()           # bolts in their holes (must be empty)
    build_yld.check_steering()        # bridge against the steered front wheels (must be empty)
    build_yld.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import yld_params as P
import yld_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Yield_Estimator"
SAVE_BASE = os.path.join(FOLDER, "Yield_Estimator")
ROOT = "Yield_estimator"

COLOR = dict(BP.COLOR)
COLOR.update({"alu": (0.80, 0.82, 0.85), "camera": (0.15, 0.15, 0.18), "tof": (0.20, 0.35, 0.70),
              "led": (0.95, 0.95, 0.60), "leaf": (0.25, 0.50, 0.25), "curd": (0.95, 0.92, 0.80)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "yield_estimator_simple")
    br = new_part(doc, root, "CamBridge", "camera_bridge_from_mole_mapper")
    add_shape(doc, br, "cam_brackets", "post_brackets_8mm_2x", G.brackets(), "frame")
    add_shape(doc, br, "cam_bracket_bolts", "post_bracket_bolts_M10_4x", G.bracket_bolts(), "zinc")
    add_shape(doc, br, "cam_posts", "posts_alu_40x40x3_2x", G.posts(), "alu")
    add_shape(doc, br, "cam_bar", "cross_bar_alu_40x40x3_L1800", G.cross_bar(), "alu")
    add_shape(doc, br, "cam_stays", "stays_flat_30x5_2x", G.stays(), "alu")
    sens = new_part(doc, root, "Sensors", "cameras_depth_cameras_leds")
    add_shape(doc, sens, "cameras", "rgb_cameras_4K_4x", G.cameras(), "camera")
    add_shape(doc, sens, "tof", "depth_cameras_ToF_2x", G.tof(), "tof")
    add_shape(doc, sens, "leds", "led_flash_bars_3x", G.leds(), "led")
    return root


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Yield estimator simple"
    doc.Comment = ("Generated by build_yld.py from yld_params.py (camera bridge from mole mapper/simple). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("cam_bracket_bolts", "cam_brackets"), ("cam_posts", "cam_brackets"), ("cam_posts", "cam_bar"),
          ("cam_stays", "cam_posts"), ("cam_stays", "cam_bar")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "cam_bracket_bolts" in (a, b) and (a.startswith("lower_beam") or b.startswith("lower_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    a, b = doc.getObject("cam_bracket_bolts"), doc.getObject("cam_brackets")
    v = global_shape(a).common(global_shape(b)).Volume
    return {} if v <= tol else {"bolts_in_brackets": round(v, 1)}


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in mine for b in rob], tol)
        if hits:
            out[str(st)] = hits
    set_steering(0.0, doc)
    return out


DENSITY = {"cam_posts": 2.7e-6, "cam_bar": 2.7e-6, "cam_stays": 2.7e-6}
MASS_FIXED = {"cameras": 1.2, "tof": 0.8, "leds": 1.5}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, 7.85e-6))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_floor", "render_leaves", "render_heads")


def add_scene(doc):
    f = doc.addObject("Part::Feature", SCENE[0])
    f.Shape = G.box_span((-1300.0, 1300.0), (-1200.0, 3000.0), (-40.0, 0.0))
    f.ViewObject.ShapeColor = (0.45, 0.35, 0.25)
    leaves, heads = G.crop()
    lv = doc.addObject("Part::Feature", SCENE[1])
    lv.Shape = leaves
    lv.ViewObject.ShapeColor = COLOR["leaf"]
    hd = doc.addObject("Part::Feature", SCENE[2])
    hd.Shape = heads
    hd.ViewObject.ShapeColor = COLOR["curd"]


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_over_4_rows.png", (-1.0, -1.2, -0.7), target=(0, 800, 500)))
    out.append(save_view("2_front_view.png", (0.0, -1.0, 0.0), target=(0, 0, 700), height=1800))
    remove(doc, SCENE)
    set_robot_visible(False, doc)
    out.append(save_view("3_bridge_sensors.png", (-0.6, 1.0, 0.5), target=(0, 650, 1350), height=1100))
    App.closeDocument(doc.Name)
    build()
    return out
