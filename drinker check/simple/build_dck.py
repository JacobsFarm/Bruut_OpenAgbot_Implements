"""Model of the drinking trough check on the Bruut OpenAgbot (standard robot).

Mast, carriage and hinge from "fence inspector/simple" (fin_parts); this file adds the long arm with the sensor head,
the tank with its pump and the trough for the renders.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_dck
    build_dck.build()                       # saves FCStd and STEP (work pose: head over the trough)
    build_dck.set_pose(z=1100, swing=80)    # carriage height (mm) and arm swing (deg, + = back): park pose
    build_dck.check_interference()          # overlap in the current pose (must be empty)
    build_dck.check_holes()                 # pins and bolts in their holes (must be empty)
    build_dck.check_poses()                 # overlap over height x swing x steering +-30 (must be empty)
    build_dck.check_trough()                # head and nozzle inside the trough, clear of its walls
    build_dck.mass_properties()
    build_dck.render_all()                  # all images in previews/
"""
