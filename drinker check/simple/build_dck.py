_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True, z=P.head_work_z, swing=0.0):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Drinker check simple"
    doc.Comment = ("Generated by build_dck.py from dck_params.py (mast and carriage from fence inspector/simple). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0. Work pose (head over "
                   "the trough); build_dck.set_pose() moves it.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, z, swing)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("bar_bolts", "cross_bars"), ("plate_bolts", "base_plate"), ("screw", "screw_blocks"), ("screw", "carriage"), ("hinge_pin", "carriage"),
          ("hinge_pin", "arm"), ("base_plate", "mast"), ("gussets", "mast"), ("gussets", "base_plate")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return bool({"plate_bolts", "bar_bolts"} & {a, b}) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    out = {}
    for a, b in JOINTS:
        if b in ("mast", "base_plate") and a in ("base_plate", "gussets"):
            continue                                # welded, touching faces
        if a in objs and b in objs and objs[a].BoundBox.intersect(objs[b].BoundBox):
            v = objs[a].common(objs[b]).Volume
            if v > tol:
                out[str((a, b))] = round(v, 1)
    return out


def check_poses(doc=None, tol=1.0, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Carriage and arm against the mount and the robot over head height x arm swing x steering. Must be empty."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Carriage")
    names = {o.Name for o in moving}
    others = [o for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    arm_names = {o.Name for o in objects_of(doc, "Arm")}
    out = {}
    for st in steer:
        set_steering(st, doc)
        fixed = [(o, global_shape(o)) for o in others]
        for z in (P.F.Z_RANGE[0], P.head_work_z, P.head_park_z):
            for sw in (0.0, P.swing_park / 2.0, P.swing_park):
                set_pose(z, sw, doc)
                mv = [(o, global_shape(o)) for o in moving]
                pairs = [(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)]
                pairs += [(a, b) for a in mv for b in mv if a[0].Name in arm_names and b[0].Name not in arm_names
                          and not _joint(a[0].Name, b[0].Name)]
                hits = _overlaps(pairs, tol)
                if hits:
                    out[str((st, z, sw))] = hits
    set_steering(0.0, doc)
    set_pose(P.head_work_z, 0.0, doc)
    return out


def check_trough(doc=None, tol=1.0):
    """Work pose over the trough: arm, head, sensors and nozzle against the trough walls (must be empty); nozzle tip
    and sensor height over the water."""
    doc = active_doc(doc)
    set_pose(P.head_work_z, 0.0, doc)
    tr = G.trough()
    hits = {}
    for n in ("arm", "head", "sensors", "nozzle"):
        s = global_shape(doc.getObject(n))
        if s.BoundBox.intersect(tr.BoundBox):
            v = s.common(tr).Volume
            if v > tol:
                hits[n] = round(v, 1)
    noz = global_shape(doc.getObject("nozzle")).BoundBox
    sen = global_shape(doc.getObject("sensors")).BoundBox
    return {"hits": hits, "nozzle_over_water_mm": round(noz.ZMin - P.water_z),
            "sensor_over_water_mm": round(sen.ZMin - P.water_z),
            "nozzle_inside_rim": P.trough_x[0] < noz.XMin and noz.XMax < P.trough_x[1]}


MASS_FIXED = {"stepper": 1.2, "head": 0.8, "sensors": 0.3, "pump": 2.5}
DENSITY = (("pads", P.pe), ("tank", P.pe))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Carriage"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m)
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


