def add_scene(doc):
    obj = doc.addObject("Part::Feature", GROUND)
    obj.Shape = G.box_span((-1100.0, 1700.0), (-1500.0, 1500.0), (-40.0, 0.0))
    obj.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    obj.ViewObject.Transparency = 30
    t = doc.addObject("Part::Feature", TROUGH)
    t.Shape = G.trough()
    t.ViewObject.ShapeColor = COLOR["trough"]
    w = doc.addObject("Part::Feature", WATER)
    w.Shape = G.water()
    w.ViewObject.ShapeColor = COLOR["water"]
    w.ViewObject.Transparency = 40


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


