"""Animation: the Bruut OpenAgbot scouts 4 potato rows with the 3.0 m camera hood and folds the wings at the headland.

The robot drives along the ridges at 1 m/s; the haulm passes through the strip curtains into the hood, the 10
cameras photograph every plant. A plant with symptoms gets a red flag in the map as soon as the cameras have passed
it (in the field nothing is marked). At the end of the rows the robot stops and both wings swing forward (the
actuators push them round the kingpins in 7.4 s): 1.20 m wide for the headland and the road. Timing and swing come
from dsc_field / dsc_calc, the same figures as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, scout from
build_dsc, ridges, plants, flags.

Use in FreeCAD:
    import animate_dsc
    animate_dsc.build()                              # build the document
    animate_dsc.play()                               # play live, animate_dsc.stop()
    animate_dsc.summary()                            # key figures of the run
    animate_dsc.render_all(r"C:\\temp\\dsc_frames")
    import make_gif_dsc; make_gif_dsc.main(r"C:\\temp\\dsc_frames", r"previews\\animation_potato_scouting.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import dsc_params as P
import dsc_calc as C
import dsc_parts as G
import dsc_field as F
import build_dsc

DOC_NAME = "Disease_scout_on_robot_animation"
FPS = 5                         # frames per second of real time; the GIF plays at 10 fps = 2 x speed
COLOR = {"soil": (0.55, 0.42, 0.30), "plant": (0.25, 0.52, 0.20), "sick": (0.70, 0.62, 0.20),
         "flag": (0.90, 0.12, 0.10)}

_timer = None
_play = {}


def prepare(fps=FPS):
    pl = F.plants()
    n = int(math.ceil(F.total_time() * fps)) + 1
    frames = []
    for k in range(n):
        f = F.frame_state(k / float(fps), pl)
        f["spin"] = (f["y"] - F.Y_START) / (P.robot_tire_d / 2.0)
        f["spin_castor"] = (f["y"] - F.Y_START) / (P.castor_wheel[0] / 2.0)
        frames.append(f)
    return frames


def build():
    if build_dsc.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_dsc.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Disease scout on robot - animation"
    doc.Comment = "Generated by animate_dsc.py. Robot from agbot design, scout from build_dsc."
    robot = build_dsc.build_robot(doc)
    build_dsc.build_into(doc, robot)
    build_dsc.set_robot_visible(True, doc)
    ridges = doc.addObject("Part::Feature", "anim_ridges")
    ridges.Shape = G.ridges(F.X_FIELD, F.Y_FIELD)
    ridges.ViewObject.ShapeColor = COLOR["soil"]
    healthy, sick = [], []
    for (x, y, t, s, ill) in F.plants():
        (sick if ill else healthy).append(G.plant(x, y, t, s))
    for name, shapes, color in (("anim_plants", healthy, "plant"), ("anim_sick", sick, "sick")):
        o = doc.addObject("Part::Feature", name)
        o.Shape = Part.makeCompound(shapes)
        o.ViewObject.ShapeColor = COLOR[color]
    o = doc.addObject("Part::Feature", "anim_flags")
    o.ViewObject.ShapeColor = COLOR["flag"]
    doc.recompute()
    return doc


def apply_frame(doc, f):
    doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    ya, za = G.castor_axle_y(), P.castor_wheel[0] / 2.0
    crot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin_castor"]))
    for tag in ("right", "left"):
        for name in ("Castor_wheel_", "Wing_castor_wheel_"):
            doc.getObject(name + tag).Placement = App.Placement(V(0, 0, 0), crot, V(0, ya, za))
    for name, pl in build_dsc.pose_placements(f["beta"], f["beta"]).items():
        doc.getObject(name).Placement = pl
    flags = [G.flag(x, y, t - 60.0) for (x, y, t) in f["sick"]]
    doc.getObject("anim_flags").Shape = Part.makeCompound(flags) if flags else Part.Shape()


CAM_A = ((-3600.0, -4600.0, 3900.0), (200.0, 500.0, 400.0))     # eye and target relative to the robot centre


def track_camera(f, fov=45.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


STATE = {"start": "ready at the start of the rows", "scout": "scouting: 10 cameras, LED flash 200 µs",
         "fold": "headland: wings swing forward", "done": "folded: 1.20 m wide for the headland and the road"}


def meta(f):
    return {"t": round(f["t"], 2), "phase": f["phase"], "state": STATE[f["phase"]],
            "v": P.speed if f["moving"] else 0.0, "beta": round(f["beta"], 1), "seen": f["seen"],
            "sick": len(f["sick"]), "images": f["images"], "driven_m": round(f["driven_m"], 2),
            "area_m2": round(f["area_m2"], 1), "width_m": round(C.width(f["beta"]) / 1000.0, 2)}


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    s["max_beta"] = round(max(f["beta"] for f in frames), 1)
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i])
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=1.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))
