"""Model of the counterweights on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_cwt
    build_cwt.build()                      # saves FCStd and STEP (2 plates per stack, front and rear)
    build_cwt.build(front=4, rear=0)       # plates per stack
    build_cwt.check_interference()         # overlap (must be empty)
    build_cwt.clearance()                  # smallest distance to the steering stacks and the GNSS dome
    build_cwt.mass_properties()
    build_cwt.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import cwt_params as P
import cwt_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Counterweights"
SAVE_BASE = os.path.join(FOLDER, "Counterweights")
ROOT = "Counterweights"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "ballast": (0.30, 0.31, 0.33),
    "plastic": (0.10, 0.10, 0.10),
}


# ---------------------------------------------------------------------
# Tree helpers
# ---------------------------------------------------------------------
def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj





def build_end(doc, parent, end, n):
    grp = new_part(doc, parent, end.capitalize(), "counterweight_%s_%dx%d_plates" % (end, 2, n))
    for sx, tag in ((-1, "left"), (1, "right")):
        k = "%s_%s" % (end, tag)
        add_shape(doc, grp, "base_" + k, "base_plate_15mm_studs_M16_" + k, G.base(end, sx), "frame")
        add_shape(doc, grp, "bolts_" + k, "base_bolts_M10_4x_" + k, G.base_bolts(end, sx), "zinc")
        for i in range(n):
            add_shape(doc, grp, "plate_%s_%d" % (k, i), "ballast_plate_11kg_%s_%d" % (k, i), G.plate(end, sx, i),
                      "ballast")
        bar, knobs = G.clamp(end, sx, n)
        add_shape(doc, grp, "clamp_" + k, "clamp_bar_40x12_" + k, bar, "zinc")
        add_shape(doc, grp, "knobs_" + k, "knob_nuts_M16_" + k, knobs, "plastic")
    return grp


def build_into(doc, parent=None, front=P.DRAW["front"], rear=P.DRAW["rear"]):
    """Put the counterweights in a document, in robot coordinates."""
    root = new_part(doc, parent, ROOT, "counterweights_simple")
    if front:
        build_end(doc, root, "front", front)
    if rear:
        build_end(doc, root, "rear", rear)
    return root


def build_robot(doc):
    """Real robot model from 'agbot design' (read only)."""
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True, front=P.DRAW["front"], rear=P.DRAW["rear"]):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Counterweights simple"
    doc.Comment = ("Generated by build_cwt.py from cwt_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0. Plates per stack: build(front=, rear=).")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, front, rear)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


