"""Model of the asparagus harvester under the belly of the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_asp
    build_asp.build()                      # saves FCStd and STEP
    build_asp.set_tool(x=60, tip=180)      # carriage x and tube tip height (180 = cutting, 1000 = retracted)
    build_asp.check_interference()         # must be empty
    build_asp.check_poses()                # x +-120, tip 180 / 1000, front wheels at +-30 deg: empty
    build_asp.check_holes()
    build_asp.mass_properties()
    build_asp.render_all()
"""
import os
import sys

import FreeCAD as App
