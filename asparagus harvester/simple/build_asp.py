from FreeCAD import Vector as V

import asp_params as P
import asp_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Asparagus_Harvester"
SAVE_BASE = os.path.join(FOLDER, "Asparagus_Harvester")
ROOT = "Asparagus_harvester"

COLOR = {"frame": (0.93, 0.42, 0.08), "zinc": (0.82, 0.84, 0.87), "alu": (0.80, 0.81, 0.83),
         "steel": (0.55, 0.56, 0.58), "motor": (0.12, 0.12, 0.13), "hood": (0.15, 0.15, 0.17),
         "led": (0.95, 0.95, 0.70), "crate": (0.10, 0.40, 0.75), "soil": (0.45, 0.33, 0.22),
         "spear": (0.95, 0.93, 0.85), "rail": (0.70, 0.72, 0.74)}


def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "asparagus_harvester_simple")
    mt = new_part(doc, root, "asp_Mount", "belly_rails_gantry_hood")
    add_shape(doc, mt, "asp_rails", "belly_rails_40x40x3", G.rails(), "frame")
    add_shape(doc, mt, "asp_rail_bolts", "rail_bolts_8xM10", G.rail_bolts(), "zinc")
    add_shape(doc, mt, "asp_gantry", "x_gantry_40x40x3", G.gantry(), "frame")
    add_shape(doc, mt, "asp_lin_rail", "x_rail_HGR15", G.lin_rail(), "rail")
    add_shape(doc, mt, "asp_x_motor", "x_motor_NEMA23", G.x_motor(), "motor")
    add_shape(doc, mt, "asp_hood_plate", "camera_hood_plate_8mm", G.hood_plate(), "frame")
    add_shape(doc, mt, "asp_hood", "camera_hood_2mm", G.hood(), "hood")
    add_shape(doc, mt, "asp_camera", "camera_LED_bars_line_laser", G.camera(), "led")
    cr = new_part(doc, mt, "asp_Carriage", "x_carriage_with_z_axis")
    add_shape(doc, cr, "asp_carriage", "x_carriage_plate", G.carriage(), "alu")
    add_shape(doc, cr, "asp_z_profile", "z_profile_40x80", G.z_profile(), "alu")
    add_shape(doc, cr, "asp_z_motor", "z_motor_NEMA23", G.z_motor(), "motor")
    tl = new_part(doc, cr, "asp_Tool", "tool_slide_moves_in_z")
    add_shape(doc, tl, "asp_slide", "z_slide_clamps", G.slide(), "alu")
    add_shape(doc, tl, "asp_tube", "knife_tube_D30_gripper_motor", G.tube(), "steel")
    add_shape(doc, tl, "asp_bin", "spear_bin", G.spear_bin(), "crate")
    dk = new_part(doc, root, "asp_Deck", "rear_deck_crate")
    add_shape(doc, dk, "asp_cross_tubes", "cross_tubes_60x40x3", G.cross_tubes(), "frame")
    add_shape(doc, dk, "asp_cross_bolts", "cross_tube_bolts_8xM10", G.cross_bolts(), "zinc")
    add_shape(doc, dk, "asp_deck_spacers", "deck_spacers", G.deck_spacers(), "frame")
    add_shape(doc, dk, "asp_deck", "deck_plate_4mm", G.deck(), "alu")
    add_shape(doc, dk, "asp_crate", "crate_600x380x240", G.crate(), "crate")
    return root


def set_tool(x=0.0, tip=P.tip_top, doc=None):
    doc = active_doc(doc)
    doc.getObject("asp_Carriage").Placement = App.Placement(V(x, 0, 0), App.Rotation())
    doc.getObject("asp_Tool").Placement = App.Placement(V(0, 0, tip - P.tip_top), App.Rotation())
    doc.recompute()


def build_robot(doc):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Asparagus harvester simple"
    doc.Comment = ("Generated by build_asp.py from asp_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


_J = [("rail_bolts", "rails"), ("gantry", "rails"), ("lin_rail", "gantry"), ("x_motor", "gantry"),
      ("hood_plate", "rails"), ("hood", "hood_plate"), ("camera", "hood"), ("camera", "hood_plate"),
      ("carriage", "lin_rail"), ("z_profile", "carriage"), ("z_motor", "z_profile"), ("slide", "z_profile"),
      ("slide", "tube"), ("bin", "tube"), ("bin", "slide"), ("cross_bolts", "cross_tubes"),
      ("deck_spacers", "cross_tubes"), ("deck_spacers", "deck"), ("crate", "deck")]
JOINTS = {("asp_" + a, "asp_" + b) for a, b in _J}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x == "asp_cross_bolts" and y.startswith("upper_beam"):
            return True
        if x in ("asp_rail_bolts", "asp_rails") and y.startswith("lower_beam"):
            return True
    return False


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        vol = sa.common(sb).Volume
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def _steer(doc, st):
    for name in ("FL_steered", "FR_steered"):
        o = doc.getObject(name)
        if o is not None:
            o.Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), st))
    doc.recompute()


def check_poses(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    moving = objects_of(doc, "asp_Carriage")
    mn = {o.Name for o in moving}
    for x in (-P.x_travel, P.x_travel):
        for tip in (P.tip_work, P.tip_top):
            set_tool(x, tip, doc)
            for st in ((-P.robot_steer_max, P.robot_steer_max) if tip == P.tip_work else (0.0,)):
                _steer(doc, st)
                fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in mn]
                mv = [(o, global_shape(o)) for o in moving]
                hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
                if hits:
                    out["x%+d_tip%d_st%+d" % (x, tip, st)] = hits
    _steer(doc, 0.0)
    set_tool(0.0, P.tip_top, doc)
    return out


def check_holes(doc=None):
    doc = active_doc(doc)
    bad = []
    upper = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith("upper_beam")]
    for (x, y) in G.BOLTS:
        rod = Part.makeCylinder(4.5, 60.0, V(x, y, 650.0))
        v = sum(rod.common(b).Volume for b in upper)
        if v > 1.0:
            bad.append(("upper", x, y, round(v)))
    lower = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith("lower_beam")]
    for (x, y) in G.FG.RAIL_BOLTS:
        rod = Part.makeCylinder(4.5, 80.0, V(x, y, 600.0))
        v = sum(rod.common(b).Volume for b in lower)
        if v > 1.0:
            bad.append(("lower", x, y, round(v)))
    return bad


DENSITY = {"asp_carriage": P.alu, "asp_z_profile": 0.45 * P.alu, "asp_slide": P.alu, "asp_deck": P.alu,
           "asp_hood": P.alu, "asp_crate": 0.95e-6, "asp_bin": 0.95e-6, "asp_camera": 1.5e-6}
MASS_FIXED = {"asp_x_motor": 1.4, "asp_z_motor": 1.4}


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "asp_Carriage"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            s = global_shape(o)
            mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
            m += mo
            c += s.BoundBox.Center * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def set_camera(direction, target=None, height=None, up=(0.0, 0.0, 1.0)):
    import FreeCADGui as Gui
    from pivy import coin
    view = Gui.getDocument(DOC_NAME).ActiveView
    view.setCameraType("Orthographic")
    d = V(*direction)
    d.normalize()
    cam = view.getCameraNode()
    tgt = V(*target) if target is not None else V(0, 0, 800)
    eye = tgt - d * 12000.0
    cam.position.setValue(coin.SbVec3f(eye.x, eye.y, eye.z))
    cam.pointAt(coin.SbVec3f(tgt.x, tgt.y, tgt.z), coin.SbVec3f(*up))
    cam.nearDistance.setValue(10.0)
    cam.farDistance.setValue(40000.0)
    if height is None:
        view.fitAll()
    else:
        cam.height.setValue(height)
    return view


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    r, gnd = G.ridge(-2500.0, 2500.0)
    sc = []
    for name, shape, col in (("render_ridge", r, COLOR["soil"]), ("render_ground", gnd, (0.38, 0.28, 0.19)),
                             ("render_spears", G.spears(-2500.0, 2500.0), COLOR["spear"])):
        o = doc.addObject("Part::Feature", name)
        o.Shape = shape
        o.ViewObject.ShapeColor = col
        sc.append(o)
    set_tool(30.0, P.tip_work, doc)
    out.append(save_view("1_iso_on_the_ridge.png", (-1.0, -1.0, -0.7), target=(0, 0, 600), height=2900))
    out.append(save_view("2_front_cutting.png", (0.0, -1.0, 0.0), target=(0, 0, 700), height=1900))
    sc[0].ViewObject.Transparency = 60
    out.append(save_view("3_side_cutting.png", (-1.0, 0.0, 0.0), target=(0, -150, 750), height=1900))
    for o in sc:
        doc.removeObject(o.Name)
    set_tool(30.0, P.tip_top, doc)
    out.append(save_view("4_side_retracted.png", (-1.0, 0.0, 0.0), target=(0, -150, 850), height=2100))
    set_robot_visible(False, doc)
    set_tool(30.0, P.tip_work, doc)
    out.append(save_view("5_gantry_tool_detail.png", (-0.8, 1.0, -0.6), target=(30, -80, 600), height=1300))
    App.closeDocument(doc.Name)
    build()
    return out
