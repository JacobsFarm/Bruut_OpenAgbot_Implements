"""Model of the concentrate dispenser on the Bruut OpenAgbot, together with the feed pusher auger V3 (imported).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_cdd
    build_cdd.build()                      # saves FCStd and STEP (dispenser only in the STEP)
    build_cdd.check_interference()         # overlap: dispenser parts, against the robot and the feed pusher (empty)
    build_cdd.check_holes()                # bolts in their holes (empty)
    build_cdd.set_auger(90)                # turn the auger (degrees)
    build_cdd.mass_properties()
    build_cdd.render_all()                 # all images in previews/
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import cdd_params as P
import cdd_parts as G
import build_fpa as BF

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Concentrate_Dispenser"
SAVE_BASE = os.path.join(FOLDER, "Concentrate_Dispenser")
ROOT = "Concentrate_dispenser"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "stainless": (0.86, 0.87, 0.88),
    "cell": (0.55, 0.60, 0.65),
    "motor": (0.12, 0.12, 0.13),
    "auger": (0.95, 0.70, 0.05),
    "rubber": (0.10, 0.10, 0.10),
    "sensor": (0.15, 0.35, 0.75),
    "lid": (0.80, 0.82, 0.84),
}


def new_part(doc, parent, name, label, placement=None):
    return BF.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True, transparency=0):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
        obj.ViewObject.Transparency = transparency
    return obj


def auger_placement(angle=0.0):
    return App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), angle), V(0, 0, P.auger_z))


def build_into(doc, parent=None, angle=0.0):
    root = new_part(doc, parent, ROOT, "concentrate_dispenser_simple")
    mount = new_part(doc, root, "cdd_Mount", "cross_tubes_load_cells_legs_frame")
    add_shape(doc, mount, "cdd_bars", "cross_tubes_40x40x3_y325", G.bars(), "frame")
    add_shape(doc, mount, "cdd_bar_bolts", "cross_tube_bolts_8xM10", G.bar_bolts(), "zinc")
    add_shape(doc, mount, "cdd_cells", "load_cells_shear_beam_4x50kg", G.load_cells(), "cell")
    add_shape(doc, mount, "cdd_cell_bolts", "load_cell_bolts_8xM8", G.cell_bolts(), "zinc")
    add_shape(doc, mount, "cdd_legs", "legs_30x30x2", G.legs(), "frame")
    add_shape(doc, mount, "cdd_frame", "hopper_frame_30x30x2", G.frame(), "frame")
    hop = new_part(doc, root, "cdd_Hopper", "hopper_47l_stainless_trough_tube")
    add_shape(doc, hop, "cdd_hopper", "hopper_stainless_1_5_60deg_U_trough", G.hopper(), "stainless")
    add_shape(doc, hop, "cdd_lid", "lid_hinged", G.lid(), "lid")
    add_shape(doc, hop, "cdd_level", "level_sensor_capacitive_M30", G.level_sensor(), "sensor")
    add_shape(doc, hop, "cdd_tube", "auger_tube_60x2_outlet_stub", G.tube(), "stainless")
    add_shape(doc, hop, "cdd_spout", "rubber_spout_O64_hose_clamp", G.spout(), "rubber")
    add_shape(doc, hop, "cdd_tie", "tie_rod_O12_frame_to_tube_end", G.tie_rod(), "zinc")
    drv = new_part(doc, root, "cdd_Drive", "nema23_planetary_10_1_bearing_flange")
    add_shape(doc, drv, "cdd_flange", "bearing_flange_80_UC_insert", G.flange(), "zinc")
    add_shape(doc, drv, "cdd_motor", "nema23_planetary_10_1", G.motor(), "motor")
    aug = new_part(doc, root, "cdd_Auger", "metering_auger_O54_pitch_50", auger_placement(angle))
    add_shape(doc, aug, "cdd_auger", "auger_flight_O54_core_O16_shaft_O20", G.auger(), "auger")
    return root


def set_auger(angle=0.0, doc=None):
    doc = active_doc(doc)
    doc.getObject("cdd_Auger").Placement = auger_placement(angle)
    doc.recompute()


def build(save=True, show_robot=False, step=True, with_pusher=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Concentrate dispenser simple"
    doc.Comment = ("Generated by build_cdd.py from cdd_params.py, with the feed pusher auger V3 (build_fpa). Robot "
                   "coordinates: x = right (feed fence), y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BF.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    if with_pusher:
        BF.build_into(doc, robot)
    build_into(doc, robot)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def others(doc):
    """Robot and feed pusher objects."""
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    pusher = {o.Name for o in objects_of(doc, "Feed_pusher")}
    for o in others(doc):
        if o.Name not in pusher:
            o.ViewObject.Visibility = visible


def set_pusher_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in objects_of(doc, "Feed_pusher"):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("cdd_bar_bolts", "cdd_bars"), ("cdd_cell_bolts", "cdd_bars"), ("cdd_cell_bolts", "cdd_cells"),
          ("cdd_auger", "cdd_motor"), ("cdd_level", "cdd_hopper"), ("cdd_tie", "cdd_frame"), ("cdd_tie", "cdd_tube")}
BEAM_BOLTS = ("cdd_bar_bolts",)


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x in BEAM_BOLTS and y.startswith("upper_beam"):
            return True
    return False


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        try:
            vol = sa.common(sb).Volume
        except Exception as exc:
            hits.append((oa.Name, ob.Name, "error %s" % exc))
            continue
        if vol > tol:
            hits.append((oa.Name, ob.Name, round(vol, 1)))
    return hits


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    rest = [(o, global_shape(o)) for o in others(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in rest if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """Bolts in their holes: JOINTS bolt pairs and the cross-tube bolts against the upper beams (~0)."""
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    for o in others(doc):
        if o.Name.startswith("upper_beam"):
            objs[o.Name] = global_shape(o)
    pairs = {p for p in JOINTS if "bolts" in p[0]}  # level sensor sits in a gland, tie rod ends in eyes
    pairs |= {("cdd_bar_bolts", n) for n in objs if n.startswith("upper_beam")}
    out = {}
    for a, b in sorted(pairs):
        if a in objs and b in objs and objs[a].BoundBox.intersect(objs[b].BoundBox):
            v = objs[a].common(objs[b]).Volume
            if v > tol:
                out[str((a, b))] = round(v, 1)
    beams = [n for n in objs if n.startswith("upper_beam")]
    out["bolts_in_upper_beams"] = sum(1 for s in objs["cdd_bar_bolts"].Solids
                                      for n in beams if s.BoundBox.intersect(objs[n].BoundBox))
    return out


def clearance(doc=None):
    """Smallest distance (mm) of tube, spout and tie rod to the robot and the feed pusher."""
    doc = active_doc(doc)
    rest = [(o, global_shape(o)) for o in others(doc) if not o.Name.endswith(("tire", "rim"))]
    out = {}
    for n in ("cdd_tube", "cdd_spout", "cdd_tie", "cdd_motor"):
        s = global_shape(doc.getObject(n))
        best = (1e9, None)
        for o, so in rest:
            if s.BoundBox.isValid() and so.BoundBox.isValid():
                bb = s.BoundBox
                bb.enlarge(300)
                if not bb.intersect(so.BoundBox):
                    continue
            d = s.distToShape(so)[0]
            if d < best[0]:
                best = (d, o.Name)
        out[n] = (round(best[0], 1), best[1])
    return out


MASS_FIXED = {"cdd_cells": 4 * 0.45, "cdd_motor": 1.0 + 0.9, "cdd_flange": 0.6, "cdd_level": 0.2}
DENSITY = (("cdd_hopper", P.stainless), ("cdd_lid", P.stainless), ("cdd_tube", P.stainless), ("cdd_spout", P.rubber))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "cdd_Mount", "cdd_Hopper", "cdd_Drive", "cdd_Auger"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


