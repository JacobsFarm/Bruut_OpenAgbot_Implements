set_camera = BF.set_camera


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_floor", "render_windrow", "render_pellets", "render_fence", "render_falling")


def add_scene(doc):
    y0, y1 = -2600.0, 1800.0
    def put(name, shape, color, tr=0):
        o = doc.addObject("Part::Feature", name)
        o.Shape = shape
        o.ViewObject.ShapeColor = color
        o.ViewObject.Transparency = tr
        return o
    put(SCENE[0], G.box_span((-1400.0, 1500.0), (y0, y1), (-40.0, 0.0)), (0.62, 0.62, 0.60))
    put(SCENE[1], G.windrow(y0, y1), (0.55, 0.62, 0.25))
    # pellets only on the part of the windrow the robot has passed (it drives in -y): from the spout forward
    put(SCENE[2], G.pellet_line(0.0, y1, z=250.0, n=90), (0.60, 0.42, 0.20))
    put(SCENE[3], G.fence(y0, y1), (0.30, 0.55, 0.35))
    put(SCENE[4], G.falling_pellets(), (0.60, 0.42, 0.20))


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_on_robot_at_fence.png", (-1.0, 1.0, -0.6), target=(300, -200, 600), height=2900))
    out.append(save_view("2_front_along_fence.png", (0.0, -1.0, -0.05), target=(350, 0, 600), height=1700))
    out.append(save_view("3_side_from_fence.png", (-1.0, 0.0, -0.1), target=(0, -200, 600), height=2500))
    for n in SCENE:
        if doc.getObject(n):
            doc.removeObject(n)
    set_pusher_visible(False, doc)
    doc.getObject("cdd_hopper").ViewObject.Transparency = 65
    doc.getObject("cdd_lid").ViewObject.Visibility = False
    doc.getObject("cdd_tube").ViewObject.Transparency = 65
    out.append(save_view("4_hopper_auger_see_through.png", (-1.0, -0.8, -0.55), target=(250, 0, 850), height=1300))
    set_robot_visible(False, doc)
    doc.getObject("cdd_hopper").ViewObject.Transparency = 0
    doc.getObject("cdd_tube").ViewObject.Transparency = 0
    doc.getObject("cdd_lid").ViewObject.Visibility = True
    out.append(save_view("5_mount_load_cells.png", (-1.0, -1.2, -0.45), target=(0, 0, 850), height=1500))
    out.append(save_view("6_outlet_and_drive.png", (0.0, -1.0, -0.15), target=(250, 0, 750), height=1500))
    App.closeDocument(doc.Name)
    build()
    return out
