def track_camera(i, fov=40.0):
    import FreeCADGui as Gui
    from pivy import coin
    eye, tgt = _s["cam"][i]
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(200.0)
    cam.farDistance.setValue(200000.0)


SEAM_DIST = 16000.0                 # camera verder weg: naden en sleuven verborgen (moire), alleen de baanstroken


def cam_dist(i):
    eye, tgt = _s["cam"][i]
    return math.sqrt(sum((a - b) ** 2 for a, b in zip(eye, tgt)))


def set_detail(i, doc=None):
    doc = doc or _s["doc"]
    vis = cam_dist(i) <= SEAM_DIST
    if not _changed("seams", vis):
        return
    for p in range(1, P.N_PASSES + 1):
        for name in ("anim_closed_%d", "anim_slot_%d", "anim_flow_%d"):
            doc.getObject(name % p).ViewObject.Visibility = vis


def meta(f):
    r = f["ref"]
    return {"t": round(f["t"], 2), "speed": round(f["speed"], 2), "w_text": f["w_text"], "r_text": r["text"],
            "level": round(f["level"], 2), "full": _s["run"]["scn"]["rx_full"], "tank_cap": round(G.tank_volume_l()),
            "ref_tank": [round(r["tank"][0], 1), r["tank"][1]], "ref_flow_lpm": round(60.0 * r["flow"]),
            "refills": r["count"], "lift": round(f["lift"]), "rpm": round(f["rpm"]), "v": round(f["v"]),
            "applied": round(f["applied"], 2), "pass_pos": f["pass_pos"], "rear": [round(c) for c in f["rear"]],
            "centre": [round(c) for c in f["centre"]], "psi": round(f["psi"], 1),
            "ref_pose": [round(c) for c in r["pose"]], "ref_state": r["state"], "mode": f["mode"],
            "slots": {str(p): [None if v is None else round(v) for v in s] for p, s in f["slots"].items()}}


def plan_meta():
    run = _s["run"]
    return {"key": run["key"], "title": run["scn"]["title"], "short": run["scn"]["short"], "order": run["order"],
            "passes": P.N_PASSES, "w": P.W, "len": P.FIELD_LEN, "ys": P.YS, "y_turn": P.Y_TURN, "r": P.R,
            "dose": P.DOSE, "kind": run["ref_kind"], "fps": P.VIDEO_FPS, "visits": [run["order"][i] for i in run["visits"]],
            "turns": {str(k): [[round(x), round(y)] for x, y in v[::6]] for k, v in _s["turns"].items()},
            "station_dock_x": F.station_dock_x()}


def render_frames(folder, first=0, count=None, size=None, only=None):
    import FreeCADGui as Gui
    size = size or P.SIZE
    doc = _s["doc"]
    Gui.setActiveDocument(doc.Name)
    frames = _s["run"]["frames"]
    os.makedirs(folder, exist_ok=True)
    if first == 0:
        with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8", newline="\n") as handle:
            json.dump({"plan": plan_meta(), "frames": [meta(f) for f in frames]}, handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        if only is not None and (cam_dist(i) > SEAM_DIST) != (only == "far"):
            continue
        apply_frame(i)
        track_camera(i)
        set_detail(i)
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, size=None, log=None, only=None):
    """Alle frames; only "far" / "near": alleen de frames met de camera verder / dichter dan SEAM_DIST (na een
    wijziging die alleen daar te zien is)."""
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 50, size, only)
        if log:
            with open(log, "a", encoding="utf-8", newline="\n") as handle:
                handle.write("%d/%d\n" % (first, total))
    return total


def summary():
    return F.summary(_s["run"])


SKIP_CHECK = ("_liquid", "anim_")


def _solids(root):
    out = []
    for o in root.OutListRecursive:
        if o.TypeId != "Part::Feature" or o.Shape.isNull() or o.Name.endswith(SKIP_CHECK) or \
                o.Name.startswith(SKIP_CHECK) or "liquid" in o.Name:
            continue
        if o.ViewObject is not None and not o.ViewObject.Visibility:
            continue
        out.append(o)
    return out


def check_fit(near=4500.0, step=1, tol=1.0, log=None, only=None):
    """Overlap tussen de refiller (robot, kit, aanhanger of station) en de werkrobot (robot, pomp, applicator, tank)
    in elk 'step'-de frame waarin hun middens minder dan 'near' uit elkaar liggen. Geeft {frame: [(a, b, mm3)]} en
    het aantal gecontroleerde frames; moet leeg zijn. only: alleen deze frames."""
    doc = _s["doc"]
    frames = _s["run"]["frames"]
    worker = _solids(_s["robot"])
    ref = _solids(_s["ref"]["root"])
    out, n, last = {}, 0, None
    for i in (only if only is not None else range(0, len(frames), step)):
        f = frames[i]
        cx, cy = f["centre"]
        rx, ry = f["ref"]["pose"]
        key = (round(cx), round(cy), round(f["psi"], 1), round(rx), round(ry), round(f["lift"]),
               f["ref"].get("boom") and tuple(round(v) for v in f["ref"]["boom"]))
        if math.hypot(cx - rx, cy - ry) > near or key == last:
            continue
        last = key
        n += 1
        apply_frame(i)
        a = [(o, B.global_shape(o)) for o in ref]
        b = [(o, B.global_shape(o)) for o in worker]
        hits = []
        for oa, sa in a:
            for ob, sb in b:
                if sa.BoundBox.intersect(sb.BoundBox):
                    vol = sa.common(sb).Volume
                    if vol > tol:
                        hits.append((oa.Label, ob.Label, round(vol, 1)))
        if hits:
            out[i] = hits
        if log:
            with open(log, "a", encoding="utf-8", newline="\n") as handle:
                handle.write("frame %d hits %s\n" % (i, hits))
    return out, n


def stop():
    if _s.get("timer") is not None:
        _s["timer"].stop()
        _s["timer"] = None


def play(loop=False, follow=True, every=2):
    import FreeCADGui as Gui
    from PySide import QtCore
    stop()
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    n = len(_s["run"]["frames"])
    _s["index"] = 0

    def step():
        try:
            if _s["index"] >= n:
                if loop:
                    _s["index"] = 0
                else:
                    stop()
                    return
            k = _s["index"]
            _s["index"] += every
            apply_frame(k)
            if follow:
                track_camera(k)
                set_detail(k)
        except Exception:
            stop()
            raise

    timer = QtCore.QTimer()
    timer.timeout.connect(step)
    timer.start(int(1000 * every / P.VIDEO_FPS))
    _s["timer"] = timer
