"""Animatie: de Bruut met de precisie-applicator V2 (5 rijen) werkt een heel veld af en wordt bijgevuld.

Per scenario (fld_params.SCENARIOS: simple, liquid, station) een apart document met de werkrobot, de refiller en het
veld. Het rijplan en de simulatie staan in fld_plan.py (zuiver rekenwerk); hier worden de frames op het model gezet:
- werkrobot: positie en koers, sturen voor, wielen rollen; applicator heft en zakt (parallellogram, actuator,
  slangen), schijven en aandrukwielen draaien in de grond, de rollenpomp draait mee met de rijsnelheid;
- werktank: vloeistofniveau;
- veld: per baan een donkerder strook waar de messen in de grond waren, open sleuven met vloeistof tussen mes en
  aandrukwiel en de dichtgedrukte naad erachter; op de kopakker de route van de volgende bocht;
- refiller: IBC-robot (verrijden, IBC-niveau, straal), robot met giek (verrijden, giekhoek, loopkat, tuit,
  tankniveaus) of IBC-aanhanger (IBC-niveau, zwaailicht, straal).

Gebruik in FreeCAD (of met render_fld.py in een eigen FreeCAD-proces):
    import animate_fld
    animate_fld.build("simple")                     # of "liquid", "station"
    animate_fld.play()                              # live, animate_fld.stop()
    animate_fld.summary()
    animate_fld.render_all(r"C:\\temp\\fld_simple")  # frames + frames.json
    import make_video_fld; make_video_fld.main(r"C:\\temp\\fld_simple", "simple")
"""
import json
import math
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import fld_plan as F
import fld_params as P
import fld_parts as G
import build_fld as B

_s = {}
BEACON = {"green": (0.10, 0.80, 0.25), "amber": (1.00, 0.55, 0.05), "red": (0.85, 0.08, 0.06)}
BEACON_OFF = 0.28


def doc_name(key):
    return "%s_field_animation" % key


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build(key="simple", run=None):
    run = run or F.simulate(key)
    name = doc_name(key)
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    doc.Label = "Field run - %s" % run["scn"]["short"]
    doc.Comment = "Generated by animate_fld.py (no need to save)."
    f0 = run["frames"][0]
    robot = B.build_worker(doc, f0["lift"], f0["level"])
    ref = B.build_refiller(doc, run["ref_kind"], run)
    B.build_ground(doc, run)
    doc.recompute()
    turns = {}
    for mv in run["route"].moves:
        for pc in mv.pieces:
            if "turn_i" in pc.tag:
                turns.setdefault(pc.tag["turn_i"], []).extend(pc.pts)
    _s.clear()
    _s.update({"key": key, "doc": doc, "run": run, "robot": robot, "ref": ref, "turns": turns,
               "cam": F.camera_path(run), "cache": {"lift": {}, "liq": {}, "rows": {}, "ibc": {}},
               "keys": {}, "timer": None})
    apply_frame(0)
    return doc


# ---------------------------------------------------------------------
# Frame op het model
# ---------------------------------------------------------------------
def _changed(name, key):
    if _s["keys"].get(name, "unset") == key:
        return False
    _s["keys"][name] = key
    return True


def set_lift(doc, lift):
    key = round(lift / 2.0) * 2.0
    if not _changed("lift", key):
        return
    c = _s["cache"]["lift"]
    if key not in c:
        c[key] = (B.build_pa.G.actuator(key), [B.cmb2_parts.hose(i, key) for i in range(5)])
    (housing, rod, motor, pins), hoses = c[key]
    doc.getObject(B.PREFIX + "Implement").Placement = B.build_pa.implement_placement(key)
    for level, side in B.build_pa.LINKS:
        doc.getObject(B.PREFIX + B.build_pa.link_name(level, side)).Placement = B.build_pa.link_placement(level, key)
    for name, shape in (("act_housing", housing), ("act_rod", rod), ("act_motor", motor), ("act_pins", pins)):
        doc.getObject(B.PREFIX + name).Shape = shape
    for i, h in enumerate(hoses):
        doc.getObject("hose_%d" % i).Shape = h


def set_tank(doc, litres):
    key = round(litres * 2.0) / 2.0
    if not _changed("tank", key):
        return
    c = _s["cache"]["liq"]
    if key not in c:
        c[key] = G.liquid(key)
    doc.getObject("fld_rx_liquid").Shape = c[key]


def _q(v):
    return None if v is None else round(v / 50.0)


def set_slots(doc, f):
    geo = _s["run"]["geo"]
    for p, (k0, k1, p0, p1) in f["slots"].items():
        x = F.px(p)
        if _changed("band_%d" % p, (_q(k0), _q(k1))):
            doc.getObject("anim_band_%d" % p).Shape = G.band(x, k0, k1)
        if _changed("closed_%d" % p, (_q(p0), _q(p1))):
            doc.getObject("anim_closed_%d" % p).Shape = G.rows(x, geo.row_x, p0, p1, 30.0, 0.9, 1.6)
        # open sleuf met vloeistof: deel van de messtrook dat nog niet is dichtgedrukt
        if p0 is None:
            spans = [(k0, k1)]
        else:
            spans = [(k0, p0), (p1, k1)]
        key = tuple((_q(a), _q(b)) for a, b in spans)
        if _changed("slot_%d" % p, key):
            slot = [G.rows(x, geo.row_x, a, b, 14.0, 0.9, 1.4) for a, b in spans if b - a > 20.0]
            flow = [G.rows(x, geo.row_x, a, b, 6.0, 1.4, 2.0) for a, b in spans if b - a > 20.0]
            doc.getObject("anim_slot_%d" % p).Shape = Part.makeCompound(slot) if slot else Part.Shape()
            doc.getObject("anim_flow_%d" % p).Shape = Part.makeCompound(flow) if flow else Part.Shape()


def set_path(doc, f):
    """Route van de bocht na de huidige baan, als gestippelde lijn op de kopakker."""
    i = f["pass_pos"]
    pts = _s["turns"].get(i)
    if _changed("path", i):
        doc.getObject("anim_path").Shape = G.path_line(pts[::3]) if pts else Part.Shape()


def set_worker(doc, f):
    robot = _s["robot"]
    cx, cy = f["centre"]
    robot.Placement = App.Placement(V(cx, cy, 0.0), App.Rotation(V(0, 0, 1), f["psi"]))
    left, right = F.wheel_angles(f["steer"])
    doc.getObject("FL_steered").Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), left))
    doc.getObject("FR_steered").Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), right))
    for tag in F.WHEELS:
        rot = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -math.degrees(f["spin"][tag])))
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = rot
    set_lift(doc, f["lift"])
    PA = _s["run"]["geo"].PA
    doc.getObject(B.PREFIX + "Rotor").Placement = App.Placement(
        V(0, 0, 0), App.Rotation(V(1, 0, 0), -math.degrees(f["disc"])), V(0, 0, PA.shaft_z))
    B.build_pa2.set_wheels(math.degrees(f["press"]), doc, B.PREFIX)
    doc.getObject("Rotor").Placement = B.build_rp.rotor_placement(f["pump"])
    set_tank(doc, f["level"])


def set_beacon(doc, lit):
    for name, rgb in BEACON.items():
        o = doc.getObject("beacon_" + name)
        if o is not None:
            o.ViewObject.ShapeColor = rgb if name == lit else tuple(BEACON_OFF * v for v in rgb)


def set_refiller(doc, f):
    ref, r = _s["ref"], f["ref"]
    kind = ref["kind"]
    stream = None
    if kind == "simple":
        x, y = r["pose"]
        ref["root"].Placement = App.Placement(V(x, y, 0.0), App.Rotation(V(0, 0, 1), -90.0))
        rot = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -math.degrees(r["spin"])))
        for tag in ("RL", "RR", "FL", "FR"):
            for part in ("tire", "rim", "hub"):
                ref["objs"]["%s_%s" % (tag, part)].Placement = rot
        key = round(r["ibc"] / 2.0) * 2.0
        if _changed("ibc", key):
            ref["mod"].set_levels(ibc=key, doc=doc)
        if r["stream"]:
            import mrs_params as MP
            stream = (r["stream"], MP.nozzle_tip_z)
    elif kind == "liquid":
        x, y = r["pose"]
        ref["root"].Placement = App.Placement(V(x, y, 0.0), App.Rotation(V(0, 0, 1), 90.0))
        rot = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -math.degrees(r["spin"])))
        for tag in ("RL", "RR", "FL", "FR"):
            for part in ("tire", "rim", "hub"):
                ref["objs"]["%s_%s" % (tag, part)].Placement = rot
        phi, rr, s = r["boom"]
        key = (round(phi, 1), round(rr), round(s))
        if _changed("boom", key):
            ref["mod"].apply_pose(doc, phi, rr, s)
        key = (round(r["mr"] / 2.0) * 2.0, round(r["tr"] / 2.0) * 2.0)
        if _changed("mr", key):
            ref["mod"].set_levels(refiller=key[0], trailer=key[1], doc=doc)
    else:
        key = round(r["ibc"] / 4.0) * 4.0
        if _changed("ibc", key):
            doc.getObject("ibc1_liquid").Shape = ref["SG"].ibc_liquid_local(key)
        if _changed("beacon", r["beacon"]):
            set_beacon(doc, r["beacon"])
        if r["stream"]:
            import stc_params as CP
            stream = (r["stream"], CP.nozzle_tip_z if hasattr(CP, "nozzle_tip_z") else 1250.0)
    if stream:
        (nx, ny), z0 = stream
        if _changed("stream", (round(nx), round(ny))):
            doc.getObject("anim_stream").Shape = G.stream(nx, ny, z0, P.FUNNEL_RIM_Z - 110.0)
    elif _changed("stream", None):
        doc.getObject("anim_stream").Shape = Part.Shape()


def apply_frame(i, doc=None):
    doc = doc or _s["doc"]
    f = _s["run"]["frames"][i]
    set_worker(doc, f)
    set_slots(doc, f)
    set_path(doc, f)
    set_refiller(doc, f)


