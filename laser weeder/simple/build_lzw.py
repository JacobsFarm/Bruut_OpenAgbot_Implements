"""Model of the laser weeder on the Bruut OpenAgbot (standard robot).

Belly rails, hanger posts and the hood with brush strip, camera and LED bars are built from "drop on demand boom/simple"
(ddb_parts, imported); this file adds the 2 scan heads, the laser box on its cradle and the fibre cables.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_lzw
    build_lzw.build()                      # saves FCStd and STEP (middle height step)
    build_lzw.set_height(25)               # hood height step (-25, 0, 25 mm)
    build_lzw.check_interference()         # overlap in the current pose (must be empty)
    build_lzw.check_poses()                # height steps x steering +-30 (must be empty)
    build_lzw.clearance()                  # hood to the tyres
    build_lzw.mass_properties()
    build_lzw.render_all()                 # all images in previews/
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import lzw_params as P
import lzw_parts as G
import ddb_parts as DG
import build_ddb as BD

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Laser_Weeder"
SAVE_BASE = os.path.join(FOLDER, "Laser_Weeder")
ROOT = "Laser_weeder"

COLOR = dict(BD.COLOR)
COLOR.update({"head": (0.15, 0.15, 0.17), "lens": (0.25, 0.45, 0.75), "laser_box": (0.90, 0.75, 0.10),
              "fibre": (0.95, 0.55, 0.10), "beam": (0.95, 0.20, 0.10)})


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BD.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None, dz=0.0):
    root = BD.new_part(doc, parent, ROOT, "laser_weeder_simple")
    mount = BD.new_part(doc, root, "Mount", "belly_rails_posts_laser_box")
    add_shape(doc, mount, "rails", "belly_rails_40x40x3_x225", DG.rails(), "frame")
    add_shape(doc, mount, "rail_bolts", "rail_bolts_8xM10", G.rail_bolts(), "zinc")
    add_shape(doc, mount, "posts", "hanger_posts_30x30x2_feet_8mm", DG.posts(), "frame")
    add_shape(doc, mount, "post_bolts", "post_foot_bolts_M8_rivet_nuts", DG.post_bolts(), "zinc")
    add_shape(doc, mount, "cradle", "cradle_tubes_40x40x3", G.cradle(), "frame")
    add_shape(doc, mount, "cradle_bolts", "cradle_bolts_M10", G.cradle_bolts(), "zinc")
    add_shape(doc, mount, "laser_box", "laser_box_2x60W_diode_drivers_fans", G.laser_box(), "laser_box")
    hood = BD.new_part(doc, root, "Hood", "hood_600_camera_leds_2_scan_heads", BD.hood_placement(dz))
    add_shape(doc, hood, "hood_shell", "hood_alu_2mm_600x524x360", DG.hood_shell(), "hood")
    add_shape(doc, hood, "brush_holder", "brush_holder_alu_U", DG.holder(), "alu")
    add_shape(doc, hood, "brush", "brush_strip_nylon_50", DG.brush(), "brush")
    add_shape(doc, hood, "post_brackets", "post_brackets_6mm", DG.post_brackets(), "frame")
    add_shape(doc, hood, "bracket_bolts", "post_bracket_bolts_8xM8", DG.bracket_bolts(), "zinc")
    add_shape(doc, hood, "pins", "height_pins_M10_R_clip", DG.pins(), "steel")
    add_shape(doc, hood, "camera_bracket", "camera_angle_bracket_5mm", DG.camera_bracket(), "alu")
    add_shape(doc, hood, "camera", "camera_5MP_global_shutter_f3_5_down", DG.camera(), "camera")
    add_shape(doc, hood, "camera_glass", "camera_lens_window", DG.camera_glass(), "glass")
    add_shape(doc, hood, "led_bars", "led_bars_2x24W", DG.led_bars(), "alu")
    add_shape(doc, hood, "led_lenses", "led_bar_lenses", DG.led_lenses(), "led")
    add_shape(doc, hood, "scan_heads", "galvo_scan_heads_2x", G.scan_heads(), "head")
    add_shape(doc, hood, "lenses", "f_theta_lenses_2x", G.lenses(), "head")
    add_shape(doc, hood, "lens_windows", "protective_windows_2x", G.lens_windows(), "lens")
    add_shape(doc, hood, "fibres", "armoured_fibre_cables_2x", G.fibres(), "fibre")
    return root


def set_height(dz=0.0, doc=None):
    if dz not in P.D.height_steps:
        raise ValueError("height step %s not in %s" % (dz, P.D.height_steps))
    doc = active_doc(doc)
    doc.getObject("Hood").Placement = BD.hood_placement(dz)
    doc.recompute()


def build(save=True, show_robot=False, step=True, dz=0.0):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Laser weeder simple"
    doc.Comment = ("Generated by build_lzw.py from lzw_params.py (hood, posts, rails from drop on demand boom/simple). "
                   "Robot coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BD.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, dz)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = BD.global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("rail_bolts", "rails"), ("post_bolts", "rails"), ("post_bolts", "posts"), ("bracket_bolts", "post_brackets"),
          ("bracket_bolts", "hood_shell"), ("pins", "post_brackets"), ("pins", "posts"), ("cradle_bolts", "cradle"),
          ("laser_box", "cradle"), ("scan_heads", "hood_shell"), ("lenses", "scan_heads"), ("lens_windows", "lenses"),
          ("fibres", "hood_shell"), ("led_bars", "scan_heads")}
BEAM_BOLTS = ("rail_bolts", "cradle_bolts")


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x in BEAM_BOLTS and y.startswith(("lower_beam", "upper_beam")):
            return True
    return False


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, BD.global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, BD.global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return BD._overlaps(pairs, tol)


def set_steering(deg, doc=None):
    BD.BS.set_steering(deg, deg, active_doc(doc))


def check_poses(doc=None, tol=1.0):
    """The hood group over the height steps x steering angles against everything else. Must be empty."""
    doc = active_doc(doc)
    hood = objects_of(doc, "Hood")
    names = {o.Name for o in hood}
    others = [o for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    out = {}
    for st in (-30.0, 0.0, 30.0):
        set_steering(st, doc)
        fixed = [(o, BD.global_shape(o)) for o in others]
        for dz in P.D.height_steps:
            set_height(dz, doc)
            hd = [(o, BD.global_shape(o)) for o in hood]
            hits = BD._overlaps([(a, b) for a in hd for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
            if hits:
                out[str((st, dz))] = hits
    set_steering(0.0, doc)
    set_height(0.0, doc)
    return out


def clearance(doc=None):
    return BD.clearance(active_doc(doc))


MASS_FIXED = {"laser_box": P.box_kg, "scan_heads": 2 * P.head_kg, "lenses": 2 * 0.3, "camera": 0.6,
              "led_bars": 1.4, "led_lenses": 0.1, "camera_glass": 0.02, "lens_windows": 0.05}
DENSITY = {"hood_shell": P.D.alu, "brush_holder": P.D.alu, "brush": P.D.nylon, "camera_bracket": P.D.alu,
           "fibres": 1.5e-6}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, my = 0.0, 0.0
    for o in objects_of(doc, ROOT):
        s = BD.global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.D.steel))
        m += mo
        my += mo * s.BoundBox.Center.y
    return {"total_kg": round(m, 1), "cg_y": round(my / m)}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = BD.global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BD.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BD.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


