    out = []
    doc = build(save=False, show_robot=True, step=False)
    BD.add_ground(doc)
    out.append(save_view("1_iso_on_robot_in_bed.png", (-1.0, -1.1, -0.65), target=(0, 0, 450), height=2300))
    out.append(save_view("2_side_on_robot.png", (1.0, 0.0, 0.0), target=(0, 0, 500), height=1900))
    for n in ("hood_shell", "brush", "brush_holder"):
        doc.getObject(n).ViewObject.Transparency = 75
    cones = doc.addObject("Part::Feature", "render_scan_fields")
    cones.Shape = G.beam_cones()
    cones.ViewObject.ShapeColor = COLOR["beam"]
    cones.ViewObject.Transparency = 65
    out.append(save_view("3_scan_fields_see_through.png", (-1.0, -0.9, -0.55), target=(0, 0, 250), height=1100))
    BD.remove(doc, [BD.GROUND, BD.PLANTS, BD.PLANTS + "_weeds"])
    set_robot_visible(False, doc)
    out.append(save_view("4_inside_from_below.png", (0.25, 0.35, 1.0), target=(0, 0, 250), height=900))
    BD.remove(doc, ["render_scan_fields"])
    for n in ("hood_shell", "brush", "brush_holder"):
        doc.getObject(n).ViewObject.Transparency = 0
    set_robot_visible(True, doc)
    out.append(save_view("5_laser_box_fibres.png", (-1.0, 0.8, -0.6), target=(0, -100, 650), height=1500))
    App.closeDocument(doc.Name)
    build()
    return out
