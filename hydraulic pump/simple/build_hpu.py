"""Model of the hydraulic power pack on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_hpu
    build_hpu.build()                      # saves FCStd and STEP
    build_hpu.check_interference()         # overlap between the parts and with the robot (must be empty)
    build_hpu.check_holes()                # bolts in their holes (must be empty)
    build_hpu.check_steering()             # overlap with the front wheels steered +-30 (must be empty)
    build_hpu.clearance()                  # smallest distance to the tyres (rear and steered front)
    build_hpu.mass_properties()
    build_hpu.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import hpu_params as P
import hpu_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Hydraulic_Power_Pack"
SAVE_BASE = os.path.join(FOLDER, "Hydraulic_Power_Pack")
ROOT = "Hydraulic_power_pack"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "steel": (0.75, 0.75, 0.78),
    "tank": (0.15, 0.35, 0.65),
    "oil": (0.80, 0.60, 0.10),
    "motor": (0.20, 0.22, 0.25),
    "pump": (0.10, 0.45, 0.20),
    "valve": (0.70, 0.12, 0.10),
    "solenoid": (0.10, 0.10, 0.10),
    "hose": (0.05, 0.05, 0.05),
    "brass": (0.80, 0.65, 0.25),
}


def new_part(doc, parent, name, label):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "hydraulic_power_pack_simple")
    m = new_part(doc, root, "Mount", "bearers_and_plate")
    add_shape(doc, m, "bearers", "bearers_40x40x3_on_upper_beams", G.bearers(), "frame")
    add_shape(doc, m, "plate", "base_plate_5mm", G.plate(), "frame")
    add_shape(doc, m, "bolts", "bolts_M10_M8", G.bolts(), "zinc")
    t = new_part(doc, root, "Tank", "tank_16l")
    add_shape(doc, t, "tank", "tank_steel_2mm_16l", G.tank(), "tank")
    add_shape(doc, t, "tank_fittings", "return_filter_filler_sight_glass", G.tank_fittings(), "steel")
    d = new_part(doc, root, "Drive", "motor_pump")
    add_shape(doc, d, "motor", "bldc_motor_48V_3.5kW", G.motor(), "motor")
    add_shape(doc, d, "bell_pump", "bell_housing_gear_pump_4cc", G.bell_pump(), "pump")
    add_shape(doc, d, "controller", "motor_controller_48V", G.controller(), "motor")
    v = new_part(doc, root, "Valves", "valve_block_and_couplers")
    add_shape(doc, v, "valve_block", "valve_block_2_sections_relief", G.valve_block(), "valve")
    add_shape(doc, v, "solenoids", "solenoids_24V_gauge", G.solenoids(), "solenoid")
    add_shape(doc, v, "couplers", "quick_couplers_ISO_A_half_inch", G.couplers(), "brass")
    add_shape(doc, v, "hoses", "hoses_3_8", G.hoses(), "hose")
    return root


def build_robot(doc, steer=0.0):
    """Real robot model from 'agbot design' (read only)."""
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, steer if tag in ("FL", "FR") else 0.0)
    return robot


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build(save=True, show_robot=False, step=True, crop=False):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Hydraulic power pack simple"
    doc.Comment = ("Generated by build_hpu.py from hpu_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if crop:
        grp = new_part(doc, None, "Load", "oil")
        add_shape(doc, grp, "oil", "oil_in_tank", G.oil(), "oil")
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


