"""Model of the charging robot (mobile charger) on the Bruut OpenAgbot (standard robot), with a working robot docked.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_chg
    build_chg.build()                 # saves FCStd and STEP (charger parts only in the STEP)
    build_chg.check_interference()    # charger parts against each other and both robots (must be empty)
    build_chg.check_holes()           # bolts in the beam holes (must be empty)
    build_chg.check_docking()         # working robot steered +-30 against the charger (must be empty)
    build_chg.mass_properties()
    build_chg.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import chg_params as P
import chg_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Charging_Robot"
SAVE_BASE = os.path.join(FOLDER, "Charging_Robot")
ROOT = "Charging_robot"
DOCKED = "Docked_robot"

COLOR = dict(BP.COLOR)
COLOR.update({"pod": (0.78, 0.80, 0.82), "cells": (0.20, 0.45, 0.75), "box": (0.20, 0.22, 0.25),
              "copper": (0.85, 0.50, 0.25), "pe": (0.95, 0.95, 0.95), "alu": (0.80, 0.82, 0.85),
              "dock": (0.10, 0.55, 0.30)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "charging_robot_simple")
    deck = new_part(doc, root, "Deck", "deck_pods_charger")
    add_shape(doc, deck, "chg_bars", "deck_bars_60x8_3x", G.deck_bars(), "frame")
    add_shape(doc, deck, "chg_bolts", "deck_bolts_M10_12x", G.deck_bolts(), "zinc")
    add_shape(doc, deck, "chg_deck", "deck_plate_alu_6mm", G.deck_plate(), "alu")
    add_shape(doc, deck, "chg_pods", "battery_pods_48V_2560Wh_4x", G.pods(), "pod")
    add_shape(doc, deck, "chg_cells", "pod_cells_and_BMS", G.pod_cells(), "cells")
    add_shape(doc, deck, "chg_fittings", "pod_handles_connectors", G.pod_fittings(), "box")
    add_shape(doc, deck, "chg_straps", "hold_down_straps_2x", G.straps(), "zinc")
    add_shape(doc, deck, "chg_dcdc", "DCDC_charger_1500W_54V", G.dcdc(), "box")
    add_shape(doc, deck, "chg_fuse", "main_switch_fuse_box", G.fuse_box(), "box")
    rear = new_part(doc, root, "Rear_head", "rear_contact_head")
    add_shape(doc, rear, "chg_bracket", "rear_bracket_6mm", G.rear_bracket(), "frame")
    add_shape(doc, rear, "chg_bracket_bolts", "rear_bracket_bolts_M10_2x", G.rear_bracket_bolts(), "zinc")
    add_shape(doc, rear, "chg_arm", "arm_60x40x3", G.rear_arm(), "frame")
    add_shape(doc, rear, "chg_head", "contact_head_PE_steel", G.head(), "pe")
    add_shape(doc, rear, "chg_funnel", "funnel_plates_3mm", G.funnel(), "frame")
    add_shape(doc, rear, "chg_contact_bars", "copper_bars_2x", G.bars(), "copper")
    return root


build_robot = BP.build_robot
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def add_docked(doc, steer=0.0):
    """Working robot behind the charger with the dock bracket of the charging dock on its front beam."""
    robot = build_robot(doc, steer)
    robot.Label = "working_robot_docked"
    robot.Placement = App.Placement(V(0, -P.dock_d, 0), App.Rotation())
    grp = new_part(doc, None, DOCKED, "working_robot_dock_bracket")
    names = ("dock_bracket", "dock_bracket_bolts", "dock_pe_carrier", "dock_pads", "dock_springs", "dock_pilot")
    for n, s in zip(names, G.docked_bracket()):
        add_shape(doc, grp, n, n, s, "dock" if n != "dock_pads" else "copper")
    return robot


def build(save=True, show_robot=False, step=True, docked=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Charging robot simple"
    doc.Comment = ("Generated by build_chg.py from chg_params.py. Robot coordinates of the charger: x = right, "
                   "y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if docked and robot is not None:
        add_docked(doc)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc, name="Robot"):
    robot = doc.getObject(name)
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def docked_robot_objects(doc):
    out = []
    for o in doc.Objects:
        if o.TypeId == "App::Part" and o.Label == "working_robot_docked":
            out = [c for c in o.OutListRecursive if c.TypeId == "Part::Feature"]
    return out + objects_of(doc, DOCKED)


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc) + docked_robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("chg_head", "chg_funnel"), ("chg_bolts", "chg_bars"), ("chg_bolts", "chg_deck"), ("chg_cells", "chg_pods"),
          ("chg_bracket_bolts", "chg_bracket"), ("chg_arm", "chg_bracket")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    bolts = ("chg_bolts", "chg_bracket_bolts", "dock_bracket_bolts")
    beams = ("upper_beam", "lower_beam")
    return any(n in (a, b) for n in bolts) and (a.startswith(beams) or b.startswith(beams))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc) + docked_robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """Every bolt shank (O9 rod) through the beams it passes must find a hole."""
    doc = active_doc(doc)
    beams = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith(("upper_beam", "lower_beam"))]
    out = {}
    pts = [(x, y, 640.0, 720.0) for y in P.bar_y for x in P.upper_bolt_x]
    pts += [(x, sum(P.rear_beam_y) / 2, 600.0, 680.0) for x in P.bk_bolt_x]
    for x, y, z0, z1 in pts:
        rod = G.cyl(9.0, (x, y, z0), (x, y, z1))
        v = sum(rod.common(b).Volume for b in beams if b.BoundBox.intersect(rod.BoundBox))
        if v > tol:
            out[str((x, y))] = round(v, 1)
    return out


def check_docking(doc=None, tol=1.0, steer=(-P.robot_steer_deg, P.robot_steer_deg)):
    """Front wheels of the docked working robot steered: no contact with the charger or its head."""
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc)]
    out = {}
    for st in steer:
        for n in ("FL_steered001", "FR_steered001"):
            o = doc.getObject(n)
            if o is not None:
                o.Placement = App.Placement(o.Placement.Base, App.Rotation(V(0, 0, 1), st))
        doc.recompute()
        rob = [(o, global_shape(o)) for o in docked_robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in rob for b in mine], tol)
        if hits:
            out[str(st)] = hits
    for n in ("FL_steered001", "FR_steered001"):
        o = doc.getObject(n)
        if o is not None:
            o.Placement = App.Placement(o.Placement.Base, App.Rotation())
    doc.recompute()
    return out


MASS_FIXED = {"chg_dcdc": 6.5, "chg_fuse": 1.5, "chg_fittings": 0.6 * P.pods_n,
              "chg_cells": (P.B.cells_n * P.B.cell_kg + P.B.bms_kg) * P.pods_n}
DENSITY = {"chg_deck": P.alu, "chg_pods": P.alu, "chg_head": 0.96e-6, "chg_contact_bars": 8.96e-6}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    import FreeCADGui as Gui
    out = []
    doc = build(save=False, show_robot=True, step=False)
    Gui.setActiveDocument(doc.Name)
    floor = doc.addObject("Part::Feature", "render_floor")
    floor.Shape = G.box_span((-1100.0, 1100.0), (-2600.0, 1000.0), (-30.0, 0.0))
    floor.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    floor.ViewObject.Transparency = 30
    out.append(save_view("1_iso_robot_docked_behind.png", (1.0, 1.0, -0.6), target=(0, -800, 500), height=3200))
    out.append(save_view("2_side_docked.png", (1.0, 0.0, 0.0), target=(0, -800, 600), height=1700))
    doc.removeObject("render_floor")
    set_robot_visible(False, doc)
    for n in ("dock_bracket", "dock_bracket_bolts", "dock_pe_carrier", "dock_pads", "dock_springs", "dock_pilot"):
        doc.getObject(n).ViewObject.Visibility = True
    out.append(save_view("3_contact_head_docked.png", (-0.5, 0.35, -0.5), target=(0, -870, 560), height=650))
    for o in objects_of(doc, DOCKED):
        o.ViewObject.Visibility = False
    out.append(save_view("4_deck_pods_charger.png", (-1.0, -1.1, -0.8), target=(0, -300, 800), height=1900))
    App.closeDocument(doc.Name)
    build()
    return out
