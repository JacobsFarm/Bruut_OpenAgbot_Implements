    set_pose(P.ZC0, 0.0, 0.0, doc)
    out.append(save_view("6_front_blower.png", (-0.8, -1.0, -0.4), target=(150, 750, 450), height=1300))
    App.closeDocument(doc.Name)
    build()
    return out
