"""Model of the hedge trimmer and leaf blower on the Bruut OpenAgbot (standard robot).

Mast, lead screw, stepper, camera, carriage, hinge pin and arm are the fence inspector's (build_fin / fin_parts,
imported); this file adds the tilt head with the trimmer bar and the front blower.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_hdg
    build_hdg.build()
    build_hdg.set_pose(arm_z=1300, tilt=90, swing=0)   # top cut
    build_hdg.check_interference()
    build_hdg.check_poses()                # heights x tilt x swing x steering: empty
    build_hdg.mass_properties()
    build_hdg.render_all()
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import hdg_params as P
import hdg_parts as G
import fin_parts as FG
import build_fin as BF

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Hedge_Trimmer"
SAVE_BASE = os.path.join(FOLDER, "Hedge_Trimmer")
ROOT = "Hedge_trimmer"

COLOR = dict(BF.COLOR)
COLOR.update({"trimmer": (0.95, 0.45, 0.10), "blade": (0.80, 0.81, 0.83), "guard": (0.10, 0.10, 0.10),
              "blower": (0.15, 0.55, 0.30), "sensor": (0.15, 0.35, 0.75)})


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BF.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def tilt_placement(tilt=0.0):
    return App.Placement(V(0, 0, 0), App.Rotation(V(0, 1, 0), tilt), V(P.tilt_x, 0, G.ZC))


def build_into(doc, parent=None, arm_z=P.ZC0, tilt=0.0, swing=0.0):
    root = BF.new_part(doc, parent, ROOT, "hedge_trimmer_leaf_blower_simple")
    mount = BF.new_part(doc, root, "Mount", "mast_on_right_upper_beams_from_fence_inspector")
    add_shape(doc, mount, "base_plate", "base_plate_8mm", FG.base_plate(), "mast")
    add_shape(doc, mount, "plate_bolts", "base_plate_bolts_M10_4x", FG.plate_bolts(), "zinc")
    add_shape(doc, mount, "mast", "mast_60x60x3", FG.mast(), "mast")
    add_shape(doc, mount, "gussets", "gussets_8mm_2x", FG.gussets(), "mast")
    add_shape(doc, mount, "screw", "lead_screw_Tr16x4", FG.screw(), "steel")
    add_shape(doc, mount, "screw_blocks", "screw_bearing_blocks", FG.screw_blocks(), "mast")
    add_shape(doc, mount, "stepper", "stepper_NEMA23", FG.stepper(), "motor")
    add_shape(doc, mount, "camera", "hedge_camera", FG.camera(), "motor")
    car = BF.new_part(doc, root, "Carriage", "carriage_moves_up_down", BF.carriage_placement(arm_z))
    add_shape(doc, car, "carriage", "carriage_C_sleeve_nut_hinge_lug", FG.carriage(), "carriage")
    add_shape(doc, car, "hinge_pin", "hinge_pin_D16_torsion_spring", FG.hinge_pin(), "steel")
    arm = BF.new_part(doc, car, "Arm", "arm_swings_about_hinge", BF.arm_placement(swing))
    add_shape(doc, arm, "arm", "arm_tube_40x40x3", FG.arm(), "carriage")
    add_shape(doc, arm, "hdg_tilt_motor", "tilt_worm_gearmotor_24V", G.tilt_motor(), "motor")
    add_shape(doc, arm, "hdg_tilt_flange", "tilt_output_flange", G.tilt_flange(), "zinc")
    tg = BF.new_part(doc, arm, "Tilt", "trimmer_turns_about_y", tilt_placement(tilt))
    add_shape(doc, tg, "hdg_housing", "trimmer_motor_gearbox_600W", G.housing(), "trimmer")
    add_shape(doc, tg, "hdg_bar", "trimmer_bar_double_sided_1000", G.bar(), "blade")
    add_shape(doc, tg, "hdg_guard", "finger_guard_strip", G.guard(), "guard")
    add_shape(doc, tg, "hdg_tof", "ToF_distance_sensor", G.tof(), "sensor")
    fr = BF.new_part(doc, root, "Blower", "leaf_blower_front")
    add_shape(doc, fr, "hdg_blower", "axial_blower_48V_900W", G.blower(), "blower")
    add_shape(doc, fr, "hdg_blower_bracket", "blower_bracket_flat_80x8", G.blower_bracket(), "frame")
    return root


def set_pose(arm_z=P.ZC0, tilt=0.0, swing=0.0, doc=None):
    doc = active_doc(doc)
    doc.getObject("Carriage").Placement = BF.carriage_placement(arm_z)
    doc.getObject("Arm").Placement = BF.arm_placement(swing)
    doc.getObject("Tilt").Placement = tilt_placement(tilt)
    doc.recompute()


set_steering = BF.set_steering
global_shape = BF.global_shape
_overlaps = BF._overlaps


def build(save=True, show_robot=False, step=True, arm_z=P.ZC0, tilt=0.0):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Hedge trimmer simple"
    doc.Comment = ("Generated by build_hdg.py from hdg_params.py (mast, carriage, arm from fence inspector/simple). "
                   "Robot coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BF.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, arm_z, tilt)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("hdg_tilt_motor", "arm"), ("hdg_tilt_flange", "hdg_tilt_motor"), ("hdg_housing", "hdg_tilt_flange"),
          ("hdg_bar", "hdg_housing"), ("hdg_guard", "hdg_housing"), ("hdg_guard", "hdg_bar"), ("hdg_tof", "hdg_housing"),
          ("hdg_blower", "hdg_blower_bracket")}


def _joint(a, b):
    return (a, b) in JOINTS or (b, a) in JOINTS or BF._joint(a, b) or \
        ({a, b} & {"hdg_blower_bracket"} and (a.startswith("lower_beam") or b.startswith("lower_beam")))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_poses(doc=None, tol=1.0, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Carriage at the lowest / highest arm height x tilt 0 / 45 / 90 x swing 0 / 80, then the blower over steering."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Carriage")
    names = {o.Name for o in moving}
    fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    out = {}
    for z in P.z_range:
        for tilt in P.TILT_POSES:
            for swing in (0.0, P.swing_max):
                set_pose(z, tilt, swing, doc)
                mv = [(o, global_shape(o)) for o in moving]
                hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
                hits = [h for h in hits]
                if hits:
                    out[str((z, tilt, swing))] = hits
    set_pose(P.ZC0, 0.0, 0.0, doc)
    blow = [(o, global_shape(o)) for o in objects_of(doc, "Blower")]
    for st in steer:
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in blow for b in rob], tol)
        if hits:
            out["steer_%g" % st] = hits
    set_steering(0.0, doc)
    return out


def ground_clear(doc=None):
    """Lowest point of the trimmer over the poses (must stay above the ground)."""
    doc = active_doc(doc)
    out = {}
    for z in P.z_range:
        for tilt in P.TILT_POSES:
            set_pose(z, tilt, 0.0, doc)
            bb = None
            for o in objects_of(doc, "Tilt"):
                b = global_shape(o).BoundBox
                bb = b if bb is None else bb.united(b)
            out[str((z, tilt))] = (round(bb.ZMin), round(bb.ZMax), round(bb.XMax))
    set_pose(P.ZC0, 0.0, 0.0, doc)
    return out


MASS_FIXED = {"hdg_housing": 2.8, "hdg_tilt_motor": 2.2, "hdg_blower": 3.5, "stepper": 1.4, "camera": 0.5, "hdg_tof": 0.1}


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = 0.95e-6 if obj.Name == "hdg_guard" else P.steel
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Carriage", "Tilt", "Blower"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


set_camera = BF.BP.set_camera


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_hedge", "render_growth", "render_path", "render_leaves")


def add_scene(doc):
    y0, y1 = -3000.0, 3000.0
    for name, shape, color in ((SCENE[0], G.hedge(y0, y1), (0.15, 0.40, 0.15)),
                               (SCENE[1], G.hedge_uncut(500.0, y1), (0.20, 0.50, 0.18)),
                               (SCENE[2], G.path(y0, y1), (0.70, 0.68, 0.62)),
                               (SCENE[3], G.leaves(y0, y1), (0.70, 0.45, 0.15))):
        o = doc.addObject("Part::Feature", name)
        o.Shape = shape
        o.ViewObject.ShapeColor = color


