def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj





def build_side(doc, parent, sx, tag):
    grp = new_part(doc, parent, "Pod_" + tag, "battery_pod_48V_50Ah_" + tag)
    add_shape(doc, grp, "hangers_" + tag, "hangers_40x8_spacers_2x_" + tag, G.hangers(sx), "frame")
    add_shape(doc, grp, "hbolts_" + tag, "hanger_bolts_M10_4x_" + tag, G.hanger_bolts(sx), "zinc")
    add_shape(doc, grp, "box_" + tag, "pod_box_alu_3mm_" + tag, G.pod_box(sx), "alu")
    add_shape(doc, grp, "hooks_" + tag, "hook_strips_2x_" + tag, G.hooks(sx), "alu")
    add_shape(doc, grp, "cells_" + tag, "cells_LiFePO4_50Ah_16x_" + tag, G.cells(sx), "cell")
    add_shape(doc, grp, "bms_" + tag, "bms_16S_" + tag, G.bms(sx), "pcb")
    add_shape(doc, grp, "fittings_" + tag, "handles_connector_latches_" + tag, G.outer_fittings(sx), "plastic")
    return grp


def build_into(doc, parent=None):
    """Put the battery pack in a document, in robot coordinates."""
    root = new_part(doc, parent, ROOT, "battery_pack_simple")
    for sx, tag in ((-1, "left"), (1, "right")):
        build_side(doc, root, sx, tag)
    return root


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build_robot(doc):
    """Real robot model from 'agbot design' (read only)."""
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Battery pack simple"
    doc.Comment = ("Generated by build_bpk.py from bpk_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0. Two pods hang under the upper beams.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


