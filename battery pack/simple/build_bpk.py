"""Model of the battery pack (2 exchangeable 48 V pods) on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_bpk
    build_bpk.build()                      # saves FCStd and STEP
    build_bpk.check_interference()         # overlap (must be empty)
    build_bpk.clearance()                  # smallest distance to the tyres (front steered +-30)
    build_bpk.mass_properties()
    build_bpk.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import bpk_params as P
import bpk_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Battery_Pack"
SAVE_BASE = os.path.join(FOLDER, "Battery_Pack")
ROOT = "Battery_pack"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "alu": (0.70, 0.72, 0.75),
    "cell": (0.20, 0.35, 0.65),
    "pcb": (0.10, 0.45, 0.20),
    "plastic": (0.10, 0.10, 0.10),
    "red": (0.80, 0.10, 0.10),
}


