"""Model of the chicken house robot on the Bruut OpenAgbot (standard robot).

The litter turner is the broom of "broom sweeper/simple" (build_bsw.build_into: push-blade toolbar, arms, king pin,
broom head) with its bristles replaced by the tine rotor; this file adds the tines, the sensor box and the camera post.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_chk
    build_chk.build()                 # saves FCStd and STEP
    build_chk.check_interference()    # overlap (must be empty)
    build_chk.check_holes()           # bolts and tines in their holes / welds (must be empty)
    build_chk.check_poses()           # broom lift x angle x steering, with the tine rotor (must be empty)
    build_chk.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import chk_params as P
import chk_parts as G
import build_bsw as BW
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Chicken_House_Robot"
SAVE_BASE = os.path.join(FOLDER, "Chicken_House_Robot")
ROOT = "Chicken_house_robot"

COLOR = dict(BW.COLOR)
COLOR.update({"tine": (0.75, 0.76, 0.78), "box": (0.20, 0.45, 0.30), "cam": (0.15, 0.15, 0.18),
              "litter": (0.80, 0.70, 0.45), "bird": (0.97, 0.97, 0.95)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "chicken_house_robot_simple")
    BW.build_into(doc, root)
    doc.removeObject("bristles")
    brush = doc.getObject("Brush")
    brush.Label = "tine_rotor_turns_about_its_axis"
    add_shape(doc, brush, "tines", "spring_tines_D6_6_rows_tip_D360", G.tines(), "tine")
    sens = new_part(doc, root, "Sensors", "climate_box_and_360_camera")
    add_shape(doc, sens, "chk_hangers", "sensor_box_hangers_6mm_2x", G.hangers(), "frame")
    add_shape(doc, sens, "chk_hanger_bolts", "hanger_bolts_M10_4x", G.hanger_bolts(), "zinc")
    add_shape(doc, sens, "sensor_box", "climate_box_NH3_CO2_T_RH_at_300mm", G.sensor_box(), "box")
    add_shape(doc, sens, "chk_cam_bar", "camera_bar_8mm", G.cam_bar(), "frame")
    add_shape(doc, sens, "chk_cam_bar_bolts", "camera_bar_bolts_M10_2x", G.cam_bar_bolts(), "zinc")
    add_shape(doc, sens, "chk_cam_post", "camera_post_40x40x3", G.cam_post(), "frame")
    add_shape(doc, sens, "camera360", "camera_360_deg", G.camera360(), "cam")
    return root


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Chicken house robot simple"
    doc.Comment = ("Generated by build_chk.py from chk_params.py (broom head with a tine rotor from broom sweeper/simple). "
                   "Robot coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("tines", "brush_core"), ("chk_hanger_bolts", "chk_hangers"), ("chk_cam_bar_bolts", "chk_cam_bar"),
          ("chk_cam_post", "chk_cam_bar"), ("chk_hangers", "sensor_box")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS or BW._joint(a, b):
        return True
    for bolt, beam in (("chk_hanger_bolts", "lower_beam"), ("chk_cam_bar_bolts", "upper_beam")):
        if (a == bolt and b.startswith(beam)) or (b == bolt and a.startswith(beam)):
            return True
    return False


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """Bolts in their own holes and in the beam holes (the beam pairs are skipped by check_interference)."""
    doc = active_doc(doc)
    out = {}
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT) + robot_objects(doc)}
    beams = [n for n in objs if n.startswith(("lower_beam", "upper_beam"))]
    for a, b in (("chk_hanger_bolts", "chk_hangers"), ("chk_cam_bar_bolts", "chk_cam_bar")):
        v = objs[a].common(objs[b]).Volume
        if v > tol:
            out[str((a, b))] = round(v, 1)
        for n in beams:
            if objs[a].BoundBox.intersect(objs[n].BoundBox):
                v = objs[a].common(objs[n]).Volume
                if v > tol:
                    out[str((a, n))] = round(v, 1)
    return out


def check_poses(doc=None):
    """The broom's own pose check (lift x head angle x steering) with the tine rotor in the Brush group."""
    return BW.check_poses(active_doc(doc))


def tine_floor(doc=None):
    """Lowest tine tip over the floor in the work pose (must stay above the concrete) and its depth in the litter."""
    doc = active_doc(doc)
    z = global_shape(doc.getObject("tines")).BoundBox.ZMin
    return {"tip_over_floor_mm": round(z, 1), "in_litter_mm": round(P.litter_depth - z, 1)}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    fixed = {"sensor_box": 2.5, "camera360": 0.8}
    for o in objects_of(doc, ROOT):
        if o.Name in fixed:
            mo, co = fixed[o.Name], global_shape(o).BoundBox.Center
        else:
            mo, co = BW._mass_cg(o)
        m += mo
        c += co * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_litter", "render_birds")


def add_scene(doc):
    lt = doc.addObject("Part::Feature", SCENE[0])
    lt.Shape = G.litter()
    lt.ViewObject.ShapeColor = COLOR["litter"]
    lt.ViewObject.Transparency = 50
    b = doc.addObject("Part::Feature", SCENE[1])
    b.Shape = G.birds()
    b.ViewObject.ShapeColor = COLOR["bird"]


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_in_house.png", (-1.0, -1.2, -0.7), target=(0, 400, 500)))
    out.append(save_view("2_side.png", (1.0, 0.0, 0.0), target=(0, 400, 600), height=2200))
    remove(doc, SCENE)
    set_robot_visible(False, doc)
    doc.getObject("hood").ViewObject.Visibility = False
    out.append(save_view("3_tine_rotor.png", (-1.0, 0.5, -0.4), target=(0, 1450, 200), height=1300))
    doc.getObject("hood").ViewObject.Visibility = True
    out.append(save_view("4_sensor_box_rear.png", (0.6, -1.0, -0.3), target=(0, -620, 450), height=800))
    App.closeDocument(doc.Name)
    build()
    return out
