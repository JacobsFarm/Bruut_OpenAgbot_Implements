"""Model of the seat, canopy and frame extension on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_sfe
    build_sfe.build()                      # saves FCStd and STEP
    build_sfe.check_interference()         # overlap (must be empty)
    build_sfe.check_steering()             # overlap with the front wheel units at +-30 degrees (must be empty)
    build_sfe.mass_properties()
    build_sfe.render_all()                 # all images in previews/ (with an operator dummy)
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import sfe_params as P
import sfe_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Seat_Frame_Extension"
SAVE_BASE = os.path.join(FOLDER, "Seat_Frame_Extension")
ROOT = "Seat_frame_extension"

COLOR = {"frame": (0.93, 0.42, 0.08), "zinc": (0.82, 0.84, 0.87), "seat": (0.12, 0.12, 0.13),
         "console": (0.25, 0.27, 0.30), "red": (0.85, 0.10, 0.08), "yellow": (0.95, 0.80, 0.10),
         "checker": (0.75, 0.76, 0.78), "rops": (0.95, 0.80, 0.10), "canopy": (0.70, 0.85, 0.95),
         "operator": (0.30, 0.45, 0.70)}


def new_part(doc, parent, name, label):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "seat_canopy_frame_extension_simple")
    fr = new_part(doc, root, "Frame", "cross_tubes_side_extensions")
    add_shape(doc, fr, "cross_tubes", "cross_tubes_40x40x3_extensions_x800", G.cross_tubes(), "frame")
    add_shape(doc, fr, "cross_bolts", "cross_tube_bolts_16xM10", G.cross_bolts(), "zinc")
    st = new_part(doc, root, "Seat", "seat_controls_footplate")
    add_shape(doc, st, "seat_plate", "seat_plate_8mm", G.seat_plate(), "frame")
    add_shape(doc, st, "pedestal", "seat_pedestal_80x80_slide", G.pedestal(), "frame")
    add_shape(doc, st, "seat", "tractor_seat_switch_armrests", G.seat(), "seat")
    add_shape(doc, st, "console", "armrest_console", G.console(), "console")
    add_shape(doc, st, "joystick", "drive_joystick", G.joystick(), "console")
    add_shape(doc, st, "estop", "emergency_stop_mushroom", G.estop(), "red")
    add_shape(doc, st, "footplate", "footplate_checker_3mm_toe_board", G.footplate(), "checker")
    rp = new_part(doc, root, "Rops", "roll_bar_canopy")
    add_shape(doc, rp, "rops", "roll_bar_tube_42x3", G.rops(), "rops")
    add_shape(doc, rp, "rops_bolts", "roll_bar_bolts_4xM10", G.rops_bolts(), "zinc")
    add_shape(doc, rp, "canopy_rails", "canopy_rails_30x30", G.canopy_rails(), "rops")
    add_shape(doc, rp, "canopy", "canopy_polycarbonate_6mm", G.canopy(), "canopy")
    return root


def build_robot(doc):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Seat frame extension simple"
    doc.Comment = ("Generated by build_sfe.py from sfe_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("cross_bolts", "cross_tubes"), ("rops_bolts", "cross_tubes"), ("rops_bolts", "rops"),
          ("canopy_rails", "rops"), ("canopy", "canopy_rails"), ("joystick", "console"), ("estop", "console"),
          ("console", "seat"), ("seat", "pedestal")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x == "cross_bolts" and y.startswith("upper_beam"):
            return True
    return False


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        vol = sa.common(sb).Volume
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_max, P.robot_steer_max):
        for name in ("FL_steered", "FR_steered"):
            o = doc.getObject(name)
            if o is not None:
                o.Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), st))
        doc.recompute()
        front = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL_", "FR_"))]
        hits = _overlaps([(a, b) for a in mine for b in front], tol)
        if hits:
            out["steer_%+d" % st] = hits
    for name in ("FL_steered", "FR_steered"):
        o = doc.getObject(name)
        if o is not None:
            o.Placement = App.Placement()
    doc.recompute()
    return out


DENSITY = {"canopy": P.pc, "seat": P.foam * 3.0}
MASS_FIXED = {"seat": 18.0, "console": 1.2, "joystick": 0.4, "estop": 0.2}


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity, without the operator."""
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"total_kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def set_camera(direction, target=None, height=None, up=(0.0, 0.0, 1.0)):
    import FreeCADGui as Gui
    from pivy import coin
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Orthographic")
    d = V(*direction)
    d.normalize()
    cam = view.getCameraNode()
    tgt = V(*target) if target is not None else V(0, 0, 800)
    eye = tgt - d * 12000.0
    cam.position.setValue(coin.SbVec3f(eye.x, eye.y, eye.z))
    cam.pointAt(coin.SbVec3f(tgt.x, tgt.y, tgt.z), coin.SbVec3f(*up))
    cam.nearDistance.setValue(10.0)
    cam.farDistance.setValue(40000.0)
    if height is None:
        view.fitAll()
    else:
        cam.height.setValue(height)
    return view


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    fl = doc.addObject("Part::Feature", "render_floor")
    fl.Shape = G.box_span((-1300.0, 1300.0), (-1500.0, 1500.0), (-40.0, 0.0))
    fl.ViewObject.ShapeColor = (0.62, 0.70, 0.52)
    op = doc.addObject("Part::Feature", "render_operator")
    op.Shape = G.operator()
    op.ViewObject.ShapeColor = COLOR["operator"]
    out.append(save_view("1_iso_with_operator.png", (-1.0, -1.1, -0.6), target=(0, 0, 1000), height=2900))
    out.append(save_view("2_side_with_operator.png", (1.0, 0.0, 0.0), target=(0, 0, 1050), height=2400))
    out.append(save_view("3_front_with_operator.png", (0.0, -1.0, 0.0), target=(0, 0, 1050), height=2400))
    op.ViewObject.Visibility = False
    doc.getObject("canopy").ViewObject.Transparency = 60
    out.append(save_view("4_seat_controls_footplate.png", (-1.0, -0.7, -0.6), target=(100, -250, 1000), height=1300))
    for o in objects_of(doc, "Rops") + objects_of(doc, "Seat"):
        o.ViewObject.Visibility = False
    out.append(save_view("5_frame_side_extensions.png", (-0.7, -1.0, -0.8), target=(0, 0, 700), height=2100))
    App.closeDocument(doc.Name)
    build()
    return out
