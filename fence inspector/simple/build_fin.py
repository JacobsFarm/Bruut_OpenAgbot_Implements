def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


GROUND = "render_floor"
FENCE = "render_fence"


def add_scene(doc):
    obj = doc.addObject("Part::Feature", GROUND)
    obj.Shape = G.box_span((-1100.0, 1500.0), (-1500.0, 2200.0), (-40.0, 0.0))
    obj.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    obj.ViewObject.Transparency = 30
    f = doc.addObject("Part::Feature", FENCE)
    f.Shape = G.fence((-1500.0, 2200.0))
    f.ViewObject.ShapeColor = COLOR["fence"]


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_along_fence.png", (-1.0, 1.3, -0.6), target=(400, 0, 600)))
    out.append(save_view("2_rear_view_top_wire.png", (0.0, 1.0, 0.0), target=(500, 0, 650), height=1700))
    set_pose(P.WIRE_Z[0], 0.0, doc)
    out.append(save_view("3_rear_view_low_wire.png", (0.0, 1.0, 0.0), target=(500, 0, 650), height=1700))
    set_pose(P.wire_z, P.swing_max, doc)
    out.append(save_view("4_top_arm_swung_back.png", (0.0, 0.0, -1.0), target=(500, 0, 0), up=(0.0, 1.0, 0.0),
                         height=2600))
    set_pose(P.wire_z, 0.0, doc)
    remove(doc, [GROUND])
    set_robot_visible(False, doc)
    out.append(save_view("5_head_and_carriage.png", (-0.8, 1.0, -0.4), target=(700, 0, 1000), height=700))
    remove(doc, [FENCE])
    App.closeDocument(doc.Name)
    build()
    return out
