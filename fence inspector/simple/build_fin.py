"""Model of the fence inspector on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_fin
    build_fin.build()                       # saves FCStd and STEP (work pose: head at the top wire)
    build_fin.set_pose(wire_z=400, swing=0) # head height (mm) and arm swing (deg, + = back)
    build_fin.check_interference()          # overlap in the current pose (must be empty)
    build_fin.check_holes()                 # pins and bolts in their holes (must be empty)
    build_fin.check_poses()                 # overlap over height x swing x steering +-30 (must be empty)
    build_fin.clearance()                   # head to wire, and arm to the tyres
    build_fin.mass_properties()
    build_fin.render_all()                  # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import fin_params as P
import fin_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Fence_Inspector"
SAVE_BASE = os.path.join(FOLDER, "Fence_Inspector")
ROOT = "Fence_inspector"

COLOR = dict(BP.COLOR)
COLOR.update({
    "mast": (0.85, 0.40, 0.10),
    "carriage": (0.95, 0.75, 0.10),
    "head": (0.15, 0.35, 0.75),
    "pe": (0.95, 0.95, 0.92),
    "motor": (0.20, 0.22, 0.25),
    "fence": (0.55, 0.42, 0.25),
})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def carriage_placement(wire_z):
    return App.Placement(V(0, 0, wire_z - P.wire_z), App.Rotation())


def arm_placement(swing):
    """Swing about the vertical hinge; + = arm end goes back (-y)."""
    hx, hy = P.hinge_xy
    return App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), -swing), V(hx, hy, 0))


def build_into(doc, parent=None, wire_z=P.wire_z, swing=0.0):
    root = new_part(doc, parent, ROOT, "fence_inspector_simple")
    mount = new_part(doc, root, "Mount", "mast_on_right_upper_beams")
    add_shape(doc, mount, "base_plate", "base_plate_8mm", G.base_plate(), "mast")
    add_shape(doc, mount, "plate_bolts", "base_plate_bolts_M10_4x", G.plate_bolts(), "zinc")
    add_shape(doc, mount, "mast", "mast_60x60x3", G.mast(), "mast")
    add_shape(doc, mount, "gussets", "gussets_8mm_2x", G.gussets(), "mast")
    add_shape(doc, mount, "screw", "lead_screw_Tr16x4", G.screw(), "steel")
    add_shape(doc, mount, "screw_blocks", "screw_bearing_blocks", G.screw_blocks(), "mast")
    add_shape(doc, mount, "stepper", "stepper_NEMA23", G.stepper(), "motor")
    add_shape(doc, mount, "camera", "post_camera", G.camera(), "motor")
    car = new_part(doc, root, "Carriage", "carriage_moves_up_down", carriage_placement(wire_z))
    add_shape(doc, car, "carriage", "carriage_C_sleeve_nut_hinge_lug", G.carriage(), "carriage")
    add_shape(doc, car, "hinge_pin", "hinge_pin_D16_torsion_spring", G.hinge_pin(), "steel")
    arm = new_part(doc, car, "Arm", "arm_swings_about_hinge", arm_placement(swing))
    add_shape(doc, arm, "arm", "arm_tube_40x40x3", G.arm(), "carriage")
    add_shape(doc, arm, "head", "sensor_head_E_field_plate_pickup_coil_ToF", G.head(), "head")
    add_shape(doc, arm, "bumper", "bumper_nose_PE", G.bumper(), "pe")
    return root


def set_pose(wire_z=P.wire_z, swing=0.0, doc=None):
    doc = active_doc(doc)
    doc.getObject("Carriage").Placement = carriage_placement(wire_z)
    doc.getObject("Arm").Placement = arm_placement(swing)


build_robot = BP.build_robot
set_steering = BP.set_steering
tyre_envelope = BP.tyre_envelope
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True, wire_z=P.wire_z, swing=0.0):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Fence inspector simple"
    doc.Comment = ("Generated by build_fin.py from fin_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0. Work pose (head at the top wire); build_fin.set_pose() moves it.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, wire_z, swing)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("plate_bolts", "base_plate"), ("screw", "screw_blocks"), ("screw", "carriage"), ("hinge_pin", "carriage"),
          ("hinge_pin", "arm"), ("base_plate", "mast"), ("gussets", "mast"), ("gussets", "base_plate")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "plate_bolts" in (a, b) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    out = {}
    for a, b in JOINTS:
        if b in ("mast", "base_plate") and a in ("base_plate", "gussets"):
            continue                                # welded, touching faces
        if a in objs and b in objs and objs[a].BoundBox.intersect(objs[b].BoundBox):
            v = objs[a].common(objs[b]).Volume
            if v > tol:
                out[str((a, b))] = round(v, 1)
    return out


def check_poses(doc=None, tol=1.0, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Carriage and arm against the mount and the robot over head height x arm swing x steering. Must be empty."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Carriage")
    names = {o.Name for o in moving}
    others = [o for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    arm_names = {o.Name for o in objects_of(doc, "Arm")}
    out = {}
    for st in steer:
        set_steering(st, doc)
        fixed = [(o, global_shape(o)) for o in others]
        for z in (P.Z_RANGE[0], 700.0, P.Z_RANGE[1]):
            for sw in (0.0, P.swing_max / 2.0, P.swing_max):
                set_pose(z, sw, doc)
                mv = [(o, global_shape(o)) for o in moving]
                pairs = [(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)]
                pairs += [(a, b) for a in mv for b in mv if a[0].Name in arm_names and b[0].Name not in arm_names
                          and not _joint(a[0].Name, b[0].Name)]
                hits = _overlaps(pairs, tol)
                if hits:
                    out[str((st, z, sw))] = hits
    set_steering(0.0, doc)
    set_pose(P.wire_z, 0.0, doc)
    return out


def clearance(doc=None, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Sensor face to the wire (work), and the smallest distance of carriage and arm to the right tyres over the
    poses (tyre envelopes, front steered)."""
    doc = active_doc(doc)
    head = global_shape(doc.getObject("head")).BoundBox
    out = {"face_to_wire_mm": round(P.wire_x - head.XMax, 1)}
    best = (1e9, None, None)
    for st in steer:
        tg = [tyre_envelope(P.robot_wheel_x, st)]
        rear = tyre_envelope(P.robot_wheel_x, 0.0)
        rear.translate(V(0, -2 * P.robot_axle_y, 0))
        tg.append(rear)
        for z in (P.Z_RANGE[0], P.Z_RANGE[1]):
            for sw in (0.0, P.swing_max):
                set_pose(z, sw, doc)
                for n in ("carriage", "arm", "head", "bumper"):
                    s = global_shape(doc.getObject(n))
                    for t in tg:
                        d = s.distToShape(t)[0]
                        if d < best[0]:
                            best = (d, n, (st, z, sw))
    set_pose(P.wire_z, 0.0, doc)
    out["tyres"] = (round(best[0], 1), best[1], best[2])
    return out


MASS_FIXED = {"stepper": 1.2, "camera": 0.4, "head": 0.9}
DENSITY = (("bumper", P.pe),)


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Carriage"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m)
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


