def track_camera(i, fov=38.0):
    import FreeCADGui as Gui
    from pivy import coin
    eye, tgt = _s["frames"][i]["cam"]
    view = Gui.ActiveDocument.ActiveView
    cam = view.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    if hasattr(cam, "heightAngle"):
        cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(100.0)
    cam.farDistance.setValue(150000.0)


_timer = None


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(step=2):
    """Live in the GUI (every 'step'-th frame)."""
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    state = {"i": 0}

    def tick():
        i = state["i"]
        if i >= len(_s["frames"]):
            stop()
            return
        apply_frame(i)
        track_camera(i)
        Gui.updateGui()
        state["i"] += step

    _timer = QtCore.QTimer()
    _timer.timeout.connect(tick)
    _timer.start(int(1000 / P.FPS * step))


def summary():
    return L.summary(_s["sc"]["key"])


def _actor_shapes():
    """Global shapes of the visible solids per actor (top-level part: working robot, refiller, trailer)."""
    out = {}
    for o in _s["doc"].Objects:
        if not o.isDerivedFrom("Part::Feature") or o.Name.startswith("tla_") or o.Shape.isNull():
            continue
        if o.ViewObject is not None and not o.ViewObject.isVisible():
            continue
        root, p = o, o.getParentGeoFeatureGroup()
        while p is not None:
            root, p = p, p.getParentGeoFeatureGroup()
        if root is o or not o.Shape.Solids:
            continue
        s = o.Shape.copy()
        s.Placement = o.getGlobalPlacement()
        out.setdefault(root.Name, []).append((o.Name, s))
    return out


def check_frame(i, min_vol=1000.0):
    """Overlaps (mm3 > min_vol) between parts of different actors in frame i."""
    apply_frame(i)
    groups = _actor_shapes()
    names = sorted(groups)
    hits = []
    for a in range(len(names)):
        for b in range(a + 1, len(names)):
            for na, sa in groups[names[a]]:
                for nb, sb in groups[names[b]]:
                    if not sa.BoundBox.intersect(sb.BoundBox):
                        continue
                    v = sa.common(sb).Volume
                    if v > min_vol:
                        hits.append((i, na, nb, round(v / 1000.0, 1)))
    return hits


def check_run(step=3, near=7000.0, log=None):
    """3D check over the run: every step-th frame in which two actors come within 'near' mm in plan view."""
    sc, frames = _s["sc"], _s["frames"]
    hits = []
    last = None
    for i in range(0, len(frames), step):
        f = frames[i]
        # skip frames in which nothing moved 100 mm (or the arm 20 mm) since the last checked one
        key = [v for k in ("worker", "refiller") if k in f for v in f[k][:2]] + [f["arm_lift"] * 5.0]
        if last is not None and max(abs(a - b) for a, b in zip(key, last)) < 100.0:
            continue
        pts = []
        if sc["worker"] is not None and f["worker"][5]:
            pts.append(L.centre(f["worker"], P.WORKER_AXLE))
        if sc["refiller"] is not None:
            pts.append(L.centre(f["refiller"], P.REFILLER_AXLE))
        if sc["trailer"] is not None:
            pts.append(L.trailer_world((0.0, 1100.0), sc["trailer"]))
        close = any(math.hypot(pts[a][0] - pts[b][0], pts[a][1] - pts[b][1]) < near
                    for a in range(len(pts)) for b in range(a + 1, len(pts)))
        if not close:
            continue
        last = key
        hits += check_frame(i)
        if log and i % 60 == 0:
            with open(log, "a", encoding="utf-8", newline="\n") as handle:
                handle.write("check %d / %d, %d overlaps\n" % (i, len(frames), len(hits)))
    return hits


def _same(a, b):
    return a["t"] == b["t"] and a["cam"] == b["cam"]


def render_all(folder, size=P.VIDEO_SIZE, log=None, only=None):
    """All frames as frame_0000.png ...; repeated frames (the holds at the start and the end) are copied."""
    import FreeCADGui as Gui
    os.makedirs(folder, exist_ok=True)
    Gui.setActiveDocument(_s["doc"].Name)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    frames = _s["frames"]
    idx = range(len(frames)) if only is None else only
    prev = None
    for i in idx:
        path = os.path.join(folder, "frame_%04d.png" % i)
        if prev is not None and prev[0] == i - 1 and _same(frames[i], frames[prev[0]]):
            shutil.copyfile(prev[1], path)
        else:
            apply_frame(i)
            track_camera(i)
            Gui.updateGui()
            view.saveImage(path, size[0], size[1], "White")
        prev = (i, path)
        if log and i % 25 == 0:
            with open(log, "a", encoding="utf-8", newline="\n") as handle:
                handle.write("frame %d / %d\n" % (i, len(frames)))
    return len(frames)
