def _spin(objs, angle_rad):
    rot = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -math.degrees(angle_rad)))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            o = objs.get("%s_%s" % (tag, part))
            if o is not None:
                o.Placement = rot


def _steer(objs, delta, wb):
    left, right = L.wheel_angles(delta, wb)
    objs["FL_steered"].Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), left))
    objs["FR_steered"].Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), right))


def apply_lift(lift):
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    doc = _s["doc"]
    q = round(lift / 15.0) * 15.0
    if _cache["lift"] == q:
        return
    BPA.set_lift(q, doc, B4.PREFIX)
    if q not in _cache["hoses"]:
        _cache["hoses"][q] = {(r, liq): G3.hose(r, liq, q) for liq in ("A", "B") for r in range(5)}
    for (r, liq), shape in _cache["hoses"][q].items():
        doc.getObject("hose_%s_%d" % (liq, r)).Shape = shape
    _cache["lift"] = q


def _tank_shape(liq, litres):
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    k = (liq, round(litres * 2.0) / 2.0)
    if k not in _cache["tank"]:
        _cache["tank"][k] = G4.liquid(liq, k[1])
    return _cache["tank"][k]


def apply_levels(lv):
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    doc = _s["doc"]
    sc = _s["sc"]
    for i, liq in enumerate(("A", "B")):
        if sc["worker"] is not None:
            key = ("w", liq, round(lv["worker"][i] * 2.0))
            if _cache["levels"].get(("w", liq)) != key:
                doc.getObject("tank_liquid_" + liq).Shape = _tank_shape(liq, lv["worker"][i])
                _cache["levels"][("w", liq)] = key
        if sc["refiller"] is not None:
            key = round(lv["refiller"][i] * 2.0)
            if _cache["levels"].get(("r", liq)) != key:
                doc.getObject("ibc%s_liquid" % liq.lower()).Shape = BD.liquid_shape(liq, lv["refiller"][i])
                _cache["levels"][("r", liq)] = key
        if sc["trailer"] is not None:
            key = round(lv["trailer"][i] * 2.0)
            if _cache["levels"].get(("t", liq)) != key:
                S2.B.set_ibc_level(doc, "ibc%d" % (i + 1), lv["trailer"][i])
                _cache["levels"][("t", liq)] = key


def nozzle_world(src, liq, f):
    """Nozzle tip (x, y, z) of the pump source in the field."""
    sc = _s["sc"]
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    if src == "refiller":
        x, y = L.to_world(f["refiller"], (BD.P.nozzle_x[liq], BD.P.mast_xy[1]), P.REFILLER_AXLE)
        return x, y, BD.P.nozzle_tip_z
    x, y = L.trailer_world((-L.REACH[liq], L.MAST_Y), sc["trailer"])
    return x, y, S2.P.nozzle_tip_z + f["arm_lift"]


def stream_bottom(dst):
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    if dst == "worker":
        return B4.P.TANK_TOP + B4.P.funnel_neck
    return BD.P.fill_cone_z0


def apply_streams(f):
    doc = _s["doc"]
    on = {liq: (src, dst) for src, dst, liq in f["pumps"]}
    for liq in ("A", "B"):
        o = doc.getObject("tla_stream_" + liq)
        if liq in on:
            src, dst = on[liq]
            x, y, z = nozzle_world(src, liq, f)
            zb = stream_bottom(dst)
            o.Shape = Part.makeCylinder(11.0, z - zb, V(x, y, zb))
        elif not o.Shape.isNull():
            o.Shape = Part.Shape()


def apply_beacon(f):
    doc = _s["doc"]
    if _s["sc"]["trailer"] is None:
        return
    pumping = any(src == "trailer" for src, dst, liq in f["pumps"])
    off = P.COLOR["beacon_off"]
    for n, col, lit in (("beacon_green", (0.10, 0.85, 0.25), not pumping), ("beacon_amber", (1.0, 0.6, 0.05), pumping),
                        ("beacon_red", (0.85, 0.08, 0.06), False)):
        o = doc.getObject(n)
        if o is not None:
            o.ViewObject.ShapeColor = col if lit else off


def apply_strips(f):
    """Worked strips: the pass the working robot leaves from the far end up to where its knives came out, the next
    pass from where they went in."""
    doc = _s["doc"]
    first = _s["sc"]["passes"][0]
    for p, (y0, y1) in f["strips"].items():
        o = doc.getObject("tla_strip_%d" % p)
        if o is None:
            continue
        lo, hi = (P.FIELD_Y[0] - 40000.0 if p == first else y0), min(y1, -60.0)
        key = (round(lo / 50.0), round(hi / 50.0))
        if _cache["strips"].get(p) != key:
            o.Shape = strip_shape(p, lo, hi)
            doc.getObject("tla_seam_%d" % p).Shape = seam_shape(p, lo, hi)
            _cache["strips"][p] = key


def apply_frame(i):
    f = _s["frames"][i]
    doc = _s["doc"]
    sc = _s["sc"]
    B4, BD, S2, BPA, G3, G4 = _s["mods"]
    if sc["worker"] is not None:
        w = _s["objs"]["w"]
        pose = f["worker"]
        w["Robot"].Placement = worker_placement(pose)
        w["Robot"].ViewObject.Visibility = bool(pose[5])
        _steer(w, pose[3], P.WORKER_WB)
        _spin(w, pose[4])
        apply_lift(f["lift"])
    if sc["refiller"] is not None:
        r = _s["objs"]["r"]
        pose = f["refiller"]
        r["Robot"].Placement = refiller_placement(pose)
        _steer(r, pose[3], P.REFILLER_WB)
        _spin(r, pose[4])
    if sc["trailer"] is not None and _cache["arm"] != round(f["arm_lift"]):
        S2.set_lift(f["arm_lift"], doc)
        _cache["arm"] = round(f["arm_lift"])
    apply_levels(f["levels"])
    apply_streams(f)
    apply_beacon(f)
    apply_strips(f)
    doc.recompute()


