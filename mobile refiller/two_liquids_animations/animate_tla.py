def worker_placement(pose):
    cx, cy = L.centre(pose, P.WORKER_AXLE)
    return App.Placement(V(cx, cy, 0.0), App.Rotation(V(0, 0, 1), pose[2]))


def refiller_placement(pose):
    cx, cy = L.centre(pose, P.REFILLER_AXLE)
    return App.Placement(V(cx, cy, 0.0), App.Rotation(V(0, 0, 1), pose[2]))


def trailer_placement(origin):
    return App.Placement(V(origin[0], origin[1], 0.0), App.Rotation(V(0, 0, 1), -90.0))


def build(key, run=None):
    B4, BD, S2, BPA, G3, G4 = load_modules()
    sc, frames = run if run is not None else L.frames(key)
    name = DOC_PREFIX + key
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    doc.Label = "Two liquids - " + key
    doc.Comment = "Generated by animate_tla.py (no need to save)."
    f0 = frames[0]
    lv = f0["levels"]
    objs = {}
    if sc["worker"] is not None:
        B4.build_into(doc, P.LIFT_MAX, litres=lv["worker"], placement=worker_placement(f0["worker"]))
        objs["w"] = {n: doc.getObject(n) for n in ("Robot", "FL_steered", "FR_steered")}
        for tag in ("RL", "RR", "FL", "FR"):
            for part in ("tire", "rim", "hub"):
                objs["w"]["%s_%s" % (tag, part)] = doc.getObject("%s_%s" % (tag, part))
    if sc["refiller"] is not None:
        robot, robjs = BD.build_robot(doc, "mobile_refiller_two_ibc", refiller_placement(f0["refiller"]))
        BD.build_refiller_into(doc, robot, 0.0, lv["refiller"])
        robjs["Robot"] = robot
        objs["r"] = robjs
    if sc["trailer"] is not None:
        S2.build_into(doc, 0.0, lv["trailer"], placement=trailer_placement(sc["trailer"]))
    ground(doc)
    for p in sorted(set(sc["done"]) | set(sc["passes"])):
        add(doc, "tla_strip_%d" % p, Part.Shape(), P.COLOR["worked"])
        add(doc, "tla_seam_%d" % p, Part.Shape(), P.COLOR["seam"])
    add(doc, "tla_stream_A", Part.Shape(), P.COLOR["stream_A"])
    add(doc, "tla_stream_B", Part.Shape(), P.COLOR["stream_B"])
    doc.recompute()
    _s.clear()
    _s.update({"doc": doc, "sc": sc, "frames": frames, "objs": objs, "mods": (B4, BD, S2, BPA, G3, G4)})
    for k in ("strips", "levels"):
        _cache[k].clear()
    _cache["lift"] = None
    _cache["arm"] = None
    for p in sc["done"]:
        doc.getObject("tla_strip_%d" % p).Shape = strip_shape(p, P.FIELD_Y[0] - 40000.0, -60.0)
        doc.getObject("tla_seam_%d" % p).Shape = seam_shape(p, P.FIELD_Y[0] - 40000.0, -60.0)
    apply_frame(0)
    return doc


