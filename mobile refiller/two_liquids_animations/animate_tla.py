def load_modules():
    if P.CMB4_FOLDER not in sys.path:
        sys.path.insert(0, P.CMB4_FOLDER)
    import build_cmb4
    build_cmb4.setup_path()
    for f in (P.MRD_FOLDER, P.SIT2_FOLDER):
        if f in sys.path:
            sys.path.remove(f)
        sys.path.insert(0, f)
    import build_mrd
    import build_sit2
    import build_pa
    import cmb3_parts
    import cmb4_parts
    return build_cmb4, build_mrd, build_sit2, build_pa, cmb3_parts, cmb4_parts


def add(doc, name, shape, color, transparency=0):
    o = doc.addObject("Part::Feature", name)
    o.Shape = shape
    if o.ViewObject is not None:
        o.ViewObject.ShapeColor = color
        o.ViewObject.LineColor = color
        o.ViewObject.Transparency = transparency
    return o


def box(x, y, z):
    return Part.makeBox(x[1] - x[0], y[1] - y[0], z[1] - z[0], V(x[0], y[0], z[0]))


def ground(doc):
    c = P.COLOR
    xr = P.X_RANGE
    add(doc, "tla_field", box(xr, (P.FIELD_Y[0] - 40000.0, 0.0), (-20.0, 0.0)), c["field"])
    add(doc, "tla_headland", box(xr, P.HEADLAND_Y, (-20.0, 0.0)), c["headland"])
    add(doc, "tla_track", box(xr, P.TRACK_Y, (-20.0, 0.5)), c["track"])
    add(doc, "tla_edge", box(xr, (-30.0, 30.0), (0.0, 1.0)), c["edge"])
    posts = [Part.makeCylinder(50.0, 1100.0, V(x, P.TRACK_Y[0] - 150.0, 0.0))
             for x in range(int(xr[0]), int(xr[1]), 3000)]
    wire = [box(xr, (P.TRACK_Y[0] - 160.0, P.TRACK_Y[0] - 140.0), (z, z + 15.0)) for z in (650.0, 950.0)]
    add(doc, "tla_fence_posts", Part.makeCompound(posts), (0.45, 0.33, 0.20))
    add(doc, "tla_fence_wires", Part.makeCompound(wire), (0.75, 0.75, 0.75))


def strip_shape(p, y0, y1):
    """Worked strip of one pass: dark soil with five seams (rows 200 apart)."""
    if y1 - y0 < 1.0:
        return Part.Shape()
    x = L.pass_x(p)
    soil = box((x - 480.0, x + 480.0), (y0, y1), (0.0, 1.5))
    return soil


def seam_shape(p, y0, y1):
    if y1 - y0 < 1.0:
        return Part.Shape()
    x = L.pass_x(p)
    return Part.makeCompound([box((x + r - 25.0, x + r + 25.0), (y0, y1), (1.5, 3.0))
                              for r in (-400.0, -200.0, 0.0, 200.0, 400.0)])


