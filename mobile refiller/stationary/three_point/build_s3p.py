def check_interference(doc=None, tol=1.0):
    return B.check_interference(active(doc), ROOT, OK, tol)


def check_fit(doc=None, tol=1.0):
    return B.check_fit(active(doc), ROOT, T.mast_spec(), OK, None, tol)


def clearance(doc=None):
    doc = active(doc)
    M = T.mast_spec()
    objs = B.kit_objects(doc, ROOT)
    bb = B.bbox(doc, objs)
    keep = doc.getObject("Arm").Placement
    B.set_arm(doc, M, 90.0)
    bt = B.bbox(doc, objs)
    doc.getObject("Arm").Placement = keep
    doc.recompute()
    left, right = P.half_widths()
    return {"size_arm_out": (round(bb.XLength), round(bb.YLength), round(bb.ZLength)),
            "size_transport": (round(bt.XLength), round(bt.YLength), round(bt.ZLength)),
            "rear_overhang_transport": round(-bt.YMin - P.leg_xy[1] - P.foot[0] / 2.0),
            "half_widths": (left, right), "reach": M["reach"], "platform_z": P.plat_z, "ibc_top_z": P.ibc_top(),
            "nozzle_tip_z": C.nozzle_tip_z, "antenna_top_z": G.antenna_top(M), "lower_pins": P.lower_pin_yz,
            "top_pin_z": P.top_pin_z(), "box_bottom_z": P.box_xyz[2], "pump_axis_z": P.box_xyz[2] + C.pump_axis[1],
            "bottle_bottom_z": P.plat_z + C.bottle_z0}


def mass_properties(doc=None):
    doc = active(doc)
    groups = {
        "frame": lambda o: o.Name.startswith(("frame_", "hitch_")),
        "box": lambda o: o.Name.startswith("box_"),
        "mast": lambda o: o.Name.startswith(("mast", "arm", "beacon")),
        "hoses": lambda o: o.Name.startswith("hose_"),
        "ibc_empty": B.is_ibc,
        "liquid": B.is_liquid,
    }
    density = {"hose_suction": B.HOSE, "hose_discharge": B.HOSE}
    return B.mass_groups(doc, ROOT, groups, None, density)


