"""Model of the stationary refill station in a three-point-linkage frame (1 IBC, category 2).

Use in FreeCAD (via run_in_freecad.py, or with this folder and ../ on sys.path):
    import build_s3p
    build_s3p.build()                      # saves FCStd and STEP (arm out to the left, IBC 800 l)
    build_s3p.set_arm(angle)               # 0 = out left, 90 = folded backwards over the IBC (transport), 180 = right
    build_s3p.set_lift(300)                # frame lifted by the tractor (image pose only)
    build_s3p.check_interference()         # overlap in the current pose (must be empty)
    build_s3p.check_fit()                  # arm 0 .. 180 deg (must be empty)
    build_s3p.clearance()                  # sizes, heights, reach
    build_s3p.mass_properties()            # masses and centres of gravity
    build_s3p.build_docked()               # scene: working robot stopped with its funnel under the nozzle
    build_s3p.render_all()                 # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import s3p_params as P
import s3p_parts as T
import stc_params as C
import stc_parts as G
import stc_build as B

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Stationary_Three_Point"
DOCKED_DOC = DOC_NAME + "_refill"
ROOT = "Station"
WORKER = "Robot"


def build_into(doc, arm=0.0, litres=None):
    M = T.mast_spec()
    litres = 0.8 * C.ibc_nominal_l if litres is None else litres
    root = B.new_part(doc, None, ROOT, "stationary_refiller_three_point")
    fr = B.new_part(doc, root, "Frame", "frame_on_legs")
    B.add_shape(doc, fr, "frame_side_rails", "side_rails_80x40x3", T.side_rails(), "frame")
    B.add_shape(doc, fr, "frame_end_rails", "end_and_middle_rails_80x40x3", T.end_rails(), "frame")
    B.add_shape(doc, fr, "frame_legs", "legs_60x60x4", T.legs(), "frame")
    B.add_shape(doc, fr, "frame_feet", "foot_plates_160x10", T.feet(), "frame")
    B.add_shape(doc, fr, "frame_lower", "lower_rails_60x40x3", T.lower_rails(), "frame")
    B.add_shape(doc, fr, "frame_box_sup", "box_supports_40x40x3", T.box_supports(), "frame")
    B.add_shape(doc, fr, "frame_braces", "diagonal_braces_42", T.braces(), "frame")
    B.add_shape(doc, fr, "frame_guides", "corner_guides_angle_50x5", T.corner_guides(), "frame")
    hk = B.new_part(doc, root, "Hitch", "three_point_hitch_cat2")
    B.add_shape(doc, hk, "hitch_plates", "hitch_plates_12mm", T.hitch_plates(), "frame")
    B.add_shape(doc, hk, "hitch_lower_pins", "lower_link_pins_cat2_D28", T.lower_pins(), "zinc")
    B.add_shape(doc, hk, "hitch_mast_foot", "mast_foot_beam_80x80x4", T.mast_foot(), "frame")
    B.add_shape(doc, hk, "hitch_mast_link", "mast_link_100x40x3", T.mast_link(), "frame")
    B.add_shape(doc, hk, "hitch_top_plates", "top_link_plates_12mm", T.top_link_plates(), "frame")
    B.add_shape(doc, hk, "hitch_top_pin", "top_link_pin_cat2_D25", T.top_pin(), "zinc")
    B.add_shape(doc, hk, "hitch_braces", "hitch_braces_50", T.hitch_braces(), "frame")
    B.build_ibc(doc, root, "ibc1", T.ibc_placement(), litres, strap_axis="y", strap_z=12.0)
    B.build_box(doc, root, T.box_placement())
    hz = B.new_part(doc, root, "Hoses", "hoses")
    B.add_shape(doc, hz, "hose_suction", "suction_hose_1.5in", T.suction_hose(), "hose")
    B.add_shape(doc, hz, "hose_discharge", "discharge_hose_up_inside_mast", T.discharge_hose(M), "hose")
    mast = B.build_mast_arm(doc, root, M, arm, beacon_face="+x")
    B.add_shape(doc, mast, "mast_gussets", "mast_gussets_10mm",
                G.mast_gussets(M, M["z0"], ("+x",), h=200.0), "frame")
    return root, M


def build(arm=0.0, litres=None, save=True, step=True):
    doc = B.new_doc(DOC_NAME, "Stationary refiller - three-point frame",
                    "Generated by build_s3p.py from s3p_params.py and ../stc_*.py. Frame coordinates: origin = middle of "
                    "the IBC footprint on the ground, x = right, y = towards the tractor, z = up. Arm: set_arm(angle).")
    build_into(doc, arm, litres)
    doc.recompute()
    base = os.path.join(FOLDER, DOC_NAME)
    if save:
        doc.saveAs(base + ".FCStd")
    if step:
        B.export_step(doc, ROOT, base + ".step")
    return doc


def active(doc=None):
    return doc if doc is not None else App.getDocument(DOC_NAME)


def set_arm(angle, doc=None):
    B.set_arm(active(doc), T.mast_spec(), angle)


def set_lift(h, doc=None):
    """Image pose only: the whole station lifted by the tractor."""
    doc = active(doc)
    doc.getObject(ROOT).Placement = App.Placement(V(0, 0, h), App.Rotation())
    doc.recompute()


def set_levels(litres, doc=None):
    doc = active(doc)
    B.set_ibc_level(doc, "ibc1", litres)
    doc.recompute()


