def render_all():
    import FreeCADGui as Gui
    out = []
    M = T.mast_spec()
    doc = build(save=False, step=False)
    B.add_floor(doc, (-2400.0, 1400.0), (-1400.0, 1600.0))
    out.append(B.save_view(PREVIEW_DIR, "1_iso_three_point.png", (1.0, -1.0, -0.7), (-350, 100, 1000), height=3000))
    out.append(B.save_view(PREVIEW_DIR, "2_side.png", (1.0, 0.0, 0.0), (0, 100, 1050), height=2400))
    out.append(B.save_view(PREVIEW_DIR, "3_hitch_from_the_tractor.png", (-0.35, -1.0, -0.25), (-300, 600, 900),
                           height=2600))
    B.set_visible(doc, B.BOX_COVER, False)
    out.append(B.save_view(PREVIEW_DIR, "4_control_box_under_the_platform.png", (0.6, 0.9, -0.45), (0, -100, 400),
                           height=1500))
    B.set_visible(doc, B.BOX_COVER, True)
    ibc = [o.Name for o in B.kit_objects(doc, ROOT) if o.Name.startswith("ibc")]
    B.set_visible(doc, ibc, False)
    out.append(B.save_view(PREVIEW_DIR, "5_frame_without_ibc.png", (1.0, -0.9, -0.9), (0, 100, 600), height=2600))
    B.set_visible(doc, ibc, True)
    B.set_arm(doc, M, 90.0)
    set_lift(P.lift_height, doc)
    B.remove(doc, [B.GROUND[0]])
    B.add_floor(doc, (-2400.0, 1400.0), (-1400.0, 1600.0))
    out.append(B.save_view(PREVIEW_DIR, "6_lifted_for_transport.png", (1.0, -0.6, -0.4), (0, 0, 1100), height=2800))
    App.closeDocument(doc.Name)
    doc = build_docked()
    Gui.updateGui()
    B.add_stream(doc, M)
    B.add_floor(doc, (-3000.0, 1400.0), (-2600.0, 2200.0))
    out.append(B.save_view(PREVIEW_DIR, "7_refill_iso.png", (1.0, 0.8, -0.6), (-800, 0, 700), height=4000))
    out.append(B.save_view(PREVIEW_DIR, "8_refill_top.png", (0.0, 0.0, -1.0), (-750, -200, 0), height=4600,
                           up=(0.0, 1.0, 0.0)))
    out.append(B.save_view(PREVIEW_DIR, "9_nozzle_over_funnel.png", (1.0, 0.5, -0.35), (-M["reach"], M["y"], 1200),
                           height=900))
    App.closeDocument(doc.Name)
    build()
    return out
