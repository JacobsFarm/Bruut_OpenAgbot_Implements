def build_docked(litres=None, rx_fill=None, heading=0.0):
    doc = B.new_doc(DOCKED_DOC, "Three-point station - refill",
                    "Generated by build_s3p.build_docked(). The working robot stopped with its funnel under the nozzle.")
    root, M = build_into(doc, 0.0, litres)
    B.build_worker(doc, B.worker_placement(M, 0.0, heading), rx_fill=rx_fill)
    doc.recompute()
    return doc


def check_docked(doc=None, tol=1.0):
    return B.check_docked(doc or App.getDocument(DOCKED_DOC), ROOT, WORKER, OK, tol)


def docked_gap(doc=None):
    return B.min_gap(doc or App.getDocument(DOCKED_DOC), ROOT, WORKER)


