"""Model of the stationary refill station on a standard flat wagon (bale wagon) with rows of IBCs.

Use in FreeCAD (via run_in_freecad.py, or with this folder and ../ on sys.path):
    import build_sfw
    build_sfw.build()                      # saves FCStd and STEP (arm out to the left, IBCs 800 l)
    build_sfw.set_arm(angle)               # 0 = out left, -90 = folded forwards along the left edge (transport)
    build_sfw.check_interference()         # overlap in the current pose (must be empty)
    build_sfw.check_fit()                  # arm -90 .. 0 deg (must be empty)
    build_sfw.clearance()                  # sizes, heights, reach
    build_sfw.mass_properties()            # masses and centres of gravity
    build_sfw.build_docked()               # scene: working robot stopped with its funnel under the nozzle
    build_sfw.render_all()                 # all images in previews/
"""
import os

import FreeCAD as App

import sfw_params as P
import sfw_parts as T
import stc_params as C
import stc_parts as G
import stc_build as B

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Stationary_Flat_Wagon"
DOCKED_DOC = DOC_NAME + "_refill"
ROOT = "Station"
WAGON = "Wagon"
WORKER = "Robot"


def ibc_tags():
    return ["ibc%d" % (i + 1) for i in range(len(P.ibc_positions()))]


def build_wagon(doc):
    """The standard wagon (not part of the kit: own App::Part next to the station)."""
    w = B.new_part(doc, None, WAGON, "standard_flat_wagon_8m")
    B.add_shape(doc, w, "wagon_deck", "deck_chequer_plate_5mm", T.deck_plate(), "deck")
    B.add_shape(doc, w, "wagon_border", "border_profile_200", T.border(), "wagon")
    B.add_shape(doc, w, "wagon_cross", "cross_members_100x50x4", T.cross_members(), "wagon")
    B.add_shape(doc, w, "wagon_beams", "main_beams_IPE200", T.main_beams(), "wagon")
    B.add_shape(doc, w, "wagon_axles", "axles_120x12", T.axles(), "steel")
    B.add_shape(doc, w, "wagon_tyres", "tyres_" + P.tyre[3], T.tyres(), "tyre")
    B.add_shape(doc, w, "wagon_rims", "rims", T.rims(), "rim")
    up, lo = T.turntable()
    B.add_shape(doc, w, "wagon_tt_upper", "turntable_upper_ring", up, "wagon")
    B.add_shape(doc, w, "wagon_tt_lower", "turntable_lower_ring", lo, "wagon")
    B.add_shape(doc, w, "wagon_bolster", "front_bolster", T.bolster(), "wagon")
    B.add_shape(doc, w, "wagon_springs", "rear_springs_and_hangers", T.springs(), "steel")
    B.add_shape(doc, w, "wagon_drawbar", "drawbar", T.drawbar(), "wagon")
    B.add_shape(doc, w, "wagon_eye", "tow_eye_40", T.tow_eye(), "steel")
    sl, leg, pin = T.drawbar_stand()
    B.add_shape(doc, w, "wagon_stand", "drawbar_stand_sleeve", sl, "wagon")
    B.add_shape(doc, w, "wagon_stand_leg", "drawbar_stand_leg", leg, "steel")
    B.add_shape(doc, w, "wagon_stand_pin", "drawbar_stand_pin", pin, "zinc")
    hs, ls, plate = T.rear_lights()
    B.add_shape(doc, w, "wagon_lights", "rear_light_clusters", hs, "black")
    B.add_shape(doc, w, "wagon_lenses", "rear_light_lenses", ls, "red")
    B.add_shape(doc, w, "wagon_plate", "number_plate", plate, "plate")
    return w


def build_into(doc, arm=0.0, litres=None):
    M = T.mast_spec()
    litres = 0.8 * C.ibc_nominal_l if litres is None else litres
    build_wagon(doc)
    root = B.new_part(doc, None, ROOT, "stationary_refiller_kit_on_flat_wagon")
    kit = B.new_part(doc, root, "Kit", "skid_guides_box_hangers")
    B.add_shape(doc, kit, "kit_skid", "mast_skid_80x40x3", T.skid(), "frame")
    B.add_shape(doc, kit, "kit_mast_base", "mast_base_plate_12mm", T.mast_base(), "frame")
    B.add_shape(doc, kit, "kit_guides", "corner_guides_angle_50x5", T.corner_guides(), "frame")
    B.add_shape(doc, kit, "kit_box_sup", "box_supports_40x40x3", T.box_supports(), "frame")
    B.add_shape(doc, kit, "kit_hangers", "box_hangers_40x8", T.box_hangers(), "frame")
    for tag, (x, y) in zip(ibc_tags(), P.ibc_positions()):
        B.build_ibc(doc, root, tag, T.ibc_placement(x, y), litres, strap_axis="y", strap_z=12.0)
    B.build_box(doc, root, T.box_placement())
    hz = B.new_part(doc, root, "Hoses", "hoses")
    B.add_shape(doc, hz, "hose_suction", "suction_hoses_and_header_1.5in", T.suction_hoses(), "hose")
    B.add_shape(doc, hz, "hose_discharge", "discharge_hose_up_inside_mast", T.discharge_hose(M), "hose")
    mast = B.build_mast_arm(doc, root, M, arm, beacon_face="+x")
    B.add_shape(doc, mast, "mast_struts", "mast_struts_42", T.mast_struts(M), "frame")
    return root, M


def build(arm=0.0, litres=None, save=True, step=True):
    doc = B.new_doc(DOC_NAME, "Stationary refiller - flat wagon",
                    "Generated by build_sfw.py from sfw_params.py and ../stc_*.py. Wagon coordinates: origin = middle "
                    "of the deck on the ground, x = right, y = forward (drawbar), z = up. Arm: set_arm(angle).")
    build_into(doc, arm, litres)
    doc.recompute()
    base = os.path.join(FOLDER, DOC_NAME)
    if save:
        doc.saveAs(base + ".FCStd")
    if step:
        B.export_step(doc, ROOT, base + ".step")
    return doc


def active(doc=None):
    return doc if doc is not None else App.getDocument(DOC_NAME)


def set_arm(angle, doc=None):
    B.set_arm(active(doc), T.mast_spec(), angle)


def set_levels(litres, doc=None):
    doc = active(doc)
    for t in ibc_tags():
        B.set_ibc_level(doc, t, litres)
    doc.recompute()


