def _all(doc):
    return B.checked(B.kit_objects(doc, ROOT)) + B.checked(B.kit_objects(doc, WAGON))


def check_interference(doc=None, tol=1.0):
    """Kit parts among themselves and against the wagon."""
    doc = active(doc)
    mine = [(o, B.global_shape(o)) for o in B.checked(B.kit_objects(doc, ROOT))]
    wagon = [(o, B.global_shape(o)) for o in B.checked(B.kit_objects(doc, WAGON))]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))]
    pairs += [(a, b) for a in mine for b in wagon]
    return B.overlaps(pairs, OK, tol)


def check_fit(doc=None, tol=1.0):
    doc = active(doc)
    M = T.mast_spec()
    mine = B.checked(B.kit_objects(doc, ROOT))
    still = [(o, B.global_shape(o)) for o in mine if not B.in_arm(o)]
    still += [(o, B.global_shape(o)) for o in B.checked(B.kit_objects(doc, WAGON))]
    keep = doc.getObject("Arm").Placement
    out = {}
    for a in range(-90, 1, 15):
        doc.getObject("Arm").Placement = B.arm_placement(M, a)
        doc.recompute()
        locked = a in (-90, 0)
        mv = [(o, B.global_shape(o)) for o in mine if B.in_arm(o) and (locked or B.base_name(o.Name) != "arm_lock_pin")]
        hits = B.overlaps([(x, y) for x in mv for y in still], OK, tol)
        if hits:
            out[a] = hits
    doc.getObject("Arm").Placement = keep
    doc.recompute()
    return out


def clearance(doc=None):
    doc = active(doc)
    M = T.mast_spec()
    objs = B.kit_objects(doc, ROOT) + B.kit_objects(doc, WAGON)
    bb = B.bbox(doc, objs)
    keep = doc.getObject("Arm").Placement
    B.set_arm(doc, M, -90.0)
    bt = B.bbox(doc, objs)
    nozzle_z_folded = B.global_shape(doc.getObject("arm_nozzle")).BoundBox.ZMin
    doc.getObject("Arm").Placement = keep
    doc.recompute()
    return {"size_arm_out": (round(bb.XLength), round(bb.YLength), round(bb.ZLength)),
            "size_transport": (round(bt.XLength), round(bt.YLength), round(bt.ZLength)),
            "reach": M["reach"], "nozzle_x_docking": P.nozzle_x(), "deck_top": P.deck_top, "ibc_top_z": P.ibc_top(),
            "nozzle_tip_z": P.nozzle_z, "nozzle_above_deck_folded": round(nozzle_z_folded - P.deck_top, 1),
            "antenna_top_z": G.antenna_top(M), "box_bottom_z": P.box_z(), "pump_axis_z": P.box_z() + C.pump_axis[1],
            "bottle_bottom_z": P.deck_top + C.bottle_z0, "rows": P.rows()}


def mass_properties(doc=None):
    doc = active(doc)
    groups = {
        "kit": lambda o: o.Name.startswith("kit_"),
        "box": lambda o: o.Name.startswith("box_"),
        "mast": lambda o: o.Name.startswith(("mast", "arm", "beacon")),
        "hoses": lambda o: o.Name.startswith("hose_"),
        "ibc_empty": B.is_ibc,
        "liquid": B.is_liquid,
    }
    density = {"hose_suction": B.HOSE, "hose_discharge": B.HOSE}
    out = B.mass_groups(doc, ROOT, groups, None, density)
    fixed = {"wagon_tyres": 4 * 70.0, "wagon_rims": 4 * 35.0, "wagon_lenses": 0.4, "wagon_lights": 2.0,
             "wagon_plate": 0.5}
    m, c = B.sum_mass(B.kit_objects(doc, WAGON), fixed, None)
    out["wagon_kg"] = round(m, 1)
    out["wagon_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


