def build_docked(litres=None, rx_fill=None, heading=0.0):
    doc = B.new_doc(DOCKED_DOC, "Flat wagon station - refill",
                    "Generated by build_sfw.build_docked(). The working robot stopped with its funnel under the nozzle.")
    root, M = build_into(doc, 0.0, litres)
    B.build_worker(doc, B.worker_placement(M, 0.0, heading), rx_fill=rx_fill)
    doc.recompute()
    return doc


def check_docked(doc=None, tol=1.0):
    doc = doc or App.getDocument(DOCKED_DOC)
    worker = [(o, B.global_shape(o)) for o in doc.getObject(WORKER).OutListRecursive
              if o.TypeId == "Part::Feature" and not o.Shape.isNull() and not o.Name.endswith("liquid")]
    station = [(o, B.global_shape(o)) for o in _all(doc)]
    return B.overlaps([(a, b) for a in station for b in worker], OK, tol)


def nozzle_over_funnel_z():
    return P.nozzle_z - C.FUNNEL_RIM_Z


