"""Model of the weeding bed (lying platform) on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_wdb
    build_wdb.build()                      # saves FCStd and STEP
    build_wdb.check_interference()         # overlap (must be empty), parking stands up and down
    build_wdb.check_steering()             # overlap with the front wheel units at +-30 degrees (must be empty)
    build_wdb.check_holes()                # every M10 in a real upper-beam hole
    build_wdb.mass_properties()
    build_wdb.render_all()                 # all images in previews/ (with 2 worker dummies)
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import wdb_params as P
import wdb_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Weeding_Bed"
SAVE_BASE = os.path.join(FOLDER, "Weeding_Bed")
ROOT = "Weeding_bed"

COLOR = {"frame": (0.93, 0.42, 0.08), "zinc": (0.82, 0.84, 0.87), "ply": (0.80, 0.65, 0.42),
         "cushion": (0.10, 0.32, 0.45), "console": (0.15, 0.15, 0.17), "red": (0.85, 0.10, 0.08),
         "yellow": (0.95, 0.80, 0.10), "canopy": (0.95, 0.95, 0.90), "worker": (0.30, 0.45, 0.70)}


def new_part(doc, parent, name, label):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_into(doc, parent=None, stands_down=False):
    root = new_part(doc, parent, ROOT, "weeding_bed_simple")
    fr = new_part(doc, root, "wdb_Frame", "cross_tubes_hangers_side_rails")
    add_shape(doc, fr, "wdb_cross_tubes", "cross_tubes_40x40x3_x1200_front_stubs", G.cross_tubes(), "frame")
    add_shape(doc, fr, "wdb_cross_bolts", "cross_tube_bolts_16xM10", G.cross_bolts(), "zinc")
    add_shape(doc, fr, "wdb_hangers", "hangers_40x40x4_gussets", G.hangers(), "frame")
    add_shape(doc, fr, "wdb_cross_arms", "cross_arms_40x40x4", G.cross_arms(), "frame")
    add_shape(doc, fr, "wdb_side_rails", "side_rails_40x40x3", G.side_rails(), "frame")
    add_shape(doc, fr, "wdb_slats", "cross_slats_40x20", G.slats(), "frame")
    bd = new_part(doc, root, "wdb_Boards", "lying_boards")
    add_shape(doc, bd, "wdb_boards", "plywood_boards_18mm", G.boards_ply(), "ply")
    add_shape(doc, bd, "wdb_cushions", "foam_cushions_chest_wedge_face_rest", G.cushions(), "cushion")
    ct = new_part(doc, root, "wdb_Controls", "hold_to_run_estops")
    add_shape(doc, ct, "wdb_pendants", "hold_to_run_pendants", G.pendants(), "console")
    add_shape(doc, ct, "wdb_pendant_brackets", "pendant_brackets_4mm", G.pendant_brackets(), "zinc")
    eb, em = G.estops()
    add_shape(doc, ct, "wdb_estop_bases", "emergency_stop_boxes", eb, "yellow")
    add_shape(doc, ct, "wdb_estops", "emergency_stop_mushrooms", em, "red")
    st = new_part(doc, root, "wdb_Stands", "parking_stands")
    sf, sl = G.stands(stands_down)
    add_shape(doc, st, "wdb_stand_tubes", "stand_tubes_60x60_cranks", sf, "frame")
    add_shape(doc, st, "wdb_stand_legs", "stand_legs_50x50_pads", sl, "zinc")
    cn = new_part(doc, root, "wdb_Canopy", "sun_canopies")
    add_shape(doc, cn, "wdb_canopy_posts", "canopy_posts_30x30_braces", G.canopy_posts(), "zinc")
    add_shape(doc, cn, "wdb_canopy", "canopy_twin_wall_4mm", G.canopy(), "canopy")
    return root


def build_robot(doc):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True, stands_down=False):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Weeding bed simple"
    doc.Comment = ("Generated by build_wdb.py from wdb_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, stands_down)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("wdb_cross_bolts", "wdb_cross_tubes"), ("wdb_hangers", "wdb_cross_tubes"), ("wdb_hangers", "wdb_cross_arms"),
          ("wdb_side_rails", "wdb_cross_arms"), ("wdb_canopy_posts", "wdb_side_rails"),
          ("wdb_canopy_posts", "wdb_cross_arms"), ("wdb_slats", "wdb_side_rails"), ("wdb_boards", "wdb_side_rails"),
          ("wdb_boards", "wdb_slats"), ("wdb_cushions", "wdb_boards"), ("wdb_pendants", "wdb_pendant_brackets"),
          ("wdb_pendant_brackets", "wdb_side_rails"), ("wdb_estop_bases", "wdb_side_rails"),
          ("wdb_estops", "wdb_estop_bases"), ("wdb_stand_tubes", "wdb_side_rails"),
          ("wdb_stand_legs", "wdb_stand_tubes"), ("wdb_canopy", "wdb_canopy_posts")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x == "wdb_cross_bolts" and y.startswith("upper_beam"):
            return True
    return False


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        vol = sa.common(sb).Volume
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    hits = _overlaps(pairs, tol)
    # parking stands down: legs against the rest
    sf, sl = G.stands(True)
    legs = doc.addObject("Part::Feature", "tmp_legs_down")
    legs.Shape = sl
    hits += [("legs_down",) + h[1:] for h in _overlaps([((legs, sl), b) for b in mine + robot
                                                        if b[0].Name not in ("wdb_stand_tubes", "wdb_stand_legs")], tol)]
    doc.removeObject(legs.Name)
    return hits


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_max, P.robot_steer_max):
        for name in ("FL_steered", "FR_steered"):
            o = doc.getObject(name)
            if o is not None:
                o.Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), st))
        doc.recompute()
        front = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL_", "FR_"))]
        hits = _overlaps([(a, b) for a in mine for b in front], tol)
        if hits:
            out["steer_%+d" % st] = hits
    for name in ("FL_steered", "FR_steered"):
        o = doc.getObject(name)
        if o is not None:
            o.Placement = App.Placement()
    doc.recompute()
    return out


def check_holes(doc=None):
    """Each bolt line (O9 rod) must pass through a hole: common() with the upper beams ~0."""
    doc = active_doc(doc)
    beams = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith("upper_beam")]
    bad = []
    for (x, y) in G.BOLTS:
        rod = Part.makeCylinder(4.5, 60.0, V(x, y, 650.0))
        v = sum(rod.common(b).Volume for b in beams)
        if v > 1.0:
            bad.append((x, y, round(v)))
    return bad


def clearance(doc=None):
    """Smallest distance from the bed (frame, boards, stands) to the front wheel units at 0 and +-30 degrees steering
    and to the rear wheel units (tyre as a plain cylinder envelope for speed)."""
    doc = active_doc(doc)
    mine = Part.makeCompound([global_shape(o) for o in objects_of(doc, ROOT)
                              if o.Name in ("wdb_hangers", "wdb_cross_arms", "wdb_side_rails", "wdb_boards", "wdb_cushions",
                                            "wdb_pendant_brackets", "wdb_pendants", "wdb_slats")])
    out = {}
    for st in (-P.robot_steer_max, 0.0, P.robot_steer_max):
        for name in ("FL_steered", "FR_steered"):
            o = doc.getObject(name)
            if o is not None:
                o.Placement = App.Placement(V(0, 0, 0), App.Rotation(V(0, 0, 1), st))
        doc.recompute()
        sh = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith(("FL_", "FR_", "RL_", "RR_"))
              and not o.Name.endswith(("_tire", "_rim", "_hub"))]
        d = min(mine.distToShape(s)[0] for s in sh)
        out["steer_%+d" % st] = round(d, 1)
    for name in ("FL_steered", "FR_steered"):
        o = doc.getObject(name)
        if o is not None:
            o.Placement = App.Placement()
    doc.recompute()
    # tyres: cylinder envelope O430 x 100 at the four wheels, front ones turned
    d_t = []
    for sx in (-1, 1):
        for sy in (-1, 1):
            for st in ((-30.0, 0.0, 30.0) if sy > 0 else (0.0,)):
                c = Part.makeCylinder(P.robot_tire_d / 2.0, P.robot_tire_w, V(-P.robot_tire_w / 2.0, 0, 0), V(1, 0, 0))
                c.rotate(V(0, 0, 0), V(0, 0, 1), st)
                c.translate(V(sx * P.robot_wheel_x, sy * P.robot_axle_y, P.robot_axle_z))
                d_t.append(mine.distToShape(c)[0])
    out["tyre_min"] = round(min(d_t), 1)
    return out


DENSITY = {"wdb_boards": P.plywood, "wdb_cushions": P.foam_rho * 2.0, "wdb_canopy": P.pc * 0.25}
MASS_FIXED = {"wdb_pendants": 0.8, "wdb_estops": 0.4, "wdb_estop_bases": 0.6}


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity, without the workers."""
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    parts = {}
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
        parts[o.Name] = round(mo, 1)
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"total_kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z)), "parts": parts}


def set_camera(direction, target=None, height=None, up=(0.0, 0.0, 1.0)):
    import FreeCADGui as Gui
    from pivy import coin
    view = Gui.getDocument(DOC_NAME).ActiveView
    view.setCameraType("Orthographic")
    d = V(*direction)
    d.normalize()
    cam = view.getCameraNode()
    tgt = V(*target) if target is not None else V(0, 0, 800)
    eye = tgt - d * 12000.0
    cam.position.setValue(coin.SbVec3f(eye.x, eye.y, eye.z))
    cam.pointAt(coin.SbVec3f(tgt.x, tgt.y, tgt.z), coin.SbVec3f(*up))
    cam.nearDistance.setValue(10.0)
    cam.farDistance.setValue(40000.0)
    if height is None:
        view.fitAll()
    else:
        cam.height.setValue(height)
    return view


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    import FreeCADGui as Gui
    out = []
    doc = build(save=False, show_robot=True, step=False)
    Gui.getDocument(DOC_NAME).ActiveView  # make sure a view exists
    fl = doc.addObject("Part::Feature", "render_floor")
    fl.Shape = G.box_span((-1700.0, 1700.0), (-1600.0, 1600.0), (-40.0, 0.0))
    fl.ViewObject.ShapeColor = (0.55, 0.42, 0.30)
    rows = doc.addObject("Part::Feature", "render_crop_rows")
    rows.Shape = Part.makeCompound([Part.makeCylinder(25.0, 120.0, V(s * P.worker_x + dx, y, 0.0))
                                    for s in (-1, 1) for dx in (-150.0, 150.0) for y in range(-1500, 1600, 120)])
    rows.ViewObject.ShapeColor = (0.25, 0.60, 0.20)
    ws = []
    for s in (-1, 1):
        w = doc.addObject("Part::Feature", "render_worker_%s" % ("L" if s < 0 else "R"))
        w.Shape = G.worker(s)
        w.ViewObject.ShapeColor = COLOR["worker"]
        ws.append(w)
    doc.getObject("wdb_canopy").ViewObject.Transparency = 55
    out.append(save_view("1_iso_with_workers.png", (-1.0, -1.1, -0.6), target=(0, 0, 700), height=3400))
    out.append(save_view("2_side_with_workers.png", (1.0, 0.0, 0.0), target=(0, 0, 750), height=2600))
    out.append(save_view("3_front_with_workers.png", (0.0, -1.0, 0.0), target=(0, 0, 750), height=2900))
    for w in ws:
        w.ViewObject.Visibility = False
    doc.getObject("wdb_canopy").ViewObject.Visibility = False
    out.append(save_view("4_boards_controls.png", (-0.8, -1.0, -0.9), target=(700, 400, 600), height=1500))
    for o in objects_of(doc, "wdb_Boards"):
        o.ViewObject.Visibility = False
    out.append(save_view("5_frame_stands.png", (-0.7, -1.0, -0.8), target=(0, 0, 600), height=2900))
    App.closeDocument(doc.Name)
    build()
    return out
