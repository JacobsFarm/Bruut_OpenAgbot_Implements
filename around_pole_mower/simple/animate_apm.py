"""Animation: the Bruut OpenAgbot mows the strip under an electric fence with the around-pole mower. The robot
drives forward (+y) at 0.5 m/s along a fence with wooden posts; at each post the guard ring touches the post, the
arm swings back and in, the head slides around the post and the spring swings it back out behind it.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, mower from
build_apm, ground, fence (posts, insulators, 3 wires) and the grass (apm_grass, tufts as cones).
Per frame: robot (position, wheel rotation), swing angle and rotor (apm_kin.simulate), spring, grass; the forces
and the power come from apm_kin and apm_calc, so the animation and the report give the same numbers.

Use in FreeCAD:
    import animate_apm
    animate_apm.build()                              # build the document
    animate_apm.play()                               # live, animate_apm.stop()
    animate_apm.summary()                            # key figures of the run
    animate_apm.render_all(r"C:\\temp\\apm_frames")
    import make_gif_apm; make_gif_apm.main(r"C:\\temp\\apm_frames", r"previews\\animation_around_posts.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import apm_params as P
import apm_kin as K
import apm_calc as C
import apm_grass as GR
import apm_parts as G
import build_apm

DOC_NAME = "APM_on_robot_animation"

# ---------------------------------------------------------------------
# Drive plan
# ---------------------------------------------------------------------
FPS = 10
SPEED = P.drive_speed                   # m/s
POSTS = (1000.0, 3000.0)                # world y of the posts (real spacing 4 .. 8 m; 2 m to keep the GIF short)
Y_START = 0.0                           # robot origin
Y_END = 4700.0
SPIN_DEG = 33.0                         # rotor turn per frame in the pictures (the real 3667 rpm would alias)
COLOR = {"ground": (0.42, 0.46, 0.30), "grass": (0.30, 0.62, 0.20), "grass_cut": (0.62, 0.72, 0.35)}

_timer = None
_play = {}


def share(grass, y_max):
    st = grass.stats(y_max=y_max)
    return st["share"] if st["total"] else None


def prepare(fps=FPS):
    """Drive plan, arm motion (apm_kin) and grass. Returns the frames (dicts)."""
    run = K.simulate(posts=POSTS, y_start=Y_START, y_end=Y_END, v=SPEED, out_dt=1.0 / fps / 5.0)
    grass = GR.Grass(posts=POSTS)
    pw = C.power(SPEED)
    frames = []
    batch = []
    f_max = 0.0
    for k, s in enumerate(run):
        batch.append(s["head"])
        f_max = max(f_max, s["F"])                  # peak of the post force since the last frame
        if k % 5 != 4:
            continue
        grass.cut_by(batch)
        batch = []
        frames.append({"t": s["t"], "y": s["y"], "psi": s["psi"], "F": f_max, "M_spring": s["M_spring"],
                       "contact": s["contact"], "spin_robot": (s["y"] - Y_START) / (P.robot_tire_d / 2.0),
                       "cut": grass.state(), "share": share(grass, s["head"][1] - P.string_r[1]), "P_el": pw["el_W"],
                       "rpm": C.head()["rpm"], "v": SPEED * 1000.0})
        f_max = 0.0
    return frames, grass


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build():
    if build_apm.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_apm.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Around-pole fence mower on robot - animation"
    doc.Comment = "Generated by animate_apm.py. Robot from agbot design, mower from build_apm."
    robot = build_apm.build_robot(doc)
    build_apm.build_into(doc, robot)
    g = doc.addObject("Part::Feature", "anim_ground")
    g.Shape = Part.makeBox(9000.0, 14000.0, 40.0, V(-4000.0, -5000.0, -40.0))
    g.ViewObject.ShapeColor = COLOR["ground"]
    for i, yp in enumerate(POSTS):
        o = doc.addObject("Part::Feature", "anim_post_%d" % i)
        o.Shape = G.fence_post(yp)
        o.ViewObject.ShapeColor = build_apm.COLOR["post"]
        ins = doc.addObject("Part::Feature", "anim_insulators_%d" % i)
        ins.Shape = Part.makeCompound(G.insulators(yp))
        ins.ViewObject.ShapeColor = build_apm.COLOR["insulator"]
    w = doc.addObject("Part::Feature", "anim_wires")
    w.Shape = Part.makeCompound(G.wires(-5000.0, 9000.0))
    w.ViewObject.ShapeColor = build_apm.COLOR["wire"]
    for name, col in (("anim_grass", "grass"), ("anim_grass_cut", "grass_cut")):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[col]
    for o in doc.Objects:
        if o.Name.startswith("anim_"):
            o.ViewObject.DisplayMode = "Shaded"                 # no black edges on grass, posts and wires
    doc.recompute()
    return doc


_TUFTS = {}


def tuft_shapes(grass):
    """Cones per tuft, long and cut (cached)."""
    key = id(grass)
    if key not in _TUFTS:
        _TUFTS.clear()
        longs, cuts = [], []
        for x, y, h, hc, _ in grass.tufts:
            longs.append(Part.makeCone(11.0, 1.5, h, V(x, y, 0), V(0, 0, 1)))
            cuts.append(Part.makeCone(11.0, 6.0, hc, V(x, y, 0), V(0, 0, 1)))
        _TUFTS[key] = (longs, cuts)
    return _TUFTS[key]


def apply_frame(doc, f, grass, index):
    doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin_robot"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    build_apm.set_swing(doc, f["psi"], 0.0, -SPIN_DEG * index)
    longs, cuts = tuft_shapes(grass)
    doc.getObject("anim_grass").Shape = Part.makeCompound([s for s, c in zip(longs, f["cut"]) if not c] or
                                                          [Part.Vertex(0, 0, 0)])
    doc.getObject("anim_grass_cut").Shape = Part.makeCompound([s for s, c in zip(cuts, f["cut"]) if c] or
                                                              [Part.Vertex(0, 0, 0)])


# ---------------------------------------------------------------------
# Camera and rendering
# ---------------------------------------------------------------------
CAM_A = ((1400.0, -1700.0, 3000.0), (650.0, -1150.0, 0.0))     # from behind, above the fence: head and post
CAM_B = ((1100.0, -1500.0, 3900.0), (650.0, -1900.0, 0.0))     # steeper at the end: the strip behind the robot


def smooth(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3.0 - 2.0 * t)


def track_camera(f, frames, fov=40.0):
    import FreeCADGui as Gui
    from pivy import coin
    t_end = frames[-1]["t"]
    s = smooth((f["t"] - (t_end - 3.0)) / 2.5)
    eye = [CAM_A[0][i] + (CAM_B[0][i] - CAM_A[0][i]) * s for i in range(3)]
    tgt = [CAM_A[1][i] + (CAM_B[1][i] - CAM_A[1][i]) * s for i in range(3)]
    target = (tgt[0], f["y"] + tgt[1], tgt[2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(target[0] + eye[0], target[1] + eye[1], target[2] + eye[2]))
    cam.pointAt(coin.SbVec3f(*target), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


def meta(f):
    return {"t": round(f["t"], 3), "v": round(f["v"], 1), "dist": round(f["y"] - Y_START, 1),
            "psi": round(f["psi"], 2), "swing": round(f["psi"] - P.psi_rest, 2), "F": round(f["F"], 1),
            "M_spring": round(f["M_spring"], 2), "contact": f["contact"], "share": None if f["share"] is None else round(f["share"], 4),
            "P_el": round(f["P_el"]), "rpm": round(f["rpm"]), "psi_rest": P.psi_rest}


def summary(frames=None):
    frames = frames or prepare()[0]
    last = frames[-1]
    return {"frames": len(frames), "duration_s": round(last["t"], 2),
            "swing_max_deg": round(max(f["psi"] for f in frames) - P.psi_rest, 1),
            "F_post_max_N": round(max(f["F"] for f in frames)), "cut_share_end": round(last["share"] or 0.0, 3),
            "M_spring_Nm": (round(min(f["M_spring"] for f in frames), 1), round(max(f["M_spring"] for f in frames), 1))}


def render_frames(folder, first=0, count=None, fps=FPS, size=(720, 480), frames=None, grass=None):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    if frames is None:
        frames, grass = prepare(fps)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i], grass, i)
        track_camera(frames[i], frames)
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(720, 480)):
    build()
    frames, grass = prepare(fps)
    first, total = 0, len(frames)
    while first < total:
        first, total = render_frames(folder, first, 25, fps, size, frames, grass)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames, grass = prepare(fps)
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            i = _play["index"]
            _play["index"] += 1
            apply_frame(doc, frames[i], grass, i)
            if follow:
                track_camera(frames[i], frames)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / fps))


def check_fit(doc=None, psis=(None, 45.0, P.psi_max)):
    """Overlap between the real robot model and the mower in the animation document, over the swing range, and the
    smallest gap between the post and the arm (apart from the guard) during the run."""
    doc = doc or App.getDocument(DOC_NAME)
    doc.getObject("Robot").Placement = App.Placement()
    out = {}
    for psi in psis:
        psi = P.psi_rest if psi is None else psi
        build_apm.set_swing(doc, psi)
        doc.recompute()
        out["psi_%g" % psi] = build_apm.check_interference(doc)
    build_apm.set_swing(doc, P.psi_rest)
    return out


def post_gap(frames=None, names=("ribs", "cover", "skid", "skid_leg", "motor", "clevis", "base_plate")):
    """Smallest distance (mm) between the posts and the arm parts other than the guard ring and the strings, over the
    frames of the run (the guard ring is meant to touch the post)."""
    doc = App.getDocument(DOC_NAME)
    frames = frames or prepare()[0]
    posts = [G.fence_post(yp) for yp in POSTS]
    best = (1e9, None, None)
    for i, f in enumerate(frames):
        if f["psi"] <= P.psi_rest + 0.01 and f["contact"] is None:
            continue
        doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
        build_apm.set_swing(doc, f["psi"])
        doc.recompute()
        for n in names:
            s = build_apm.global_shape(doc.getObject(n))
            for p in posts:
                if abs(p.BoundBox.Center.y - s.BoundBox.Center.y) > 1500:
                    continue
                d = s.distToShape(p)[0]
                if d < best[0]:
                    best = (d, n, i)
    doc.getObject("Robot").Placement = App.Placement()
    build_apm.set_swing(doc, P.psi_rest)
    return {"gap_mm": round(best[0], 1), "part": best[1], "frame": best[2]}
