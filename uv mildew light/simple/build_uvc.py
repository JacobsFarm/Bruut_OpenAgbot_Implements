def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj







def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "uv_mildew_light_simple")
    mount = new_part(doc, root, "Mount", "mount_bearers_hangers")
    add_shape(doc, mount, "bearers", "bearers_40x40x3_2x", G.bearers(), "frame")
    add_shape(doc, mount, "bearer_bolts", "bearer_bolts_M10_8x", G.bearer_bolts(), "zinc")
    add_shape(doc, mount, "hangers", "hangers_40x6_slotted_4x", G.hangers(), "frame")
    add_shape(doc, mount, "driver_box", "driver_box_6_ballasts_interlock", G.driver_box(), "box")
    hood = new_part(doc, root, "Hood", "uv_hood")
    add_shape(doc, hood, "hood", "hood_alu_2mm", G.hood(), "alu")
    add_shape(doc, hood, "skirts", "side_skirts_rubber_6mm", G.skirts(), "rubber")
    add_shape(doc, hood, "brushes", "brush_curtains_front_rear", G.brushes(), "brush")
    add_shape(doc, hood, "lamps", "uvc_lamps_PL_L_55W_%dx" % P.n_lamps, G.lamps(), "lamp")
    add_shape(doc, hood, "sockets", "lamp_sockets", G.sockets(), "plastic")
    add_shape(doc, hood, "lamp_clips", "lamp_clips", G.lamp_clips(), "zinc")
    add_shape(doc, hood, "guards", "lamp_guard_wires_D3", G.guards(), "zinc")
    return root


def build_robot(doc, steer=0.0):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, steer if tag in ("FL", "FR") else 0.0)
    return robot


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "UV-C mildew light simple"
    doc.Comment = ("Generated by build_uvc.py from uvc_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


