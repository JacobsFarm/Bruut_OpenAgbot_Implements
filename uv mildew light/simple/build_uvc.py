"""Model of the UV-C mildew light on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_uvc
    build_uvc.build()                      # saves FCStd and STEP
    build_uvc.check_interference()         # overlap (must be empty)
    build_uvc.check_poses()                # front wheels steered +-30 (must be empty)
    build_uvc.clearance()                  # hood to the four tyres
    build_uvc.mass_properties()
    build_uvc.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import uvc_params as P
import uvc_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "UV_Mildew_Light"
SAVE_BASE = os.path.join(FOLDER, "UV_Mildew_Light")
ROOT = "UV_mildew_light"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "alu": (0.78, 0.80, 0.83),
    "rubber": (0.10, 0.10, 0.10),
    "brush": (0.18, 0.18, 0.20),
    "lamp": (0.55, 0.40, 0.95),
    "plastic": (0.95, 0.95, 0.92),
    "box": (0.20, 0.45, 0.25),
}


