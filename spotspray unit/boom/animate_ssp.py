"""Animation: the Bruut OpenAgbot spot-sprays dock in grassland and folds the right wing for a fence post.

The robot drives straight at 1 m/s. The camera on the mast sees the strip ahead (yellow: the image on the ground);
every plant it detects gets an orange ring. When the nozzle line reaches a plant, only the nozzles above it open
(fan from the tip, blue spot on the ground). Before the post the right wing folds up (the actuator pulls it in 3.2 s),
its nozzles are off; after the post it folds down again. A plant in that strip is missed and logged (red ring).
Timing, rates and the fold come from ssp_field / ssp_calc, the same figures as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, sprayer from
build_ssp, grass floor, the docks, the post, the camera footprint, the sprayed spots.

Use in FreeCAD:
    import animate_ssp
    animate_ssp.build()                              # build the document
    animate_ssp.play()                               # play live, animate_ssp.stop()
    animate_ssp.summary()                            # key figures of the run
    animate_ssp.render_all(r"C:\\temp\\ssp_frames")
    import make_gif_ssp; make_gif_ssp.main(r"C:\\temp\\ssp_frames", r"previews\\animation_spot_spraying.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import ssp_params as P
import ssp_calc as C
import ssp_parts as G
import ssp_field as F
import build_ssp

DOC_NAME = "Spot_sprayer_on_robot_animation"
FPS = 6                         # frames per second of real time; the GIF plays at 12 fps = 2 x speed
COLOR = {"grass": (0.47, 0.62, 0.30), "dock": (0.16, 0.38, 0.12), "post": (0.45, 0.32, 0.20),
         "footprint": (0.98, 0.82, 0.20), "spot": (0.15, 0.40, 0.90), "fan": (0.55, 0.75, 1.00),
         "detected": (0.98, 0.55, 0.10), "missed": (0.90, 0.10, 0.10)}

_timer = None
_play = {}


# ---------------------------------------------------------------------
# Frames
# ---------------------------------------------------------------------
def prepare(fps=FPS):
    pl = F.plan()
    sched = F.fold_schedule()
    t_end = F.drive_time() + F.HOLD_END
    n = int(math.ceil(t_end * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        f = F.frame_state(t, pl, sched)
        f["spin"] = (f["y"] - F.Y_START) / (P.robot_tire_d / 2.0)
        f["phase"] = phase(t, sched)
        frames.append(f)
    return frames


def phase(t, s):
    if t >= F.drive_time():
        return "done"
    if s["up_start"] <= t < s["up_end"]:
        return "fold_up"
    if s["up_end"] <= t < s["down_start"]:
        return "past_post"
    if s["down_start"] <= t < s["down_end"]:
        return "fold_down"
    return "spray"


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build():
    if build_ssp.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_ssp.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Spot sprayer on robot - animation"
    doc.Comment = "Generated by animate_ssp.py. Robot from agbot design, sprayer from build_ssp."
    robot = build_ssp.build_robot(doc)
    build_ssp.build_into(doc, robot)
    build_ssp.set_robot_visible(True, doc)
    floor = doc.addObject("Part::Feature", "anim_floor")
    floor.Shape = Part.makeBox(9000.0, 26000.0, 40.0, V(-4500.0, -6000.0, -40.0))
    floor.ViewObject.ShapeColor = COLOR["grass"]
    docks = doc.addObject("Part::Feature", "anim_docks")
    docks.Shape = Part.makeCompound([G.dock(x, y, d, h, s) for (x, y, d, h, s) in F.weeds()])
    docks.ViewObject.ShapeColor = COLOR["dock"]
    px, py, pd, ph = F.POST
    post = doc.addObject("Part::Feature", "anim_post")
    post.Shape = G.post(px, py, pd, ph)
    post.ViewObject.ShapeColor = COLOR["post"]
    fp = doc.addObject("Part::Feature", "anim_footprint")
    fp.Shape = G.ground_polygon(C.footprint(), z=2.0, t=0.5)
    fp.ViewObject.ShapeColor = COLOR["footprint"]
    fp.ViewObject.Transparency = 55
    for name, color, transp in (("anim_spots", "spot", 25), ("anim_fans", "fan", 45), ("anim_detected", "detected", 0),
                                ("anim_missed", "missed", 0)):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
        o.ViewObject.Transparency = transp
    doc.recompute()
    return doc


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def apply_frame(doc, f, weeds=None):
    weeds = weeds or F.weeds()
    doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    for name, pl in build_ssp.pose_placements(0.0, f["phi_r"]).items():
        doc.getObject(name).Placement = pl
    doc.getObject("anim_footprint").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    doc.getObject("anim_spots").Shape = _compound([G.patch(x0, x1, y0, y1) for (x0, x1, y0, y1) in f["patches"]
                                                   if y1 - y0 > 1.0])
    y_n = f["y"] + P.boom_y
    doc.getObject("anim_fans").Shape = _compound([G.spray_fan(P.nozzle_x[i], y_n) for i, o in enumerate(f["open"]) if o])
    det = [G.ring(w[0], w[1], w[2] + 80.0, w=35.0) for w, s in zip(weeds, f["weeds"]) if s["detected"] and not s["missed"]]
    mis = [G.ring(w[0], w[1], w[2] + 80.0, w=45.0) for w, s in zip(weeds, f["weeds"]) if s["missed"]]
    doc.getObject("anim_detected").Shape = _compound(det)
    doc.getObject("anim_missed").Shape = _compound(mis)


# ---------------------------------------------------------------------
# Camera and rendering
# ---------------------------------------------------------------------
CAM_A = ((-3000.0, -4000.0, 2800.0), (300.0, 800.0, 150.0))     # eye and target relative to the robot centre


def track_camera(f, fov=42.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


STATE = {"spray": "spot spraying", "fold_up": "post ahead: right wing folds up, its nozzles off",
         "past_post": "passing the post, right wing up", "fold_down": "post passed: right wing folds down",
         "done": "done"}


def meta(f):
    w = f["weeds"]
    return {"t": round(f["t"], 2), "phase": f["phase"], "state": STATE[f["phase"]], "v": round(f["v"], 0),
            "phi_r": round(f["phi_r"], 1), "open": [1 if o else 0 for o in f["open"]],
            "folded": [1 if (F.wing_of(i) == "right" and f["phi_r"] > 2.0) else 0 for i in range(P.n_nozzles)],
            "n": len(w), "detected": sum(1 for s in w if s["detected"]), "sprayed": sum(1 for s in w if s["sprayed"]),
            "missed": sum(1 for s in w if s["missed"]), "litres": round(f["litres"], 4),
            "blanket_l": round(f["blanket_l"], 3), "driven_m": round((f["y"] - F.Y_START) / 1000.0, 2),
            "nozzle_x": list(P.nozzle_x)}


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    s["max_open"] = max(sum(f["open"]) for f in frames)
    s["max_phi"] = round(max(f["phi_r"] for f in frames), 1)
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    weeds = F.weeds()
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i], weeds)
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=1.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    weeds = F.weeds()
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f, weeds)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))


def check_fit(doc=None, tol=1.0):
    """Overlap between the robot model and the sprayer in the animation document, over the fold of the right wing."""
    doc = doc or App.getDocument(DOC_NAME)
    phis = sorted({round(f["phi_r"], 0) for f in prepare()[::3]})
    return build_ssp.check_fit(doc, poses=[(0.0, p) for p in phis], tol=tol)
