"""Model of the swarm kit on the Bruut OpenAgbot (standard robot); render_all() also shows 3 units in one field.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_swm
    build_swm.build()                 # saves FCStd and STEP
    build_swm.check_interference()    # overlap (must be empty)
    build_swm.check_holes()           # bolts in their holes (must be empty)
    build_swm.check_steering()        # bridge against the steered front wheels (must be empty)
    build_swm.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import swm_params as P
import swm_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Swarm_Operation"
SAVE_BASE = os.path.join(FOLDER, "Swarm_Operation")
ROOT = "Swarm_operation"

COLOR = dict(BP.COLOR)
COLOR.update({"green": (0.10, 0.75, 0.25), "yellow": (0.95, 0.80, 0.10), "red": (0.85, 0.15, 0.10),
              "blue": (0.15, 0.35, 0.85), "box": (0.20, 0.22, 0.25)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


LIGHT_COLORS = ("green", "yellow", "red", "blue")


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "swarm_kit_simple")
    grp = new_part(doc, root, "SwarmKit", "post_radio_status_lights")
    add_shape(doc, grp, "swm_bar", "bar_8mm_across_inner_upper_beams", G.bar(), "frame")
    add_shape(doc, grp, "swm_bolts", "bar_bolts_M10_2x", G.bar_bolts(), "zinc")
    add_shape(doc, grp, "swm_post", "post_40x40x3_1500", G.post(), "frame")
    for c, seg in zip(LIGHT_COLORS, G.light_segments()):
        add_shape(doc, grp, "swm_light_" + c, "status_light_" + c, seg, c)
    add_shape(doc, grp, "swm_whip", "mesh_radio_868MHz_whip", G.whip(), "box")
    add_shape(doc, grp, "swm_box", "swarm_computer_and_radio_box", G.box(), "box")
    return root


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Swarm operation simple"
    doc.Comment = ("Generated by build_swm.py from swm_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("swm_bolts", "swm_bar"), ("swm_post", "swm_bar")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "swm_bolts" in (a, b) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    a, b = doc.getObject("swm_bolts"), doc.getObject("swm_bar")
    v = global_shape(a).common(global_shape(b)).Volume
    return {} if v <= tol else {"bolts_in_brackets": round(v, 1)}


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in mine for b in rob], tol)
        if hits:
            out[str(st)] = hits
    set_steering(0.0, doc)
    return out


DENSITY = {}
MASS_FIXED = {"swm_box": 0.9, "swm_whip": 0.2}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, 7.85e-6))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = "render_field"
OTHERS = ("render_unit_2", "render_unit_3")


def add_field(doc):
    f = doc.addObject("Part::Feature", SCENE)
    f.Shape = G.box_span((-1800.0, 6200.0), (-2500.0, 4500.0), (-40.0, 0.0))
    f.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    f.ViewObject.Transparency = 30


def add_units(doc):
    """Two more units as single shapes (robot + kit), 1.8 m (one pass) and 3.6 m to the right, staggered in y."""
    import Part
    objs = [o for o in robot_objects(doc) + objects_of(doc, ROOT)]
    shapes = [global_shape(o) for o in objs]
    for k, (dx, dy) in enumerate(((P.pass_w * 1000.0 * 1.5, -1500.0), (P.pass_w * 1000.0 * 3.0, 1200.0))):
        c = Part.makeCompound([s.copy() for s in shapes])
        c.translate(V(dx, dy, 0))
        u = doc.addObject("Part::Feature", OTHERS[k])
        u.Shape = c
        u.ViewObject.ShapeColor = (0.30, 0.30, 0.32)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    out.append(save_view("1_iso_swarm_kit_on_robot.png", (-1.0, -1.2, -0.7), target=(0, 0, 800)))
    add_field(doc)
    add_units(doc)
    out.append(save_view("2_three_units_in_field.png", (-1.0, -1.4, -0.9), target=(2700, 0, 500)))
    out.append(save_view("3_top_three_passes.png", (0.0, 0.0, -1.0), target=(2700, 0, 0), up=(0.0, 1.0, 0.0),
                         height=7500))
    for n in OTHERS + (SCENE,):
        doc.removeObject(n)
    set_robot_visible(False, doc)
    out.append(save_view("4_kit_detail.png", (-1.0, -0.8, -0.4), target=(-100, -325, 1200), height=1300))
    App.closeDocument(doc.Name)
    build()
    return out
