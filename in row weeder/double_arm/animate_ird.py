# Camera and rendering
# ---------------------------------------------------------------------
CAM_A = ((1750.0, -1500.0, 1050.0), (120.0, -120.0, 150.0))     # eye and target relative to the robot centre


def track_camera(f, fov=44.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


def meta(f):
    """Per frame: the arm angles, the knife offsets and the plants near each knife (for the panel)."""
    fld = F.field()
    sim = F.simulate()
    out = {"t": round(f["t"], 2), "v": round(f["v"], 0), "driven_m": round((f["y"] - F.Y_START) / 1000.0, 2),
           "theta": {k: round(v, 1) for k, v in f["theta"].items()}, "rows": {}}
    for r in F.ROWS:
        kns = [F.knife(r, s, f["t"]) for s in P.SIDES]
        cy = sum(p[1] for kn in kns for p in kn) / 8.0           # between the two knives of the row
        x0 = F.row_x(r)
        sgn = 1.0 if r == "right" else -1.0
        plants = [[round(sgn * (p["x"] - x0), 1), round(p["y"] - cy, 1)] for p in fld["plants"]
                  if p["row"] == r and -500.0 < p["y"] - cy < 700.0]
        knives = [[[round(sgn * (x - x0), 1), round(y - cy, 1)] for (x, y) in kn] for kn in kns]
        out["rows"][r] = {"knives": knives, "plants": plants}
    killed = [i for i, k in sim["killed"].items() if k <= f["t"]]
    out["killed"] = len(killed)
    out["plants_passed"] = sum(1 for i, p in enumerate(fld["plants"])
                               if p["y"] < f["y"] + C.finger_uv(P.theta_in, -1)[1] - 100.0 and p["y"] > F.Y_START)
    return out


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    s["theta_range"] = (round(min(min(f["theta"].values()) for f in frames), 1),
                        round(max(max(f["theta"].values()) for f in frames), 1))
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i])
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=1.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))


def check_fit(doc=None, tol=1.0):
    """Overlap between the robot and the weeder in the animation document over the arm angles that occur."""
    doc = doc or App.getDocument(DOC_NAME)
    poses = sorted({(round(f["theta"]["right_outer"], 0), round(f["theta"]["right_inner"], 0)) for f in prepare()[::2]})
    return build_ird.check_fit(doc, poses=[(0.0, p, p) for p in poses], tol=tol)
