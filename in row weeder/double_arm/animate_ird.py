"""Animation: the Bruut OpenAgbot weeds two rows of broccoli with double arms: two knives per row, four steppers.

The robot drives straight at 0.5 m/s. The camera under the front beams sees the plants (yellow: its image on the
ground; a plant gets an orange ring once it is detected). Between the plants both knives of a row are in, each in its
half of the row band; at a plant they swing out to both sides and back in behind it, each as late / early as its
distance to the stem allows. The soil that a knife passed turns dark, the seedlings it passed lie flat (killed).
Timing and swings come from ird_field / ird_calc, the same figures as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, weeder from
build_ird, soil, the broccoli, the weeds, the camera footprint, the hoed strips.

Use in FreeCAD:
    import animate_ird
    animate_ird.build()                              # build the document
    animate_ird.play()                               # play live, animate_ird.stop()
    animate_ird.summary()                            # key figures of the run
    animate_ird.render_all(r"C:\\temp\\ird_frames")
    import make_gif_ird; make_gif_ird.main(r"C:\\temp\\ird_frames", r"previews\\animation_double_arm_weeding.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import ird_params as P
import ird_calc as C
import ird_parts as G
import ird_field as F
import build_ird

DOC_NAME = "In_row_double_arm_on_robot_animation"
SIDE_TAG = {1: "outer", -1: "inner"}


def key(r, s):
    return "%s_%s" % (r, SIDE_TAG[s])
FPS = 10                        # frames per second of real time; the GIF plays at 10 fps = real speed
COLOR = {"soil": (0.50, 0.37, 0.25), "hoed": (0.33, 0.23, 0.15), "crop": (0.25, 0.50, 0.30),
         "weed": (0.45, 0.78, 0.25), "dead": (0.62, 0.55, 0.30), "footprint": (0.98, 0.82, 0.20),
         "detected": (0.98, 0.55, 0.10)}
VIEW_TRANSPARENT = ("RR_", "FR_")       # right wheel units see-through, so the right unit is visible

_timer = None
_play = {}


# ---------------------------------------------------------------------
# Frames
# ---------------------------------------------------------------------
def prepare(fps=FPS):
    t_end = F.drive_time() + F.HOLD_END
    n = int(math.ceil(t_end * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        y = F.robot_y(t)
        f = {"t": t, "y": y, "v": P.speed * 1000.0 if t < F.drive_time() else 0.0,
             "theta": {key(r, s): F.theta(r, s, t) for (r, s) in F.KNIVES}}
        f["spin"] = (y - F.Y_START) / (P.robot_tire_d / 2.0)
        frames.append(f)
    return frames


def _seen(p, y_robot):
    c = C.camera()
    return p["y"] - y_robot <= c["far"]


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build():
    if build_ird.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_ird.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    _CACHE.clear()
    doc = App.newDocument(DOC_NAME)
    doc.Label = "In-row weeder on robot - animation"
    doc.Comment = "Generated by animate_ird.py. Robot from agbot design, weeder from build_ird."
    robot = build_ird.build_robot(doc)
    build_ird.build_into(doc, robot)
    build_ird.set_robot_visible(True, doc)
    for o in build_ird.robot_objects(doc):
        if o.Name.startswith(VIEW_TRANSPARENT):
            o.ViewObject.Transparency = 75
    fld = F.field()
    floor = doc.addObject("Part::Feature", "anim_soil")
    floor.Shape = Part.makeBox(3000.0, 9000.0, 40.0, V(-1500.0, -2500.0, -40.0))
    floor.ViewObject.ShapeColor = COLOR["soil"]
    crop = doc.addObject("Part::Feature", "anim_crop")
    crop.Shape = Part.makeCompound([G.broccoli(p["x"], p["y"], p["d"], p["h"], p["seed"]) for p in fld["plants"]])
    crop.ViewObject.ShapeColor = COLOR["crop"]
    for name, color, transp in (("anim_hoed", "hoed", 0), ("anim_weeds", "weed", 0), ("anim_dead", "dead", 0),
                                ("anim_detected", "detected", 0), ("anim_footprint", "footprint", 60)):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
        o.ViewObject.Transparency = transp
        if name in ("anim_hoed", "anim_footprint", "anim_detected", "anim_weeds", "anim_dead"):
            o.ViewObject.DisplayMode = "Shaded"
    doc.getObject("anim_footprint").Shape = G.ground_polygon(C.footprint(), z=1.2, t=0.4)
    doc.recompute()
    return doc


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def _face(pts, z=0.8):
    pts = list(pts) + [pts[0]]
    return Part.Face(Part.makePolygon([V(x, y, z) for (x, y) in pts]))


_CACHE = {}


def _shapes():
    """Weed shapes (alive and hoed out) and the hoed soil faces, made once."""
    if not _CACHE:
        fld = F.field()
        sim = F.simulate()
        _CACHE["alive"] = [G.weed(w["x"], w["y"], w["s"]) for w in fld["weeds"]]
        _CACHE["dead"] = [G.weed_dead(w["x"], w["y"], w["s"]) for w in fld["weeds"]]
        _CACHE["hoed"] = [(ts, _face(h)) for kn in F.KNIVES for (ts, h) in sim["strips"][kn][::2]]
    return _CACHE


def apply_frame(doc, f):
    fld = F.field()
    sim = F.simulate()
    y = f["y"]
    doc.getObject("Robot").Placement = App.Placement(V(0.0, y, 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    th = f["theta"]
    for name, pl in build_ird.pose_placements(0.0, (th["right_outer"], th["right_inner"]),
                                              (th["left_outer"], th["left_inner"])).items():
        doc.getObject(name).Placement = pl
    doc.getObject("anim_footprint").Placement = App.Placement(V(0.0, y, 0.0), App.Rotation())
    t = f["t"]
    cache = _shapes()
    doc.getObject("anim_hoed").Shape = _compound([fc for (ts, fc) in cache["hoed"] if ts <= t])
    alive, dead = [], []
    for i, w in enumerate(fld["weeds"]):
        k = sim["killed"].get(i)
        if k is not None and k <= t:
            dead.append(cache["dead"][i])
        else:
            alive.append(cache["alive"][i])
    doc.getObject("anim_weeds").Shape = _compound(alive)
    doc.getObject("anim_dead").Shape = _compound(dead)
    rings = []
    for p in fld["plants"]:
        if _seen(p, y):
            ring = Part.makeCylinder(P.safe_r + 6.0, 1.0, V(p["x"], p["y"], 1.5)).cut(
                Part.makeCylinder(P.safe_r, 1.0, V(p["x"], p["y"], 1.5)))
            rings.append(ring)
    doc.getObject("anim_detected").Shape = _compound(rings)


