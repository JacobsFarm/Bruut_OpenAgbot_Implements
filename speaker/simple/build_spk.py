"""Model of the speech speaker on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_spk
    build_spk.build()                 # saves FCStd and STEP
    build_spk.check_interference()    # overlap (must be empty)
    build_spk.check_holes()           # bolts in their holes (must be empty)
    build_spk.check_steering()        # bridge against the steered front wheels (must be empty)
    build_spk.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import spk_params as P
import spk_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Speaker"
SAVE_BASE = os.path.join(FOLDER, "Speaker")
ROOT = "Speaker_unit"

COLOR = dict(BP.COLOR)
COLOR.update({"horn": (0.92, 0.92, 0.90), "box": (0.20, 0.22, 0.25)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "speaker_simple")
    grp = new_part(doc, root, "Speakers", "horns_brackets_amplifier")
    add_shape(doc, grp, "spk_brackets", "bars_8mm_with_upright_2x", G.brackets(), "frame")
    add_shape(doc, grp, "spk_bolts", "bar_bolts_M10_4x", G.bracket_bolts(), "zinc")
    add_shape(doc, grp, "horns", "horn_speakers_30W_front_rear", G.horns(), "horn")
    add_shape(doc, grp, "amp", "amplifier_2x30W_box_IP65", G.amp(), "box")
    add_shape(doc, grp, "mic", "microphone", G.mic(), "box")
    return root


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Speaker simple"
    doc.Comment = ("Generated by build_spk.py from spk_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("spk_bolts", "spk_brackets")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "spk_bolts" in (a, b) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    a, b = doc.getObject("spk_bolts"), doc.getObject("spk_brackets")
    v = global_shape(a).common(global_shape(b)).Volume
    return {} if v <= tol else {"bolts_in_brackets": round(v, 1)}


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in mine for b in rob], tol)
        if hits:
            out[str(st)] = hits
    set_steering(0.0, doc)
    return out


DENSITY = {}
MASS_FIXED = {"horns": 3.2, "amp": 0.8, "mic": 0.1}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, 7.85e-6))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    out.append(save_view("1_iso_front_on_robot.png", (-1.0, -1.2, -0.7), target=(0, 0, 600)))
    out.append(save_view("2_side.png", (1.0, 0.0, 0.0), target=(0, 0, 600), height=1900))
    set_robot_visible(False, doc)
    out.append(save_view("3_horns_and_amp.png", (-1.0, 0.6, -0.6), target=(0, 0, 800), height=1500))
    App.closeDocument(doc.Name)
    build()
    return out
