"""Animation: the Bruut OpenAgbot flames a freshly sown bed before the crop comes up.

The robot drives at 0.7 m/s with the hood behind it (drawn see-through so that the flames show; the seedlings are
drawn 1.6 x larger). The seedlings that the
hood passes collect heat: green = alive, dark = killed, yellow = passed but survived (the biggest, 4-leaf ones). At the
end of the bed the robot stops: the main valve closes at once (0.3 s), only the pilot flames stay on. Dose, gas use
and kills come from flw_field / flw_calc, the same figures as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot, flame weeder
from build_flw, the seedbed, the seedlings, the flames.

Use in FreeCAD:
    import animate_flw
    animate_flw.build()                              # build the document
    animate_flw.play()                               # play live, animate_flw.stop()
    animate_flw.summary()                            # key figures of the run
    animate_flw.render_all(r"C:\\temp\\flw_frames")
    import make_gif_flw; make_gif_flw.main(r"C:\\temp\\flw_frames", r"previews\\animation_flaming_bed.gif")
"""
import json
import math
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import flw_params as P
import flw_calc as C
import flw_parts as G
import flw_field as F
import build_flw

DOC_NAME = "Flame_weeder_on_robot_animation"
FPS = 10                        # frames per second of real time; the GIF plays at 10 fps = real speed
COLOR = {"soil": (0.40, 0.30, 0.20), "bed": (0.50, 0.37, 0.25), "rows": (0.62, 0.50, 0.36),
         "alive": (0.45, 0.78, 0.25), "heating": (0.80, 0.80, 0.20), "dead": (0.05, 0.04, 0.03),
         "survived": (0.85, 0.80, 0.30), "flame": (1.00, 0.55, 0.10)}
SEE_THROUGH = ("hood_skin", "blanket", "top_cover", "front_shield")
DRAW_SCALE = 1.6                # seedlings drawn 1.6 x larger, so they show at this distance

_timer = None
_play = {}


# ---------------------------------------------------------------------
# Frames
# ---------------------------------------------------------------------
def prepare(fps=FPS):
    n = int(math.ceil(F.t_end() * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        y = F.robot_y(t)
        frames.append({"t": t, "y": y, "flame": F.flame_scale(t), "v": F.v() if t < F.drive_time() else 0.0,
                       "spin": (y - F.Y_START) / (P.robot_tire_d / 2.0)})
    return frames


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
_CACHE = {}


def build():
    if build_flw.AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, build_flw.AGBOT_FOLDER)
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    _CACHE.clear()
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Flame weeder on robot - animation"
    doc.Comment = "Generated by animate_flw.py. Robot from agbot design, flame weeder from build_flw."
    robot = build_flw.build_robot(doc)
    build_flw.build_into(doc, robot)
    build_flw.set_robot_visible(True, doc)
    for n in SEE_THROUGH:
        doc.getObject(n).ViewObject.Transparency = 80
    for n in ("blanket", "top_cover"):                 # drawn see-through: only the skin and the shield
        doc.getObject(n).ViewObject.Visibility = False
    y0, y1 = F.Y_START + P.hood_y[0] - 600.0, F.Y_START + F.DRIVE + 2600.0
    soil = doc.addObject("Part::Feature", "anim_soil")
    soil.Shape = G.box_span((-2000.0, 2000.0), (y0, y1), (-60.0, -40.0))
    soil.ViewObject.ShapeColor = COLOR["soil"]
    bed = doc.addObject("Part::Feature", "anim_bed")
    bed.Shape = G.seedbed(y0, y1)
    bed.ViewObject.ShapeColor = COLOR["bed"]
    rows = doc.addObject("Part::Feature", "anim_rows")
    rows.Shape = G.seed_rows(y0, y1)
    rows.ViewObject.ShapeColor = COLOR["rows"]
    for name, color, tr in (("anim_alive", "alive", 0), ("anim_heating", "heating", 0), ("anim_dead", "dead", 0),
                            ("anim_survived", "survived", 0), ("anim_flames", "flame", 15)):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
        o.ViewObject.Transparency = tr
    for n in ("anim_rows", "anim_alive", "anim_heating", "anim_dead", "anim_survived", "anim_flames"):
        doc.getObject(n).ViewObject.DisplayMode = "Shaded"
    doc.recompute()
    return doc


def _shapes():
    if not _CACHE:
        ws = F.weeds()
        k = DRAW_SCALE
        _CACHE["alive"] = [G.weed(w["x"], w["y"], k * w["s"]) for w in ws]
        _CACHE["dead"] = [G.weed_scorched(w["x"], w["y"], k * w["s"]) for w in ws]
    return _CACHE


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def apply_frame(doc, f):
    y = f["y"]
    doc.getObject("Robot").Placement = App.Placement(V(0.0, y, 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    fl = doc.getObject("anim_flames")
    fl.Shape = G.flames(f["flame"])
    fl.Placement = App.Placement(V(0.0, y, 0.0), App.Rotation())
    cache = _shapes()
    groups = ([], [], [], [])
    for i, s in enumerate(F.state(f["t"])):
        groups[s].append(cache["dead"][i] if s == 2 else cache["alive"][i])
    for name, g in zip(("anim_alive", "anim_heating", "anim_dead", "anim_survived"), groups):
        doc.getObject(name).Shape = _compound(g)


# ---------------------------------------------------------------------
# Camera and rendering
# ---------------------------------------------------------------------
CAM_A = ((1900.0, -2900.0, 1150.0), (-50.0, -1150.0, 60.0))     # eye and target relative to the robot centre


def track_camera(f, fov=42.0):
    import FreeCADGui as Gui
    from pivy import coin
    y = f["y"]
    tgt = (CAM_A[1][0], y + CAM_A[1][1], CAM_A[1][2])
    eye = (CAM_A[0][0], y + CAM_A[0][1], CAM_A[0][2])
    cam = Gui.ActiveDocument.ActiveView.getCameraNode()
    cam.position.setValue(coin.SbVec3f(*eye))
    cam.pointAt(coin.SbVec3f(*tgt), coin.SbVec3f(0, 0, 1))
    cam.heightAngle.setValue(math.radians(fov))
    cam.nearDistance.setValue(20.0)
    cam.farDistance.setValue(60000.0)


def meta(f):
    st = F.state(f["t"])
    d = C.dose()
    on = f["flame"] > 0.99
    return {"t": round(f["t"], 2), "v": round(f["v"], 0), "flame": round(f["flame"], 2),
            "state": "flaming" if on else ("stopped: main valve closed, pilots on" if f["flame"] < 0.2 else
                                           "stopped: main valve closing"),
            "kW": round(C.flow()["kW"] * (1.0 if on else max(0.01, f["flame"] - 0.15)), 0),
            "dose": round(d["kg_ha"], 0), "soil_kJ": round(d["soil_kJ_m2"], 0),
            "gas_g": round(1000.0 * F.gas_used(f["t"]), 1), "killed": st.count(2), "survived": st.count(3),
            "driven_m": round((f["y"] - F.Y_START) / 1000.0, 2)}


def summary(frames=None):
    frames = frames or prepare()
    s = F.summary()
    s["frames"] = len(frames)
    return s


def render_frames(folder, first=0, count=None, fps=FPS, size=(800, 500)):
    import FreeCADGui as Gui
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "frames.json"), "w", encoding="utf-8") as handle:
        json.dump([meta(f) for f in frames], handle)
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Perspective")
    last = len(frames) if count is None else min(len(frames), first + count)
    for i in range(first, last):
        apply_frame(doc, frames[i])
        track_camera(frames[i])
        Gui.updateGui()
        view.saveImage(os.path.join(folder, "frame_%04d.png" % i), size[0], size[1], "White")
    return last, len(frames)


def render_all(folder, fps=FPS, size=(800, 500)):
    build()
    first, total = 0, 1
    while first < total:
        first, total = render_frames(folder, first, 30, fps, size)
    return total


def stop():
    global _timer
    if _timer is not None:
        _timer.stop()
        _timer = None


def play(fps=FPS, loop=False, follow=True, speed=1.0):
    import FreeCADGui as Gui
    from PySide import QtCore
    global _timer
    stop()
    doc = App.getDocument(DOC_NAME)
    frames = prepare(fps)
    Gui.ActiveDocument.ActiveView.setCameraType("Perspective")
    _play.update({"index": 0})

    def step():
        try:
            if _play["index"] >= len(frames):
                if loop:
                    _play["index"] = 0
                else:
                    stop()
                    return
            f = frames[_play["index"]]
            _play["index"] += 1
            apply_frame(doc, f)
            if follow:
                track_camera(f)
        except Exception:
            stop()
            raise

    _timer = QtCore.QTimer()
    _timer.timeout.connect(step)
    _timer.start(int(1000 / (fps * speed)))


def check_fit(doc=None, tol=1.0):
    """Overlap between the robot and the flame weeder in the animation document (float range of build_flw)."""
    doc = doc or App.getDocument(DOC_NAME)
    return build_flw.check_fit(doc, tol=tol)
