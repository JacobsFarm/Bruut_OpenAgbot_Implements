"""Animation: the Bruut OpenAgbot drives over a lettuce bed and the drop-on-demand boom puts single drops on the weeds.

The robot drives straight at 0.5 m/s over the bed. The hood is shown see-through. The camera in the hood sees the
ground in front of the injector rail (yellow: its image inside the hood); every weed it confirms gets an orange ring.
When the injector line is over a weed, only the injectors above it fire (a short blue jet), and the weed gets wet
dots. Drops that would land within the keep-out of a lettuce plant are not fired; a weed with only such drops is left
for the in-row weeder (red ring). Timing and drop figures come from ddb_field / ddb_calc, the same as the report.

Builds a separate document (the robot files in "agbot design" are not changed): robot from build_agbot (via build_ssp),
boom from build_ddb, the bed, the lettuce, the weeds, the camera footprint, the jets and the wet dots.

Use in FreeCAD:
    import animate_ddb
    animate_ddb.build()                              # build the document
    animate_ddb.play()                               # play live, animate_ddb.stop()
    animate_ddb.summary()                            # key figures of the run
    animate_ddb.render_all(r"C:\\temp\\ddb_frames")
    import make_gif_ddb; make_gif_ddb.main(r"C:\\temp\\ddb_frames", r"previews\\animation_drop_on_demand.gif")
"""
import json
import math
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import ddb_params as P
import ddb_calc as C
import ddb_parts as G
import ddb_field as F
import build_ddb

DOC_NAME = "Drop_on_demand_boom_on_robot_animation"
FPS = 6                         # frames per second of real time; the GIF plays at 12 fps = 2 x speed
COLOR = {"soil": (0.45, 0.33, 0.22), "lettuce": (0.40, 0.70, 0.22), "weed": (0.20, 0.42, 0.10),
         "footprint": (0.98, 0.82, 0.20), "jet": (0.15, 0.40, 0.95), "dot": (0.10, 0.30, 0.90),
         "detected": (0.98, 0.55, 0.10), "left": (0.90, 0.10, 0.10)}
SEE_THROUGH = ("hood_shell", "brush", "brush_holder")

_timer = None
_play = {}


def prepare(fps=FPS):
    pl = F.plan()
    t_end = F.drive_time() + F.HOLD_END
    n = int(math.ceil(t_end * fps)) + 1
    frames = []
    for k in range(n):
        t = k / float(fps)
        f = F.frame_state(t, pl, 1.0 / fps)
        f["spin"] = (f["y"] - F.Y_START) / (P.robot_tire_d / 2.0)
        frames.append(f)
    return frames


# ---------------------------------------------------------------------
# Document
# ---------------------------------------------------------------------
def build():
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Drop on demand boom on robot - animation"
    doc.Comment = "Generated by animate_ddb.py. Robot from agbot design, boom from build_ddb."
    robot = build_ddb.build_robot(doc)
    build_ddb.build_into(doc, robot)
    build_ddb.set_robot_visible(True, doc)
    for n in SEE_THROUGH:
        doc.getObject(n).ViewObject.Transparency = 80
    soil = doc.addObject("Part::Feature", "anim_soil")
    soil.Shape = Part.makeCompound([G.bed(*F.BED_Y), G.box_span((-1500.0, 1500.0), F.BED_Y, (-100.0, -60.0))])
    soil.ViewObject.ShapeColor = COLOR["soil"]
    lettuce = doc.addObject("Part::Feature", "anim_lettuce")
    lettuce.Shape = Part.makeCompound([G.lettuce(x, y, d, s) for (x, y, d, s) in F.crops()])
    lettuce.ViewObject.ShapeColor = COLOR["lettuce"]
    weeds = doc.addObject("Part::Feature", "anim_weeds")
    weeds.Shape = Part.makeCompound([G.weed(x, y, d, s) for (x, y, d, s) in F.weeds()])
    weeds.ViewObject.ShapeColor = COLOR["weed"]
    c = C.camera()
    fp = doc.addObject("Part::Feature", "anim_footprint")
    fp.Shape = G.box_span((-P.work_width / 2.0, P.work_width / 2.0), c["view_in_hood_y"], (1.0, 1.5))
    fp.ViewObject.ShapeColor = COLOR["footprint"]
    fp.ViewObject.Transparency = 60
    for name, color in (("anim_jets", "jet"), ("anim_dots", "dot"), ("anim_detected", "detected"),
                        ("anim_left", "left")):
        o = doc.addObject("Part::Feature", name)
        o.ViewObject.ShapeColor = COLOR[color]
    doc.recompute()
    return doc


def _compound(shapes):
    return Part.makeCompound(shapes) if shapes else Part.Shape()


def ring(x, y, d, w=6.0, z=2.0):
    return G.cyl_z(d + w, z, z + 1.0, x, y).cut(G.cyl_z(d - w, z - 1, z + 2.0, x, y))


def apply_frame(doc, f, weeds=None, plan_=None):
    weeds = weeds or F.weeds()
    doc.getObject("Robot").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    rot = App.Rotation(V(1, 0, 0), -math.degrees(f["spin"]))
    for tag in ("RL", "RR", "FL", "FR"):
        for part in ("tire", "rim", "hub"):
            doc.getObject("%s_%s" % (tag, part)).Placement = App.Placement(V(0, 0, 0), rot)
    doc.getObject("anim_footprint").Placement = App.Placement(V(0.0, f["y"], 0.0), App.Rotation())
    doc.getObject("anim_jets").Shape = _compound([G.cyl_z(4.0, 2.0, P.tip_z, x, y) for (x, y) in f["jets"]])
    doc.getObject("anim_dots").Shape = _compound([G.wet_dot(x, y) for (x, y) in f["dots"]])
    det = [ring(w[0], w[1], w[2] + 20.0) for w, s in zip(weeds, f["weeds"]) if s["detected"] and not s["protected"]]
    left = [ring(w[0], w[1], w[2] + 20.0, w=8.0) for w, s in zip(weeds, f["weeds"]) if s["detected"] and s["protected"]]
    doc.getObject("anim_detected").Shape = _compound(det)
    doc.getObject("anim_left").Shape = _compound(left)


