"""Model of the riding arena leveller on the Bruut OpenAgbot (standard robot).

Mount (toolbar, hangers, pivot lugs, actuator mast), lift actuator and the frame weldment are the grassland harrow's
(build_gha / gha_parts, imported); this file adds the loosening tines, the levelling board, the rod roller and the
lidar post.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_arl
    build_arl.build()
    build_arl.set_pose(25)                 # lift (degrees, + = up)
    build_arl.check_interference()         # must be empty
    build_arl.check_holes()
    build_arl.check_poses()                # over the lift poses: empty
    build_arl.ground_contact()             # tine points, board heel, roller in the work pose
    build_arl.mass_properties()
    build_arl.render_all()
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import arl_params as P
import arl_parts as G
import gha_parts as HG
import build_gha as BG

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Arena_Leveller"
SAVE_BASE = os.path.join(FOLDER, "Arena_Leveller")
ROOT = "Arena_leveller"

COLOR = dict(BG.COLOR)
COLOR.update({"tine": (0.25, 0.27, 0.30), "point": (0.75, 0.75, 0.78), "roller": (0.93, 0.42, 0.08),
              "lidar": (0.12, 0.12, 0.13), "bearing": (0.10, 0.20, 0.45)})
for k in ("frame", "zinc", "board", "actuator", "steel", "plastic"):
    COLOR.setdefault(k, (0.6, 0.6, 0.6))


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


lift_placement = BG.lift_placement


def build_leveller(doc, parent, lift=P.lift_work):
    grp = BG.new_part(doc, parent, "Leveller", "leveller_turns_about_pivot", lift_placement(lift))
    add_shape(doc, grp, "arl_frame", "frame_weldment_of_the_grassland_harrow", G.frame(), "frame")
    add_shape(doc, grp, "arl_tines", "rigid_tines_40x12_x%d" % P.tine_n, G.tines(), "tine")
    add_shape(doc, grp, "arl_points", "reversible_points_hardened", G.points(), "point")
    add_shape(doc, grp, "arl_clamps", "tine_clamp_plates_8mm", G.tine_clamps(), "frame")
    add_shape(doc, grp, "arl_tine_bolts", "tine_bolts_M10", G.tine_bolts(), "zinc")
    add_shape(doc, grp, "arl_board", "levelling_board_angle_100x100x8_L1300", G.board(), "board")
    add_shape(doc, grp, "arl_straps", "board_straps_60x8_height_holes", G.straps(), "frame")
    add_shape(doc, grp, "arl_strap_bolts", "strap_bolts_M10", G.strap_bolts(), "zinc")
    add_shape(doc, grp, "arl_side_plates", "roller_side_plates_8mm", G.side_plates(), "frame")
    add_shape(doc, grp, "arl_bearings", "bearings_UCFL205", G.bearings(), "bearing")
    add_shape(doc, grp, "arl_roller", "rod_roller_O220_12_rods_O16", G.roller(), "roller")
    return grp


def build_into(doc, parent=None, lift=P.lift_work):
    root = BG.new_part(doc, parent, ROOT, "arena_leveller_simple")
    BG.build_mount(doc, root)
    build_leveller(doc, root, lift)
    BG.build_actuator(doc, root, lift)
    post = BG.new_part(doc, root, "arl_Lidar", "lidar_post_360_degree")
    add_shape(doc, post, "arl_post", "lidar_post_40x40x3_clamp_plate", G.lidar_post(), "frame")
    add_shape(doc, post, "arl_lidar", "lidar_360_degree_2D", G.lidar(), "lidar")
    return root


def set_pose(lift=P.lift_work, doc=None):
    doc = active_doc(doc)
    doc.getObject("Leveller").Placement = lift_placement(lift)
    body, rod, _ = HG.actuator(lift)
    doc.getObject("act_body").Shape = body
    doc.getObject("act_rod").Shape = rod
    doc.recompute()


global_shape = BG.global_shape
_overlaps = BG._overlaps


def build(save=True, show_robot=False, step=True, lift=P.lift_work):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Arena leveller simple"
    doc.Comment = ("Generated by build_arl.py from arl_params.py (mount, actuator, frame from grassland harrow/simple). "
                   "Robot coordinates: x = right, y = driving direction (front = +y), z = up, z 0 = footing surface.")
    robot = None
    try:
        robot = BG.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, lift)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("arl_tine_bolts", "arl_tines"), ("arl_tine_bolts", "arl_clamps"), ("arl_strap_bolts", "arl_straps"),
          ("arl_strap_bolts", "arl_frame"), ("arl_strap_bolts", "arl_board"), ("arl_roller", "arl_bearings"),
          ("arl_roller", "arl_side_plates"), ("arl_points", "arl_tines")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS or BG._joint(a, b):
        return True
    return False


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """The new bolts must sit in holes (JOINTS overlap ~0, except the roller shaft in its bearings)."""
    doc = active_doc(doc)
    out = {}
    for a, b in sorted(JOINTS):
        if not a.endswith("bolts"):
            continue
        sa, sb = global_shape(doc.getObject(a)), global_shape(doc.getObject(b))
        if sa.BoundBox.intersect(sb.BoundBox):
            v = sa.common(sb).Volume
            if v > tol:
                out[str((a, b))] = round(v, 1)
    return out


def check_poses(doc=None, tol=1.0):
    doc = active_doc(doc)
    lev = objects_of(doc, "Leveller") + objects_of(doc, "Actuator")
    names = {o.Name for o in lev}
    fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    out = {}
    for lift in P.LIFT_POSES:
        set_pose(lift, doc)
        mv = [(o, global_shape(o)) for o in lev]
        hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
        if hits:
            out[str(lift)] = hits
    set_pose(P.lift_work, doc)
    return out


def ground_contact(doc=None):
    doc = active_doc(doc)
    out = {}
    for lift in (P.lift_work, P.lift_transport):
        set_pose(lift, doc)
        out["lift_%g" % lift] = {n: round(global_shape(doc.getObject(n)).BoundBox.ZMin, 1)
                                 for n in ("arl_points", "arl_board", "arl_roller")}
    set_pose(P.lift_work, doc)
    return out


MASS_FIXED = {"arl_lidar": 0.8, "arl_bearings": 2 * 1.1, "act_body": 2.0, "act_rod": 0.6}


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    if obj.Name == "toolbar_caps":
        return vol * 0.95e-6, cg
    return vol * P.steel, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Leveller", "Actuator", "arl_Lidar"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


set_camera = BG.set_camera


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_footing", "render_band", "render_prints")


def add_scene(doc):
    y0, y1 = -4000.0, 1500.0
    for name, shape, color in ((SCENE[0], G.footing(y0, y1), (0.85, 0.75, 0.55)),
                               (SCENE[1], G.worked_band(y0, P.roll_y), (0.92, 0.84, 0.66)),
                               (SCENE[2], G.hoof_prints(y0, y1), (0.70, 0.60, 0.42))):
        o = doc.addObject("Part::Feature", name)
        o.Shape = shape
        o.ViewObject.ShapeColor = color


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_rear_on_robot_in_arena.png", (-1.0, 1.1, -0.6), target=(0, -900, 300), height=2900))
    out.append(save_view("2_side_work.png", (1.0, 0.0, 0.0), target=(0, -700, 400), height=2000))
    doc.getObject(SCENE[0]).ViewObject.Transparency = 60
    out.append(save_view("3_side_tines_in_footing.png", (1.0, 0.0, -0.1), target=(0, -1300, 150), height=900))
    for n in SCENE:
        doc.removeObject(n)
    set_pose(P.lift_transport, doc)
    out.append(save_view("4_side_lifted_25deg.png", (1.0, 0.0, 0.0), target=(0, -700, 450), height=2000))
    set_pose(P.lift_work, doc)
    set_robot_visible(False, doc)
    out.append(save_view("5_iso_tools_from_front_below.png", (-0.7, -1.0, 0.45), target=(0, -1300, 150), height=1700))
    out.append(save_view("6_top.png", (0.0, 0.0, -1.0), target=(0, -1000, 0), up=(0.0, 1.0, 0.0), height=1900))
    App.closeDocument(doc.Name)
    build()
    return out
