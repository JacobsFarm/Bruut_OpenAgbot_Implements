"""Model of the windbreak and tree-row inspector on the Bruut OpenAgbot (standard robot).

Base plate, mast and gussets from "fence inspector/simple" (fin_parts); this file adds the extension and the head.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_wbi
    build_wbi.build()                 # saves FCStd and STEP
    build_wbi.check_interference()    # overlap (must be empty)
    build_wbi.check_holes()           # bolts in their holes (must be empty)
    build_wbi.check_steering()        # mast and head against the steered front wheels (must be empty)
    build_wbi.mass_properties()
    build_wbi.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import wbi_params as P
import wbi_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Windbreak_Inspector"
SAVE_BASE = os.path.join(FOLDER, "Windbreak_Inspector")
ROOT = "Windbreak_inspector"

COLOR = dict(BP.COLOR)
COLOR.update({"mast": (0.85, 0.40, 0.10), "alu": (0.80, 0.82, 0.85), "sensor": (0.15, 0.15, 0.18),
              "hedge": (0.25, 0.45, 0.20), "trunk": (0.40, 0.30, 0.20), "crown": (0.30, 0.55, 0.25)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "windbreak_inspector_simple")
    mount = new_part(doc, root, "Mount", "mast_from_fence_inspector")
    add_shape(doc, mount, "base_plate", "base_plate_8mm", G.base_plate(), "mast")
    add_shape(doc, mount, "plate_bolts", "base_plate_bolts_M10_4x", G.plate_bolts(), "zinc")
    add_shape(doc, mount, "mast", "mast_60x60x3_2_holes", G.mast().cut(G.mast_bolt_holes()), "mast")
    add_shape(doc, mount, "gussets", "gussets_8mm_2x", G.gussets(), "mast")
    add_shape(doc, mount, "extension", "extension_50x50x3_to_2100", G.extension(), "mast")
    add_shape(doc, mount, "ext_bolts", "extension_bolts_M10_2x", G.ext_bolts(), "zinc")
    head = new_part(doc, root, "SensorHead", "sensor_head")
    add_shape(doc, head, "head", "head_box_alu_120x260x420", G.head(), "alu")
    add_shape(doc, head, "lidar", "lidar_2D_270deg_vertical_plane", G.lidar(), "sensor")
    add_shape(doc, head, "cameras", "stereo_pair_and_crown_camera", G.cameras(), "sensor")
    return root


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Windbreak inspector simple"
    doc.Comment = ("Generated by build_wbi.py from wbi_params.py (mast from fence inspector/simple). Robot coordinates: "
                   "x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("plate_bolts", "base_plate"), ("ext_bolts", "mast"), ("ext_bolts", "extension"), ("base_plate", "mast"),
          ("gussets", "mast"), ("gussets", "base_plate")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "plate_bolts" in (a, b) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    out = {}
    for a, b in (("plate_bolts", "base_plate"), ("ext_bolts", "mast"), ("ext_bolts", "extension")):
        v = objs[a].common(objs[b]).Volume
        if v > tol:
            out[str((a, b))] = round(v, 1)
    return out


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in mine for b in rob], tol)
        if hits:
            out[str(st)] = hits
    set_steering(0.0, doc)
    return out


DENSITY = {"head": 0.25 * P.alu, "extension": P.alu}
MASS_FIXED = {"lidar": 1.2, "cameras": 0.6}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
        m += mo
        c += s.BoundBox.Center * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


