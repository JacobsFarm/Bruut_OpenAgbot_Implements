def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_floor", "render_hedge", "render_trunks", "render_crowns")


def add_scene(doc):
    f = doc.addObject("Part::Feature", SCENE[0])
    f.Shape = G.box_span((-1100.0, 2600.0), (-1600.0, 2600.0), (-40.0, 0.0))
    f.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    f.ViewObject.Transparency = 30
    h = doc.addObject("Part::Feature", SCENE[1])
    h.Shape = G.hedge()
    h.ViewObject.ShapeColor = COLOR["hedge"]
    h.ViewObject.Transparency = 40
    tr = G.trees()
    t = doc.addObject("Part::Feature", SCENE[2])
    t.Shape = Part.makeCompound(tr[0::2])
    t.ViewObject.ShapeColor = COLOR["trunk"]
    c = doc.addObject("Part::Feature", SCENE[3])
    c.Shape = Part.makeCompound(tr[1::2])
    c.ViewObject.ShapeColor = COLOR["crown"]
    c.ViewObject.Transparency = 40


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_along_row.png", (1.0, 1.3, -0.5), target=(700, 300, 1500)))
    out.append(save_view("2_rear_view.png", (0.0, 1.0, 0.0), target=(900, 0, 1800), height=4500))
    remove(doc, SCENE)
    out.append(save_view("3_iso_on_robot.png", (-1.0, -1.2, -0.6), target=(200, 0, 1000)))
    set_robot_visible(False, doc)
    out.append(save_view("4_sensor_head.png", (-1.0, -0.7, -0.3), target=(520, 0, 2000), height=700))
    App.closeDocument(doc.Name)
    build()
    return out
