def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj







def build_into(doc, parent=None):
    """Hitch (from build_cbr) on the robot, the trailer with the cbr drawbar and coupling, the load."""
    root = new_part(doc, parent, ROOT, "bag_trailer_simple")
    C.build_hitch(doc, root)
    tr = new_part(doc, root, TRAILER, "bag_trailer_turns_about_the_ball")
    fr = new_part(doc, tr, "Frame", "trailer_frame_deck")
    add_shape(doc, fr, "frame", "frame_rails_cross_members_40x40x3", G.frame(), "frame")
    add_shape(doc, fr, "cross_beam", "front_cross_beam_40x40x3", C.G.cross_beam(P.cross_y), "frame")
    add_shape(doc, fr, "axle", "axle_50x50x4_spindles_D30", G.axle(), "zinc")
    add_shape(doc, fr, "deck", "deck_plywood_18", G.deck(), "wood")
    add_shape(doc, fr, "boards", "side_front_boards_plywood_18", G.boards(), "wood")
    add_shape(doc, fr, "tailgate", "drop_tailgate_plywood_18", G.tailgate(), "wood")
    add_shape(doc, fr, "mudguards", "mudguards_2mm", G.mudguards(), "frame")
    wh = new_part(doc, tr, "Wheels", "wheels_4_00_8")
    add_shape(doc, wh, "wheels", "tyres_4_00_8_D400", G.wheels(), "rubber")
    add_shape(doc, wh, "rims", "rims_hubs", G.rims(), "zinc")
    C.build_drawbar(doc, tr, P.cross_y)
    ld = new_part(doc, tr, "Load", "bags_12x25kg")
    add_shape(doc, ld, "bags", "bags_25kg_12x", G.bags(), "bag")
    return root


def set_articulation(yaw=0.0, pitch=0.0, doc=None):
    active_doc(doc).getObject(TRAILER).Placement = C.articulation(yaw, pitch)


def set_load(visible=True, doc=None):
    for o in objects_of(active_doc(doc), "Load"):
        o.ViewObject.Visibility = visible


def build_robot(doc):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, 0.0)
    return robot


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Bag trailer simple"
    doc.Comment = ("Generated by build_bgt.py from bgt_params.py (hitch, coupling and drawbar from build_cbr). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


