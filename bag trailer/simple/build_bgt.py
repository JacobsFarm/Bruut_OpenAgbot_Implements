"""Model of the bag trailer behind the Bruut OpenAgbot (standard robot), on the tow hitch of the cambridge roll.
The hitch, coupling head, drawbar, braces and parking leg come from build_cbr ("overseeding/cambridge roll").

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_bgt
    build_bgt.build()                      # saves FCStd and STEP (loaded, straight)
    build_bgt.set_articulation(60, 0)      # trailer yaw / pitch about the ball (deg)
    build_bgt.set_load(False)              # hide the bags
    build_bgt.check_interference()         # overlap (must be empty)
    build_bgt.check_poses()                # yaw +-75, pitch +-8 (must be empty)
    build_bgt.trailer_mass()
    build_bgt.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import bgt_params as P
import bgt_parts as G
import build_cbr as C

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Bag_Trailer"
SAVE_BASE = os.path.join(FOLDER, "Bag_Trailer")
ROOT = "Bag_trailer"
TRAILER = "Trailer"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "wood": (0.55, 0.38, 0.22),
    "rubber": (0.10, 0.10, 0.10),
    "bag": (0.92, 0.90, 0.80),
}


