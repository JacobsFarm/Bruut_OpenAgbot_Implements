def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    if g is None:
        return []
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"]


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        try:
            vol = sa.common(sb).Volume
        except Exception as exc:
            hits.append((oa.Label, ob.Label, "error %s" % exc))
            continue
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits




JOINTS = {("frame", "cross_beam"), ("frame", "axle"), ("axle", "rims"), ("rims", "wheels"), ("deck", "frame"),
          ("deck", "cross_beam"), ("boards", "deck"), ("tailgate", "deck"), ("tailgate", "boards"),
          ("mudguards", "frame"), ("bags", "deck"), ("braces", "cross_beam"), ("drawbar", "cross_beam"),
          ("drawbar", "coupling"), ("drawbar", "braces"), ("park_lug", "drawbar"), ("park_pin", "park_lug"),
          ("park_pin", "park_leg"), ("hitch_bolts", "hitch_plate"), ("hitch_leg", "hitch_plate"),
          ("hitch_leg", "hitch_bar"), ("hitch_gusset", "hitch_bar"), ("hitch_gusset", "hitch_leg"),
          ("tow_ball", "hitch_bar"), ("ball_stud", "hitch_bar"), ("ball_stud", "tow_ball")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return (a == "hitch_bolts" and b.startswith("lower_beam")) or (b == "hitch_bolts" and a.startswith("lower_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


ARTICULATION_POSES = [(y, p) for y in (-75.0, -45.0, 45.0, 75.0) for p in (-8.0, 0.0, 8.0)]


def check_poses(doc=None, tol=1.0):
    """Trailer yawed +-75 and pitched +-8 degrees about the ball against the hitch and the robot. Must be empty."""
    doc = active_doc(doc)
    moving = objects_of(doc, TRAILER)
    names = {o.Name for o in moving}
    fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) + robot_objects(doc) if o.Name not in names]
    out = {}
    for yaw, pitch in ARTICULATION_POSES:
        set_articulation(yaw, pitch, doc)
        mv = [(o, global_shape(o)) for o in moving]
        hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
        if hits:
            out[(yaw, pitch)] = hits
    set_articulation(0.0, 0.0, doc)
    return out


def trailer_mass(doc=None):
    """Trailer empty and loaded: mass and cg y (for the ball load); hitch mass."""
    doc = active_doc(doc)
    tr = [o for o in objects_of(doc, TRAILER) if o.Name != "bags"]
    m, c = sum_mass(tr)
    mh, _ = sum_mass([o for o in objects_of(doc, ROOT) if o not in objects_of(doc, TRAILER)])
    return {"trailer_kg": round(m, 1), "trailer_cg_y": round(c.y), "hitch_kg": round(mh, 1)}


MASS_FIXED = {"coupling": 3.5, "tow_ball": 1.6, "bags": 12 * P.bag_kg}
DENSITY = (("deck", P.ply), ("boards", P.ply), ("tailgate", P.ply), ("wheels", P.rubber * 0.35))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    for key, m in MASS_FIXED.items():
        if obj.Name == key:
            return m, cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
            break
    return vol * dens, cg


def sum_mass(objs):
    m, c = 0.0, V(0, 0, 0)
    for o in objs:
        mo, co = _mass_cg(o)
        m += mo
        c += co * mo
    return m, (c * (1.0 / m) if m > 0 else c)


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity (robot coordinates) of everything, the trailer with load, the hitch and the load."""
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, TRAILER, "Hitch", "Load"):
        m, c = sum_mass(objects_of(doc, name))
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


