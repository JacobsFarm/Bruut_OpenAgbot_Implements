"""Model of the mole and tunnel mapper on the Bruut OpenAgbot (standard robot).

The camera bridge is built here; the cone penetrometer is the soil compaction meter (build_scm.build_into), unchanged.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_mmp
    build_mmp.build()                 # saves FCStd and STEP (penetrometer parked)
    build_mmp.set_pose(tip=-300)      # cone tip height (mm, - = in the soil)
    build_mmp.check_interference()    # overlap in the current pose (must be empty)
    build_mmp.check_holes()           # bolts in their holes (must be empty)
    build_mmp.check_poses()           # penetrometer park..full depth x steering +-30 (must be empty)
    build_mmp.mass_properties()
    build_mmp.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
from FreeCAD import Vector as V

import mmp_params as P
import mmp_parts as G
import build_pbl as BP
import build_scm as SC

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Mole_Mapper"
SAVE_BASE = os.path.join(FOLDER, "Mole_Mapper")
ROOT = "Mole_mapper"

COLOR = dict(BP.COLOR)
COLOR.update({"alu": (0.80, 0.82, 0.85), "camera": (0.15, 0.15, 0.18), "thermal": (0.75, 0.20, 0.15),
              "soil": (0.35, 0.25, 0.18)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build_into(doc, parent=None, tip=P.tip_park):
    root = new_part(doc, parent, ROOT, "mole_mapper_simple")
    cam = new_part(doc, root, "CamBridge", "camera_bridge_on_front_beam")
    add_shape(doc, cam, "cam_brackets", "post_brackets_8mm_2x", G.brackets(), "frame")
    add_shape(doc, cam, "cam_bracket_bolts", "post_bracket_bolts_M10_4x", G.bracket_bolts(), "zinc")
    add_shape(doc, cam, "cam_posts", "posts_alu_40x40x3_2x", G.posts(), "alu")
    add_shape(doc, cam, "cam_bar", "cross_bar_alu_40x40x3_L1800", G.cross_bar(), "alu")
    add_shape(doc, cam, "cam_stays", "stays_flat_30x5_2x", G.stays(), "alu")
    add_shape(doc, cam, "cameras", "rgb_cameras_4K_3x", G.cameras(), "camera")
    add_shape(doc, cam, "thermal", "thermal_camera_640", G.thermal(), "thermal")
    SC.build_into(doc, root, tip)
    return root


def set_pose(tip=P.tip_park, doc=None):
    SC.set_pose(tip, active_doc(doc))


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True, tip=P.tip_park):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Mole mapper simple"
    doc.Comment = ("Generated by build_mmp.py from mmp_params.py (penetrometer from soil compaction meter/simple). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, tip)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("cam_bracket_bolts", "cam_brackets"), ("cam_posts", "cam_brackets"), ("cam_posts", "cam_bar"),
          ("cam_stays", "cam_posts"), ("cam_stays", "cam_bar")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS or SC._joint(a, b):
        return True
    return "cam_bracket_bolts" in (a, b) and (a.startswith("lower_beam") or b.startswith("lower_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    doc = active_doc(doc)
    objs = {o.Name: global_shape(o) for o in objects_of(doc, ROOT)}
    out = {}
    for a, b in (("cam_bracket_bolts", "cam_brackets"),):
        v = objs[a].common(objs[b]).Volume
        if v > tol:
            out[str((a, b))] = round(v, 1)
    return out


def check_poses(doc=None, tol=1.0, steer=(-P.robot_steer_deg, 0.0, P.robot_steer_deg)):
    """Penetrometer park..full depth, and the camera bridge against the steered front wheels. Must be empty."""
    doc = active_doc(doc)
    out = {}
    cam = [(o, None) for o in objects_of(doc, "CamBridge")]
    moving = objects_of(doc, "Carriage") + objects_of(doc, "Foot")
    names = {o.Name for o in moving} | {o.Name for o, _ in cam}
    for st in steer:
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc)]
        fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) if o.Name not in names] + rob
        cams = [(o, global_shape(o)) for o, _ in cam]
        for tip in (P.tip_park, -P.probe_depth, -P.C.depth_max):
            set_pose(tip, doc)
            mv = [(o, global_shape(o)) for o in moving]
            pairs = [(a, b) for a in mv + cams for b in fixed if not _joint(a[0].Name, b[0].Name)]
            pairs += [(a, b) for a in mv for b in cams]
            hits = _overlaps(pairs, tol)
            if hits:
                out[str((st, tip))] = hits
    set_steering(0.0, doc)
    set_pose(P.tip_park, doc)
    return out


DENSITY = (("cam_posts", P.alu), ("cam_bar", P.alu), ("cam_stays", P.alu))
MASS_FIXED = {"cameras": 0.9, "thermal": 0.4}


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    m_scm, c_scm = SC.sum_mass(objects_of(doc, SC.ROOT))
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, "CamBridge"):
        s = global_shape(o)
        if o.Name in MASS_FIXED:
            mo = MASS_FIXED[o.Name]
        else:
            dens = dict(DENSITY).get(o.Name, P.steel)
            mo = s.Volume * dens
        m += mo
        c += s.BoundBox.Center * mo
    out["cam_bridge_kg"] = round(m, 1)
    out["cam_bridge_cg"] = tuple(round(v) for v in c * (1.0 / m))
    out["penetrometer_kg"] = round(m_scm, 1)
    tot = m + m_scm
    cy = (c.y + c_scm.y * m_scm) / tot
    out["total_kg"] = round(tot, 1)
    out["total_cg_y"] = round(cy)
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


