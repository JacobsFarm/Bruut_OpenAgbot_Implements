def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_floor", "render_hills", "render_tunnels")
HILLS = ((-500.0, 1900.0), (700.0, 2600.0), (550.0, -500.0))


def add_scene(doc, cut=False):
    import Part
    f = doc.addObject("Part::Feature", SCENE[0])
    floor = G.box_span((-1500.0, 1500.0), (-1200.0, 3200.0), (-400.0 if cut else -40.0, 0.0))
    tun = [G.tunnel((-700.0, P.C.rod_y), (800.0, P.C.rod_y)), G.tunnel((300.0, P.C.rod_y), (700.0, -800.0))]
    if cut:
        floor = floor.cut(Part.makeCompound(tun)).cut(G.box_span((-1500.0, 1500.0), (P.C.rod_y, 3200.0), (-401.0, 1.0)))
    f.Shape = floor
    f.ViewObject.ShapeColor = (0.45, 0.62, 0.30)
    f.ViewObject.Transparency = 0 if cut else 30
    h = doc.addObject("Part::Feature", SCENE[1])
    h.Shape = Part.makeCompound([G.hill(x, y) for x, y in HILLS])
    h.ViewObject.ShapeColor = COLOR["soil"]
    if cut:
        t = doc.addObject("Part::Feature", SCENE[2])
        t.Shape = Part.makeCompound(tun)
        t.ViewObject.ShapeColor = (0.15, 0.10, 0.08)


def remove(doc, names):
    for n in names:
        if doc.getObject(n):
            doc.removeObject(n)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    out.append(save_view("1_iso_front_on_robot.png", (-1.0, -1.2, -0.7), target=(0, 700, 600)))
    out.append(save_view("2_side.png", (1.0, 0.0, 0.0), target=(0, 900, 700), height=2000))
    remove(doc, SCENE)
    add_scene(doc, cut=True)
    set_pose(-P.probe_depth, doc)
    set_robot_visible(False, doc)
    doc.getObject("CamBridge").Visibility = False
    out.append(save_view("3_probing_tunnel_cutaway.png", (0.35, -1.0, -0.3), target=(100, 0, 150), height=1300))
    doc.getObject("CamBridge").Visibility = True
    set_robot_visible(True, doc)
    remove(doc, SCENE)
    set_pose(P.tip_park, doc)
    set_steering(P.robot_steer_deg, doc)
    out.append(save_view("4_top_steered_30deg.png", (0.0, 0.0, -1.0), target=(0, 500, 0), up=(0.0, 1.0, 0.0),
                         height=2400))
    set_steering(0.0, doc)
    set_robot_visible(False, doc)
    out.append(save_view("5_camera_bar.png", (-0.6, 1.0, 0.4), target=(0, 620, 1350), height=900))
    App.closeDocument(doc.Name)
    build()
    return out
