def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj







def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "sawdust_spreader_simple")
    mount = new_part(doc, root, "Mount", "mount_bearers_legs")
    add_shape(doc, mount, "bearers", "bearers_40x40x3_2x", G.bearers(), "frame")
    add_shape(doc, mount, "bearer_bolts", "bearer_bolts_M10_8x", G.bearer_bolts(), "zinc")
    add_shape(doc, mount, "legs", "legs_angle_40x4_4x", G.legs(), "frame")
    b = new_part(doc, root, "Bin", "bin_2mm")
    add_shape(doc, b, "bin_walls", "bin_slopes_and_trough_2mm", G.bin_walls(), "bin")
    add_shape(doc, b, "side_walls", "bin_side_walls_2mm", G.side_walls(), "bin")
    a = new_part(doc, root, "Auger", "auger_and_drive")
    add_shape(doc, a, "auger_shaft", "auger_shaft_D%d" % P.auger_shaft, G.auger_shaft(), "zinc")
    add_shape(doc, a, "auger_flight", "auger_flight_D%d_pitch_%d" % (P.auger_d, P.auger_pitch), G.auger_flight(), "steel")
    add_shape(doc, a, "outlet_tube", "outlet_tube_D170", G.outlet_tube(), "bin")
    box, motor = G.gearmotor()
    add_shape(doc, a, "gearbox", "auger_worm_gearbox", box, "motor")
    add_shape(doc, a, "gear_motor", "auger_motor_24V_200W", motor, "motor")
    add_shape(doc, a, "end_bearing", "auger_end_bearing", G.bearing_housing(), "motor")
    s = new_part(doc, root, "Spinner", "spinner_housing_disc")
    add_shape(doc, s, "housing", "spinner_housing_2mm", G.housing(), "bin")
    add_shape(doc, s, "disc", "spinner_disc_D%d_4_vanes" % P.disc_d, G.disc(), "steel")
    add_shape(doc, s, "spinner_motor", "spinner_motor_24V", G.spinner_motor(), "motor")
    return root


def build_robot(doc, steer=0.0):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, steer if tag in ("FL", "FR") else 0.0)
    return robot


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Sawdust spreader simple"
    doc.Comment = ("Generated by build_sds.py from sds_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


