"""Model of the sawdust spreader on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_sds
    build_sds.build()                      # saves FCStd and STEP
    build_sds.check_interference()         # overlap (must be empty)
    build_sds.check_poses()                # front wheels steered +-30 (must be empty)
    build_sds.clearance()                  # bin to the steered front wheel units
    build_sds.mass_properties()
    build_sds.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import sds_params as P
import sds_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Sawdust_Spreader"
SAVE_BASE = os.path.join(FOLDER, "Sawdust_Spreader")
ROOT = "Sawdust_spreader"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "bin": (0.20, 0.45, 0.25),
    "steel": (0.75, 0.75, 0.78),
    "motor": (0.25, 0.26, 0.28),
}


