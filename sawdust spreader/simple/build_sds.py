def active_doc(doc=None):
    if doc is not None:
        return doc
    d = App.ActiveDocument
    if d is not None and d.getObject(ROOT) is not None:
        return d
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def objects_of(doc, name):
    g = doc.getObject(name)
    if g is None:
        return []
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"]


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


def _overlaps(pairs, tol):
    hits = []
    for (oa, sa), (ob, sb) in pairs:
        if not sa.BoundBox.intersect(sb.BoundBox):
            continue
        try:
            vol = sa.common(sb).Volume
        except Exception as exc:
            hits.append((oa.Label, ob.Label, "error %s" % exc))
            continue
        if vol > tol:
            hits.append((oa.Label, ob.Label, round(vol, 1)))
    return hits




JOINTS = {("bearer_bolts", "bearers"), ("legs", "bearers"), ("legs", "bin_walls"), ("bin_walls", "side_walls"),
          ("auger_shaft", "side_walls"), ("auger_shaft", "gearbox"), ("auger_shaft", "end_bearing"),
          ("auger_shaft", "housing"), ("auger_shaft", "auger_flight"), ("outlet_tube", "side_walls"),
          ("outlet_tube", "housing"), ("end_bearing", "housing"), ("gearbox", "side_walls"), ("disc", "housing"),
          ("disc", "spinner_motor"), ("spinner_motor", "housing")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return (a == "bearer_bolts" and b.startswith("upper_beam")) or (b == "bearer_bolts" and a.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_poses(doc=None, tol=1.0):
    """Front wheels steered +-30: the spreader against the front wheel units. Must be empty."""
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    out = {}
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        front = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL_", "FR_"))]
        hits = _overlaps([(a, b) for a in mine for b in front], tol)
        if hits:
            out[st] = hits
    set_steering(0.0, doc)
    return out


def clearance(doc=None):
    """Smallest distance (mm) of the bin front to the steered front wheel units (above the beams)."""
    doc = active_doc(doc)
    mine = [global_shape(doc.getObject(n)) for n in ("bin_walls", "side_walls", "housing")]
    best = 1e9
    for st in (-P.robot_steer_deg, 0.0, P.robot_steer_deg):
        set_steering(st, doc)
        front = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith(("FL_", "FR_"))
                 and global_shape(o).BoundBox.ZMax > 650.0]
        for a in mine:
            for t in front:
                best = min(best, a.distToShape(t)[0])
    set_steering(0.0, doc)
    return round(best, 1)


MASS_FIXED = {"auger_flight": 6.5, "gearbox": 4.5, "gear_motor": 2.0, "spinner_motor": 2.5, "end_bearing": 0.8}
DENSITY = ()


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    for key, m in MASS_FIXED.items():
        if obj.Name == key:
            return m, cg
    dens = P.steel
    for key, d in DENSITY:
        if obj.Name.startswith(key):
            dens = d
            break
    return vol * dens, cg


def sum_mass(objs):
    m, c = 0.0, V(0, 0, 0)
    for o in objs:
        mo, co = _mass_cg(o)
        m += mo
        c += co * mo
    return m, (c * (1.0 / m) if m > 0 else c)


def mass_properties(doc=None):
    """Mass (kg) and centre of gravity (robot coordinates) of the whole spreader and of each group (empty)."""
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Bin", "Auger", "Spinner"):
        m, c = sum_mass(objects_of(doc, name))
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


