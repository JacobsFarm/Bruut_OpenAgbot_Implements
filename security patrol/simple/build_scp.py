"""Model of the security patrol on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_scp
    build_scp.build()                 # saves FCStd and STEP
    build_scp.check_interference()    # overlap (must be empty)
    build_scp.check_holes()           # bolts in the grid holes of the upper beams (must be empty)
    build_scp.check_poses()           # pan/tilt head over all poses (must be empty)
    build_scp.check_steering()        # against the steered front wheels (must be empty)
    build_scp.mass_properties()
    build_scp.render_all()            # all images in previews/
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import scp_params as P
import scp_parts as G
import build_pbl as BP

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Security_Patrol"
SAVE_BASE = os.path.join(FOLDER, "Security_Patrol")
ROOT = "Security_patrol"

COLOR = dict(BP.COLOR)
COLOR.update({"horn": (0.92, 0.92, 0.90), "box": (0.20, 0.22, 0.25), "cam": (0.95, 0.95, 0.95),
              "lens": (0.05, 0.05, 0.08), "beacon": (1.0, 0.6, 0.05), "mast": (0.30, 0.32, 0.35)})


def new_part(doc, parent, name, label, placement=None):
    return BP.new_part(doc, parent, name, label, placement)


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = BP.add_shape(doc, parent, name, label, shape, "frame", visible)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def pan_placement(pan=0.0):
    return App.Placement(V(P.mast_xy[0], P.mast_xy[1], 0.0), App.Rotation(V(0, 0, 1), pan))


def tilt_placement(tilt=0.0):
    return App.Placement(V(0.0, 0.0, P.tilt_z), App.Rotation(V(1, 0, 0), tilt))


def build_into(doc, parent=None, pan=0.0, tilt=0.0):
    root = new_part(doc, parent, ROOT, "security_patrol_simple")
    mount = new_part(doc, root, "Mount", "base_plate_mast")
    add_shape(doc, mount, "scp_plate", "base_plate_8mm_on_4_upper_beams", G.base_plate(), "frame")
    add_shape(doc, mount, "scp_bolts", "base_bolts_M10_8x", G.base_bolts(), "zinc")
    add_shape(doc, mount, "scp_mast", "mast_80x80x4_2m_with_top_flange", G.mast(), "mast")
    add_shape(doc, mount, "scp_gussets", "gussets_8mm_4x", G.gussets(), "frame")
    sens = new_part(doc, root, "Sensors", "fixed_cameras_horns_beacon_box")
    add_shape(doc, sens, "fixed_cams", "fixed_cameras_wide_4x", G.fixed_cams(), "cam")
    add_shape(doc, sens, "horn_clamp", "horn_clamp_band", G.horn_clamps(), "zinc")
    add_shape(doc, sens, "horns", "horn_speakers_30W_front_rear", G.horns(), "horn")
    add_shape(doc, sens, "beacon_bracket", "beacon_bracket", G.beacon_bracket(), "frame")
    add_shape(doc, sens, "beacon", "amber_LED_beacon", G.beacon(), "beacon")
    add_shape(doc, sens, "mic", "microphone", G.mic(), "box")
    add_shape(doc, sens, "elec_box", "box_recorder_LTE_PoE_IP65", G.elec_box(), "box")
    add_shape(doc, sens, "antennas", "LTE_antennas_2x", G.antennas(), "box")
    add_shape(doc, sens, "pan_base", "pan_unit_base", G.pan_base(), "box")
    pan_p = new_part(doc, root, "Pan", "pan_head", pan_placement(pan))
    add_shape(doc, pan_p, "pan_yoke", "pan_yoke_8mm", G.pan_yoke(), "cam")
    add_shape(doc, pan_p, "tilt_motor", "tilt_motor", G.pan_motor(), "box")
    tilt_p = new_part(doc, pan_p, "Tilt", "tilt_head", tilt_placement(tilt))
    add_shape(doc, tilt_p, "tilt_axle", "tilt_axle_20", G.tilt_axle(), "steel")
    add_shape(doc, tilt_p, "tilt_frame", "camera_bracket", G.tilt_frame(), "box")
    add_shape(doc, tilt_p, "cam_vis", "day_night_camera_30x_zoom", G.tilt_vis(), "cam")
    add_shape(doc, tilt_p, "cam_ir", "thermal_camera_640x512", G.tilt_ir(), "lens")
    add_shape(doc, tilt_p, "illum", "IR_illuminator_850nm", G.tilt_illum(), "lens")
    return root


def set_pose(pan=0.0, tilt=0.0, doc=None):
    doc = active_doc(doc)
    doc.getObject("Pan").Placement = pan_placement(pan)
    doc.getObject("Tilt").Placement = tilt_placement(tilt)
    doc.recompute()


build_robot = BP.build_robot
set_steering = BP.set_steering
global_shape = BP.global_shape
_overlaps = BP._overlaps
objects_of = BP.objects_of


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Security patrol simple"
    doc.Comment = ("Generated by build_scp.py from scp_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    for n in App.listDocuments():
        d = App.getDocument(n)
        if d.getObject(ROOT) is not None:
            return d
    raise RuntimeError("no document with %s open" % ROOT)


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


JOINTS = {("scp_bolts", "scp_plate"), ("tilt_axle", "pan_yoke"), ("tilt_axle", "tilt_frame"), ("tilt_axle", "tilt_motor"),
          ("tilt_frame", "cam_vis"), ("tilt_frame", "cam_ir"), ("horn_clamp", "horns")}


def _joint(a, b):
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    return "scp_bolts" in (a, b) and (a.startswith("upper_beam") or b.startswith("upper_beam"))


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_holes(doc=None, tol=1.0):
    """Each bolt shank must pass through a hole of an upper beam: a vertical O10 rod at the bolt position may not cut
    the beam material."""
    doc = active_doc(doc)
    beams = [global_shape(o) for o in robot_objects(doc) if o.Name.startswith("upper_beam")]
    out = {}
    for x in P.bolt_x:
        for y in P.hole_y:
            rod = G.cyl(9.0, (x, y, 600.0), (x, y, 720.0))
            v = sum(rod.common(b).Volume for b in beams if b.BoundBox.intersect(rod.BoundBox))
            if v > tol:
                out[str((x, y))] = round(v, 1)
    return out


MOVING = ("pan_yoke", "tilt_motor", "tilt_axle", "tilt_frame", "cam_vis", "cam_ir", "illum")


def check_poses(doc=None, tol=1.0):
    doc = active_doc(doc)
    fixed = [(o, global_shape(o)) for o in objects_of(doc, ROOT) if o.Name not in MOVING]
    out = {}
    for pan in P.PAN_POSES:
        for tilt in P.TILT_POSES:
            set_pose(pan, tilt, doc)
            mov = [(doc.getObject(n), global_shape(doc.getObject(n))) for n in MOVING]
            hits = _overlaps([(a, b) for a in mov for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
            if hits:
                out[str((pan, tilt))] = hits
    set_pose(0.0, 0.0, doc)
    return out


def check_steering(doc=None, tol=1.0):
    doc = active_doc(doc)
    out = {}
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    for st in (-P.robot_steer_deg, P.robot_steer_deg):
        set_steering(st, doc)
        rob = [(o, global_shape(o)) for o in robot_objects(doc) if o.Name.startswith(("FL", "FR"))]
        hits = _overlaps([(a, b) for a in mine for b in rob], tol)
        if hits:
            out[str(st)] = hits
    set_steering(0.0, doc)
    return out


# bought parts (kg, estimated from datasheets); the rest is steel or aluminium by volume
MASS_FIXED = {"horns": 3.2, "fixed_cams": 1.6, "beacon": 0.6, "mic": 0.1, "elec_box": 4.5, "antennas": 0.3,
              "pan_base": 2.5, "tilt_motor": 0.6, "cam_vis": 1.8, "cam_ir": 0.9, "illum": 0.8}
DENSITY = {"pan_yoke": P.alu, "tilt_frame": P.alu}


def mass_properties(doc=None):
    doc = active_doc(doc)
    m, c = 0.0, V(0, 0, 0)
    for o in objects_of(doc, ROOT):
        s = global_shape(o)
        mo = MASS_FIXED.get(o.Name, s.Volume * DENSITY.get(o.Name, P.steel))
        try:
            co = s.CenterOfMass if hasattr(s, "CenterOfMass") else s.BoundBox.Center
        except Exception:
            co = s.BoundBox.Center
        m += mo
        c += co * mo
    c = c * (1.0 / m)
    return {"kg": round(m, 1), "cg": (round(c.x), round(c.y), round(c.z))}


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    BP.set_camera(direction, target, height, up)
    Gui.updateGui()
    view = BP.set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def add_floor(doc):
    obj = doc.addObject("Part::Feature", "render_floor")
    obj.Shape = G.box_span((-1200.0, 1200.0), (-1200.0, 1200.0), (-30.0, 0.0))
    obj.ViewObject.ShapeColor = (0.72, 0.72, 0.70)
    obj.ViewObject.Transparency = 30
    return obj


def render_all():
    import FreeCADGui as Gui
    out = []
    doc = build(save=False, show_robot=True, step=False)
    set_pose(35.0, -15.0, doc)
    add_floor(doc)
    Gui.setActiveDocument(doc.Name)
    out.append(save_view("1_iso_front_on_robot.png", (-1.0, -1.2, -0.6), target=(0, 0, 1100), height=2900))
    set_pose(0.0, 0.0, doc)
    out.append(save_view("2_side.png", (1.0, 0.0, 0.0), target=(0, 0, 1150), height=2700))
    doc.removeObject("render_floor")
    set_robot_visible(False, doc)
    set_pose(-40.0, -20.0, doc)
    out.append(save_view("3_pan_tilt_head.png", (-1.0, -1.3, -0.5), target=(0, -300, 2150), height=700))
    set_pose(0.0, 0.0, doc)
    out.append(save_view("4_mast_rear.png", (0.8, 1.0, -0.4), target=(0, -300, 1300), height=1700))
    App.closeDocument(doc.Name)
    build()
    return out
