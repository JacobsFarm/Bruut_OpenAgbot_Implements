"""Model of the rotary tiller (power harrow idea) in the three-point hitch of the Bruut OpenAgbot (standard robot).

Mount, links, lift rods, implement frame (toolbar 60 x 60, A-mast) and its 2 gauge wheels are the three-point hitch's
(build_tph / tph_parts, imported); this file adds the rotor, hood, drive and flap behind the toolbar.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_pwh
    build_pwh.build()
    build_pwh.set_pose(25)                 # lower links up 25 degrees (transport)
    build_pwh.set_rotor(30)                # rotor angle (degrees)
    build_pwh.check_interference()         # must be empty
    build_pwh.check_poses()                # lift poses and rotor angles: empty
    build_pwh.ground_contact()
    build_pwh.mass_properties()
    build_pwh.render_all()
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import pwh_params as P
import pwh_parts as G
import tph_parts as TG
import build_tph as BT

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
DOC_NAME = "Power_Harrow"
SAVE_BASE = os.path.join(FOLDER, "Power_Harrow")
ROOT = "Power_harrow"

COLOR = dict(BT.COLOR)
COLOR.update({"tiller": (0.85, 0.15, 0.10), "blade": (0.30, 0.30, 0.33), "hood": (0.85, 0.15, 0.10),
              "motor": (0.12, 0.12, 0.13), "case": (0.85, 0.15, 0.10), "skirt": (0.08, 0.08, 0.08),
              "pin": (0.82, 0.84, 0.87)})


def add_shape(doc, parent, name, label, shape, color, visible=True):
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_implement(doc, parent, lift=P.lift_work):
    grp = BT.new_part(doc, parent, "Implement", "rotary_tiller_700", BT.implement_placement(lift))
    add_shape(doc, grp, "imp_frame", "toolbar_60x60_A_mast_gauge_arms_of_the_hitch", TG.imp_frame(), "implement")
    add_shape(doc, grp, "hitch_pins", "hitch_pins_D16_linch", TG.hitch_pins(), "zinc")
    add_shape(doc, grp, "gauge_wheels", "frame_gauge_wheels_D250x80_2x", TG.gauge_wheels(), "rubber")
    add_shape(doc, grp, "wheel_axles", "frame_gauge_wheel_axles_D20", TG.wheel_axles(), "zinc")
    add_shape(doc, grp, "pwh_brackets", "hood_brackets_10mm_2x", G.brackets(), "tiller")
    add_shape(doc, grp, "pwh_side_plates", "side_plates_5mm_skids", G.side_plates(), "tiller")
    add_shape(doc, grp, "pwh_hood", "hood_2mm_R218", G.hood(), "hood")
    add_shape(doc, grp, "pwh_skirt", "front_skirt_rubber_6mm", G.skirt(), "skirt")
    add_shape(doc, grp, "pwh_flap_hinge", "flap_hinge_rod_D16", G.flap_hinge(), "pin")
    add_shape(doc, grp, "pwh_flap", "rear_levelling_flap_4mm", G.flap(), "tiller")
    add_shape(doc, grp, "pwh_bearing", "rotor_bearing_left_UCFL", G.bearings(), "zinc")
    add_shape(doc, grp, "pwh_chain_case", "chain_case_right_1to1", G.chain_case(), "case")
    add_shape(doc, grp, "pwh_motor", "gearmotor_48V_1500W_i12", G.motor(), "motor")
    add_shape(doc, grp, "pwh_motor_bracket", "gearmotor_stand_6mm", G.motor_bracket(), "tiller")
    rot = BT.new_part(doc, grp, "pwh_Rotor", "rotor_turns_about_x")
    add_shape(doc, rot, "pwh_rotor_tube", "rotor_tube_D60x5_shaft_D40", G.rotor_tube(), "pin")
    add_shape(doc, rot, "pwh_flanges", "blade_flanges_D180_4x", G.flanges(), "blade")
    add_shape(doc, rot, "pwh_blades", "L_blades_60x7_16x", G.blades(), "blade")
    return grp


def build_into(doc, parent=None, lift=P.lift_work):
    root = BT.new_part(doc, parent, ROOT, "power_harrow_rotary_tiller_simple")
    BT.build_mount(doc, root)
    BT.build_links(doc, root, lift)
    BT.build_actuators(doc, root, lift)
    build_implement(doc, root, lift)
    return root


def set_pose(lift=P.lift_work, doc=None):
    BT.set_pose(lift, active_doc(doc))
    active_doc(doc).recompute()


def set_rotor(angle, doc=None):
    doc = active_doc(doc)
    doc.getObject("pwh_Rotor").Placement = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), angle),
                                                         V(0, P.rotor_y, P.rotor_z))
    doc.recompute()


global_shape = BT.global_shape
_overlaps = BT._overlaps


def build(save=True, show_robot=False, step=True, lift=P.lift_work):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Power harrow simple"
    doc.Comment = ("Generated by build_pwh.py from pwh_params.py (hitch and frame from three point hitch/simple). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BT.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, lift)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


_J = [("brackets", "hood"), ("side_plates", "hood"), ("skirt", "hood"), ("flap_hinge", "hood"), ("flap_hinge", "flap"),
      ("flap_hinge", "side_plates"), ("bearing", "side_plates"), ("chain_case", "side_plates"),
      ("motor", "chain_case"), ("motor", "motor_bracket"), ("motor_bracket", "hood"), ("motor_bracket", "chain_case"),
      ("rotor_tube", "flanges"), ("flanges", "blades"), ("rotor_tube", "bearing"), ("rotor_tube", "chain_case"),
      ("rotor_tube", "side_plates"), ("skirt", "side_plates")]
JOINTS = {("pwh_" + a, "pwh_" + b) for a, b in _J}


def _joint(a, b):
    if BT._joint(a, b):
        return True
    if (a, b) in JOINTS or (b, a) in JOINTS:
        return True
    for x, y in ((a, b), (b, a)):
        if x == "pwh_brackets" and y == "imp_frame":
            return True
    return False


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_poses(doc=None, tol=1.0):
    """Lift poses (implement against mount and robot) and rotor angles (rotor against the housing)."""
    doc = active_doc(doc)
    moving = objects_of(doc, "Implement")
    names = {o.Name for o in moving}
    fixed = [(o, global_shape(o)) for o in objects_of(doc, "Mount") + robot_objects(doc) if o.Name not in names]
    out = {}
    for lift in (-4.0, P.lift_work, 12.0, P.lift_transport):
        set_pose(lift, doc)
        mv = [(o, global_shape(o)) for o in moving]
        hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
        if hits:
            out["lift_%g" % lift] = hits
    set_pose(P.lift_work, doc)
    rotor = objects_of(doc, "pwh_Rotor")
    rn = {o.Name for o in rotor}
    housing = [(o, global_shape(o)) for o in moving if o.Name not in rn]
    for a in (0.0, 11.25, 33.75, 56.25, 78.75):
        set_rotor(a, doc)
        rv = [(o, global_shape(o)) for o in rotor]
        hits = _overlaps([(p, q) for p in rv for q in housing if not _joint(p[0].Name, q[0].Name)], tol)
        if hits:
            out["rotor_%g" % a] = hits
    set_rotor(0.0, doc)
    return out


def ground_contact(doc=None):
    doc = active_doc(doc)
    out = {}
    for lift in (P.lift_work, P.lift_transport):
        set_pose(lift, doc)
        out["lift_%g" % lift] = {n: round(global_shape(doc.getObject(n)).BoundBox.ZMin, 1)
                                 for n in ("pwh_blades", "pwh_side_plates", "pwh_flap", "gauge_wheels", "pwh_skirt")}
    set_pose(P.lift_work, doc)
    return out


MASS_FIXED = {"pwh_motor": P.motor_kg, "act_body_left": 2.6, "act_body_right": 2.6, "act_rod_left": 0.8,
              "act_rod_right": 0.8}
DENSITY = (("pwh_skirt", P.rubber), ("gauge_wheels", 0.6e-6), ("toolbar_caps", 0.95e-6), ("pwh_chain_case", 0.45 * P.steel))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    dens = P.steel
    for key, d in DENSITY:
        if key in obj.Name:
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Implement", "pwh_Rotor"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


set_camera = BT.set_camera


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_soil", "render_tilled")


def add_scene(doc):
    o = doc.addObject("Part::Feature", SCENE[0])
    o.Shape = G.soil(-4000.0, 1500.0)
    o.ViewObject.ShapeColor = (0.50, 0.38, 0.26)
    o = doc.addObject("Part::Feature", SCENE[1])
    o.Shape = G.tilled_strip(-4000.0, P.rotor_y - 150.0)
    o.ViewObject.ShapeColor = (0.36, 0.26, 0.17)


def render_all():
    out = []
    doc = build(save=False, show_robot=True, step=False)
    add_scene(doc)
    set_rotor(20.0, doc)
    out.append(save_view("1_iso_rear_tilling.png", (-1.0, 1.0, -0.6), target=(0, -1300, 350), height=2800))
    out.append(save_view("2_side_work.png", (1.0, 0.0, 0.0), target=(0, -1100, 450), height=2200))
    for n in SCENE:
        doc.removeObject(n)
    set_pose(P.lift_transport, doc)
    out.append(save_view("3_side_lifted.png", (1.0, 0.0, 0.0), target=(0, -1100, 500), height=2200))
    set_pose(P.lift_work, doc)
    set_robot_visible(False, doc)
    doc.getObject("pwh_hood").ViewObject.Transparency = 75
    doc.getObject("pwh_flap").ViewObject.Transparency = 75
    out.append(save_view("4_rotor_under_hood.png", (-0.9, 0.8, 0.5), target=(0, -1580, 150), height=1100))
    out.append(save_view("5_rear_drive.png", (0.35, 1.0, -0.35), target=(100, -1580, 300), height=1200))
    App.closeDocument(doc.Name)
    build()
    return out
