def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build_implement(doc, parent, lift=P.lift_work):
    grp = BT.new_part(doc, parent, "Implement", "precision_seeder_2_rows_500", BT.implement_placement(lift))
    add_shape(doc, grp, "imp_frame", "toolbar_60x60_A_mast_gauge_arms_of_the_hitch", TG.imp_frame(), "implement")
    add_shape(doc, grp, "hitch_pins", "hitch_pins_D16_linch", TG.hitch_pins(), "zinc")
    add_shape(doc, grp, "gauge_wheels", "frame_gauge_wheels_D250x80_2x", TG.gauge_wheels(), "rubber")
    add_shape(doc, grp, "wheel_axles", "frame_gauge_wheel_axles_D20", TG.wheel_axles(), "zinc")
    add_shape(doc, grp, "psd_blower", "vacuum_blower_24V", G.blower(), "motor")
    add_shape(doc, grp, "psd_vac_hoses", "vacuum_hoses_O38", G.vac_hoses(), "hose")
    for i, ux in enumerate(P.ROW_X):
        tag = "L" if ux < 0 else "R"
        ug = BT.new_part(doc, grp, "psd_Unit_" + tag, "seeding_unit_row_x%+d" % ux)
        for name, shape in G.unit(ux).items():
            add_shape(doc, ug, "psd_%s_%s" % (tag, name), "%s_%s" % (name, tag), shape, UNIT_COLOR[name])
    return grp


def build_into(doc, parent=None, lift=P.lift_work):
    root = BT.new_part(doc, parent, ROOT, "precision_seeder_simple")
    BT.build_mount(doc, root)
    BT.build_links(doc, root, lift)
    BT.build_actuators(doc, root, lift)
    build_implement(doc, root, lift)
    return root


def set_pose(lift=P.lift_work, doc=None):
    BT.set_pose(lift, active_doc(doc))
    active_doc(doc).recompute()


global_shape = BT.global_shape
_overlaps = BT._overlaps


def build(save=True, show_robot=False, step=True, lift=P.lift_work):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Precision seeder simple"
    doc.Comment = ("Generated by build_psd.py from psd_params.py (hitch and frame from three point hitch/simple). Robot "
                   "coordinates: x = right, y = driving direction (front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = BT.build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot, lift)
    if robot is not None:
        set_robot_visible(bool(show_robot), doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("no document %s open" % DOC_NAME)


def objects_of(doc, name):
    g = doc.getObject(name)
    return [o for o in g.OutListRecursive if o.TypeId == "Part::Feature"] if g else []


def robot_objects(doc):
    robot = doc.getObject("Robot")
    if robot is None:
        return []
    mine = {o.Name for o in objects_of(doc, ROOT)}
    return [o for o in robot.OutListRecursive if o.TypeId == "Part::Feature" and o.Name not in mine]


def set_robot_visible(visible, doc=None):
    doc = active_doc(doc)
    for o in robot_objects(doc):
        o.ViewObject.Visibility = visible


def export_step(doc, path):
    import Import
    objs = []
    for o in objects_of(doc, ROOT):
        f = doc.addObject("Part::Feature", "step_" + o.Name)
        f.Label = o.Label
        f.Shape = global_shape(o)
        objs.append(f)
    try:
        Import.export(objs, path)
    finally:
        for f in objs:
            doc.removeObject(f.Name)


UNIT_JOINTS = {("pins", "brackets"), ("pins", "links"), ("pins", "side_plates"), ("brackets", "links"),
               ("shank", "side_plates"), ("shank", "discs"), ("gauge_stubs", "gauge_wheels"), ("gauge_stubs", "side_plates"),
               ("press_arms", "side_plates"), ("press_axle", "press_wheel"), ("press_axle", "press_arms"),
               ("meter", "side_plates"), ("meter", "hopper"), ("meter", "stepper"), ("stepper", "side_plates"),
               ("seed_tube", "meter"), ("seed_sensor", "seed_tube"), ("hopper", "side_plates"), ("links", "side_plates")}


def _joint(a, b):
    if BT._joint(a, b):
        return True
    for x, y in ((a, b), (b, a)):
        if x.startswith("psd_") and y.startswith("psd_") and x[4] == y[4] and x[5] == "_" and y[5] == "_":
            if (x[6:], y[6:]) in UNIT_JOINTS:
                return True
        if x == "psd_vac_hoses" and (y.endswith("_meter") or y.endswith("_side_plates") or y == "psd_blower"):
            return True
        if x.endswith("_brackets") and y == "imp_frame":
            return True
    return False


def check_interference(doc=None, tol=1.0):
    doc = active_doc(doc)
    mine = [(o, global_shape(o)) for o in objects_of(doc, ROOT)]
    robot = [(o, global_shape(o)) for o in robot_objects(doc)]
    pairs = [(mine[i], mine[j]) for i in range(len(mine)) for j in range(i + 1, len(mine))
             if not _joint(mine[i][0].Name, mine[j][0].Name)]
    pairs += [(a, b) for a in mine for b in robot if not _joint(a[0].Name, b[0].Name)]
    return _overlaps(pairs, tol)


def check_poses(doc=None, tol=1.0):
    doc = active_doc(doc)
    moving = objects_of(doc, "Implement")
    names = {o.Name for o in moving}
    fixed = [(o, global_shape(o)) for o in objects_of(doc, "Mount") + robot_objects(doc) if o.Name not in names]
    out = {}
    for lift in (-4.0, P.lift_work, 12.0, P.lift_transport):
        set_pose(lift, doc)
        mv = [(o, global_shape(o)) for o in moving]
        hits = _overlaps([(a, b) for a in mv for b in fixed if not _joint(a[0].Name, b[0].Name)], tol)
        if hits:
            out[str(lift)] = hits
    set_pose(P.lift_work, doc)
    return out


def ground_contact(doc=None):
    doc = active_doc(doc)
    out = {}
    for lift in (P.lift_work, P.lift_transport):
        set_pose(lift, doc)
        out["lift_%g" % lift] = {n: round(global_shape(doc.getObject(n)).BoundBox.ZMin, 1)
                                 for n in ("psd_R_discs", "psd_R_gauge_wheels", "psd_R_press_wheel", "gauge_wheels")}
    set_pose(P.lift_work, doc)
    return out


MASS_FIXED = {"psd_blower": 3.0, "act_body_left": 2.6, "act_body_right": 2.6, "act_rod_left": 0.8, "act_rod_right": 0.8}
DENSITY = (("_side_plates", P.alu), ("_brackets", P.alu), ("_press_arms", P.alu), ("_links", P.alu), ("_shank", P.alu),
           ("_hopper", P.pe), ("_gauge_wheels", 0.5e-6), ("_press_wheel", P.rubber), ("gauge_wheels", 0.6e-6),
           ("psd_vac_hoses", 1.0e-6), ("_seed_tube", 1.0e-6), ("_seed_sensor", 1.0e-6), ("_meter", 0.35 * P.alu),
           ("toolbar_caps", P.pe))


def _mass_cg(obj):
    shape = global_shape(obj)
    solids = shape.Solids or [shape]
    vol = sum(s.Volume for s in solids)
    cg = V(0, 0, 0)
    for s in solids:
        cg += s.CenterOfMass * s.Volume
    cg = cg * (1.0 / vol) if vol > 0 else shape.BoundBox.Center
    if obj.Name in MASS_FIXED:
        return MASS_FIXED[obj.Name], cg
    if obj.Name.endswith("_stepper"):
        return 0.6, cg
    dens = P.steel
    for key, d in DENSITY:
        if key in obj.Name:
            dens = d
    return vol * dens, cg


def mass_properties(doc=None):
    doc = active_doc(doc)
    out = {}
    for name in (ROOT, "Mount", "Implement", "psd_Unit_R"):
        m, c = 0.0, V(0, 0, 0)
        for o in objects_of(doc, name):
            mo, co = _mass_cg(o)
            m += mo
            c += co * mo
        c = c * (1.0 / m) if m > 0 else c
        out[name.lower() + "_kg"] = round(m, 1)
        out[name.lower() + "_cg"] = (round(c.x), round(c.y), round(c.z))
    return out


def size(doc=None):
    doc = active_doc(doc)
    bb = None
    for o in objects_of(doc, ROOT):
        b = global_shape(o).BoundBox
        bb = b if bb is None else bb.united(b)
    return (round(bb.XLength), round(bb.YLength), round(bb.ZLength)), (round(bb.XMin), round(bb.YMin), round(bb.ZMin))


set_camera = BT.set_camera


def save_view(name, direction, target=None, height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    Gui.updateGui()
    set_camera(direction, target, height, up)
    Gui.updateGui()
    view = set_camera(direction, target, height, up)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


SCENE = ("render_bed", "render_furrows", "render_seeds")


def add_scene(doc):
    y0, y1 = -5000.0, 1500.0
    for name, shape, color in ((SCENE[0], G.seedbed(y0, y1), (0.42, 0.31, 0.21)),
                               (SCENE[1], G.furrows(y0, P.opener_y), (0.30, 0.22, 0.15)),
                               (SCENE[2], G.seed_flags(y0, P.opener_y - 100.0), (0.95, 0.30, 0.20))):
        o = doc.addObject("Part::Feature", name)
        o.Shape = shape
        o.ViewObject.ShapeColor = color


