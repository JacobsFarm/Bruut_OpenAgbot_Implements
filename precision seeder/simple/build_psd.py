"""Model of the precision seeder in the three-point hitch of the Bruut OpenAgbot (standard robot).

Mount, links, lift rods, implement frame (toolbar 60 x 60, A-mast) and its 2 gauge wheels are the three-point hitch's
(build_tph / tph_parts, imported); this file adds 2 seeding units and the vacuum blower.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_psd
    build_psd.build()
    build_psd.set_pose(25)                 # lower links up 25 degrees (transport)
    build_psd.check_interference()         # must be empty
    build_psd.check_poses()                # lift poses: empty
    build_psd.ground_contact()
    build_psd.mass_properties()
    build_psd.render_all()
"""
