    for n in SCENE:
        doc.removeObject(n)
    set_pose(P.lift_transport, doc)
    out.append(save_view("3_side_lifted.png", (1.0, 0.0, 0.0), target=(0, -1100, 500), height=2200))
    set_pose(P.lift_work, doc)
    set_robot_visible(False, doc)
    out.append(save_view("4_unit_detail.png", (1.0, 0.75, -0.35), target=(250, -1750, 330), height=900))
    for o in objects_of(doc, "psd_Unit_R"):
        if o.Name.endswith(("_hopper", "_side_plates", "_gauge_wheels")):
            o.ViewObject.Transparency = 70
