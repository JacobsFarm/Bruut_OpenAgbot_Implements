def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, label, shape, color, visible=True):
    if isinstance(shape, (list, tuple)):
        shape = Part.makeCompound(list(shape))
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    view = obj.ViewObject
    if view is not None:
        view.ShapeColor = COLOR[color]
        view.Visibility = visible
    return obj







def build_into(doc, parent=None):
    root = new_part(doc, parent, ROOT, "biocontrol_spreader_simple")
    m = new_part(doc, root, "Mount", "mount_bearer_arms")
    add_shape(doc, m, "bearer", "bearer_40x40x3", G.bearer(), "frame")
    add_shape(doc, m, "bearer_bolts", "bearer_bolts_M10_4x", G.bearer_bolts(), "zinc")
    add_shape(doc, m, "arms", "hopper_arms_30x6_rings", G.arms_and_rings(), "frame")
    add_shape(doc, m, "controller", "driver_box", G.controller(), "box")
    h = new_part(doc, root, "Hoppers", "hoppers_metering")
    add_shape(doc, h, "hoppers", "hoppers_PE_5l_2x", G.hoppers(), "hopper")
    add_shape(doc, h, "agitators", "agitator_motors_2x", G.agitator_motors(), "motor")
    add_shape(doc, h, "meters", "metering_wheels_NEMA17_2x", G.meters(), "motor")
    a = new_part(doc, root, "Air", "blower_and_lines")
    fan, motor = G.fan()
    add_shape(doc, a, "fan", "blower_housing_D200", fan, "box")
    add_shape(doc, a, "fan_motor", "blower_motor_24V_60W", motor, "motor")
    add_shape(doc, a, "manifold", "air_pipe_D40", G.manifold(), "pipe")
    add_shape(doc, a, "venturis", "venturis_2x", G.venturis(), "pipe")
    add_shape(doc, a, "hoses", "hoses_D40_2x", G.hoses(), "hose")
    add_shape(doc, a, "nozzles", "deflector_nozzles_2x", G.nozzles(), "zinc")
    return root


def build_robot(doc, steer=0.0):
    if AGBOT_FOLDER not in sys.path:
        sys.path.insert(0, AGBOT_FOLDER)
    import build_agbot as BA
    robot = BA.new_part(doc, None, "Robot", "Bruut_OpenAgbot_robot")
    BA.build_chassis(doc, robot)
    shapes = BA.make_shapes()
    for tag in ("RL", "RR", "FL", "FR"):
        BA.build_wheel_unit(doc, robot, tag, shapes, steer if tag in ("FL", "FR") else 0.0)
    return robot


def set_steering(deg, doc=None):
    doc = active_doc(doc)
    for n in ("FL_steered", "FR_steered"):
        o = doc.getObject(n)
        if o is not None:
            pl = o.Placement
            o.Placement = App.Placement(pl.Base, App.Rotation(V(0, 0, 1), deg))


def build(save=True, show_robot=False, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Biocontrol spreader simple"
    doc.Comment = ("Generated by build_bcs.py from bcs_params.py. Robot coordinates: x = right, y = driving direction "
                   "(front = +y), z = up, ground = z 0.")
    robot = None
    try:
        robot = build_robot(doc)
    except Exception as exc:
        print("robot model not loaded:", exc)
    build_into(doc, robot)
    if robot is not None and not show_robot:
        set_robot_visible(False, doc)
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


