"""Model of the biological-control spreader on the Bruut OpenAgbot (standard robot).

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_bcs
    build_bcs.build()                      # saves FCStd and STEP
    build_bcs.check_interference()         # overlap (must be empty)
    build_bcs.check_poses()                # front wheels steered +-30 (must be empty)
    build_bcs.mass_properties()
    build_bcs.render_all()                 # all images in previews/
"""
import os
import sys

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import bcs_params as P
import bcs_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
AGBOT_FOLDER = os.path.join(os.path.dirname(os.path.dirname(FOLDER)), "agbots", "agbot design")
DOC_NAME = "Biocontrol_Spreader"
SAVE_BASE = os.path.join(FOLDER, "Biocontrol_Spreader")
ROOT = "Biocontrol_spreader"

COLOR = {
    "frame": (0.93, 0.42, 0.08),
    "zinc": (0.82, 0.84, 0.87),
    "hopper": (0.92, 0.92, 0.85),
    "motor": (0.25, 0.26, 0.28),
    "box": (0.20, 0.45, 0.25),
    "pipe": (0.60, 0.62, 0.65),
    "hose": (0.10, 0.10, 0.10),
}


